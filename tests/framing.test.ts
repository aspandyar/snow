import { describe, expect, it } from 'vitest'

import { сцена } from '@/lib/config'
import { полеЗренияПоКадру } from '@/lib/camera/framing'

/** Горизонтальный охват в градусах — то, ради чего вся подгонка. */
function охват(полеЗрения: number, отношение: number): number {
  const тангенс = Math.tan((полеЗрения * Math.PI) / 360) * отношение
  return (360 / Math.PI) * Math.atan(тангенс)
}

const ОПОРНОЕ = 16 / 9
const БАЗОВОЕ = 45
const ПРЕДЕЛ = 70

describe('поле зрения по форме окна', () => {
  it('на опорном отношении не меняется вовсе', () => {
    expect(полеЗренияПоКадру(БАЗОВОЕ, ОПОРНОЕ, ОПОРНОЕ, ПРЕДЕЛ)).toBe(БАЗОВОЕ)
  })

  it('на широком окне не сужается', () => {
    // Сужать на широком экране значило бы обрезать то, ради чего его туда
    // и поставили.
    expect(полеЗренияПоКадру(БАЗОВОЕ, ОПОРНОЕ, 2.4, ПРЕДЕЛ)).toBe(БАЗОВОЕ)
  })

  it('на узком окне расширяется', () => {
    expect(полеЗренияПоКадру(БАЗОВОЕ, ОПОРНОЕ, 375 / 812, ПРЕДЕЛ)).toBeGreaterThan(БАЗОВОЕ)
  })

  it('никогда не выходит за предел', () => {
    // Иначе на вытянутом экране получается рыбий глаз: прямые выгибаются,
    // сфера уезжает точкой.
    for (const отношение of [0.2, 0.35, 0.46, 0.6, 0.9]) {
      expect(полеЗренияПоКадру(БАЗОВОЕ, ОПОРНОЕ, отношение, ПРЕДЕЛ)).toBeLessThanOrEqual(ПРЕДЕЛ)
    }
  })

  it('пока предел не достигнут, горизонтальный охват держится прежним', () => {
    // Это и есть смысл подгонки: вертикаль меняется, горизонталь стоит.
    const опорный = охват(БАЗОВОЕ, ОПОРНОЕ)
    for (const отношение of [1.6, 1.4, 1.2, 1.0]) {
      const поле = полеЗренияПоКадру(БАЗОВОЕ, ОПОРНОЕ, отношение, ПРЕДЕЛ)
      if (поле >= ПРЕДЕЛ) continue
      expect(охват(поле, отношение)).toBeCloseTo(опорный, 6)
    }
  })

  it('на телефоне охват шире, чем был бы без подгонки', () => {
    // Проверка того самого дефекта: на 375×812 без подгонки в кадр
    // попадает вдвое меньше горизонта.
    const отношение = 375 / 812
    const без = охват(БАЗОВОЕ, отношение)
    const с = охват(полеЗренияПоКадру(БАЗОВОЕ, ОПОРНОЕ, отношение, ПРЕДЕЛ), отношение)
    expect(с).toBeGreaterThan(без * 1.4)
  })

  it('монотонна: чем у́же окно, тем шире поле', () => {
    const отношения = [1.8, 1.5, 1.2, 0.9, 0.7, 0.5]
    const поля = отношения.map((о) => полеЗренияПоКадру(БАЗОВОЕ, ОПОРНОЕ, о, ПРЕДЕЛ))
    for (let i = 1; i < поля.length; i++) {
      expect(поля[i]).toBeGreaterThanOrEqual(поля[i - 1])
    }
  })

  it('настройки сцены не противоречат друг другу', () => {
    // Предел обязан быть больше базового поля зрения, иначе подгонка
    // молча не работает вовсе.
    expect(сцена.камера.пределПоляЗрения).toBeGreaterThan(сцена.камера.полеЗрения)
  })
})
