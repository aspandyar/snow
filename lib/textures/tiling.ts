/** Сколько раз текстура укладывается вдоль стороны поверхности.
 *
 *  Метраж на повтор — вторая вещь, которую нужно проверять, когда
 *  «текстуры 4K, а всё равно мыло». Тайл в девять метров теряет детали
 *  при любом разрешении: один пиксель текстуры растягивается на
 *  несколько пикселей кадра, и добавлять пиксели в исходник бесполезно. */
export function числоПовторов(сторона: number, метраж: number): number {
  if (метраж <= 0) {
    throw new Error('метраж на повтор должен быть положительным')
  }
  return сторона / метраж
}
