'use client'

import { useMemo } from 'react'
import { useFrame, useThree } from '@react-three/fiber'
import { Vector3 } from 'three'

import { прокрутка } from '@/lib/config'
import { путьЦели, путьПозиции } from '@/lib/scroll/path'
import { конецСцены, прогрессСцены } from '@/lib/transition/flash'
import { useХранилищеПрокрутки } from '@/lib/scroll/store'

/** Камера, ведомая прокруткой.
 *
 *  Каждый кадр читает прогресс прокрутки из хранилища и берёт по нему
 *  точку на двух кривых Катмулла-Рома: одна даёт положение камеры,
 *  другая — точку, куда камера смотрит. Обе кривые и точки траектории
 *  заданы в lib/config.ts (раздел траектория) — там же объяснено, почему
 *  выбраны именно эти точки и почему путь не задевает снег и не
 *  выглядывает за край равнины.
 *
 *  Компонент ничего не рендерит: камера уже создана Canvas'ом в
 *  SceneCanvas.tsx через проп camera={{ position, fov }} — этот же
 *  проп задаёт исходное положение, совпадающее с первой точкой
 *  траектории, так что до первого кадра useFrame картинка уже верная. */
export default function CameraRig() {
  const { camera } = useThree()

  // Векторы под результат getPointAt выделяются один раз вне кадра, а не
  // создаются заново на каждый вызов: сборщик мусора останавливает кадр
  // в непредсказуемый момент, а useFrame вызывается шестьдесят раз в
  // секунду.
  const позиция = useMemo(() => new Vector3(), [])
  const цель = useMemo(() => new Vector3(), [])

  // Порог, после которого лендинг начинает наезжать на кадр. Камера
  // обязана доиграть весь путь ДО него, иначе самое интересное пройдёт за
  // страницей — так и было, пока это не связали формулой.
  const порог = useMemo(
    () =>
      конецСцены(прокрутка.доляСцены, прокрутка.нахлёстВЭкранах, прокрутка.экранов),
    [],
  )

  // Приоритет по умолчанию (второй аргумент не передаётся). Любое
  // значение больше нуля отключает в R3F автоматическую отрисовку кадра,
  // и экран чернеет без единой ошибки в консоли.
  useFrame(() => {
    // Через getState(), а не через хук: хук подписал бы этот компонент
    // на изменения и заставил бы его перерисовываться на каждый пиксель
    // прокрутки. Здесь чтение целиком императивное, как и весь useFrame.
    const { прогресс } = useХранилищеПрокрутки.getState()
    // Не сырой прогресс прокрутки, а прогресс СЦЕНЫ: путь укладывается в
    // отрезок до порога нахлёста и дальше стоит. Последняя треть прокрутки
    // отдана вспышке и передаче кадра лендингу.
    const ход = прогрессСцены(прогресс, порог)

    // getPointAt, а НЕ getPoint: getPointAt идёт по длине дуги, и камера
    // движется равномерно. getPoint идёт по параметру между опорными
    // точками, и скорость скачет от сегмента к сегменту — на глаз это
    // читается как рывки, причину которых потом ищут в прокрутке, а не
    // в кривой.
    путьПозиции.getPointAt(ход, позиция)
    путьЦели.getPointAt(ход, цель)

    camera.position.copy(позиция)
    camera.lookAt(цель)
  })

  return null
}
