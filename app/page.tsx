import Landing from '@/components/landing/Landing'
import SceneMount from '@/components/scene/SceneMount'
import { прокрутка } from '@/lib/config'

export default function Page() {
  return (
    <main className="w-full">
      {/* Блок высотой в несколько экранов даёт прокрутке путь: пока он
          прокручивается, толкатель (ScrollDriver.tsx) считает прогресс
          от нуля до единицы. Высота — calc, а не Tailwind-класс:
          прокрутка.экранов приходит из конфига, а не задаётся здесь
          числом. 100dvh — не число проекта, а единица измерения: один
          экран по определению. dvh, а не vh, — на мобильных адресная
          строка появляется и исчезает на ходу, и vh давал бы скачок
          высоты блока прямо во время прокрутки. */}
      <div
        className="relative w-full"
        style={{ height: `calc(${прокрутка.экранов} * 100dvh)` }}
      >
        {/* Липкий контейнер держит холст на экране, пока блок вокруг
            прокручивается: без sticky холст проехал бы вместе со
            страницей за первый же экран. */}
        <div className="sticky top-0 h-dvh w-full">
          <SceneMount />
        </div>
      </div>
      {/* Лендинг наезжает на кадр отрицательным верхним отступом в
          прокрутка.нахлёстВЭкранах экранов. Это не украшение: наезд —
          часть перехода, кадр к этому моменту уже залит цветом подложки,
          и страница выезжает будто из света. Связь наезда с моментом,
          когда сцена доигрывает, держится формулой — см. конецСцены. */}
      {/* relative + z-10 обязательны, а не для красоты.
          Холст сцены лежит в липком контейнере, то есть в
          ПОЗИЦИОНИРОВАННОМ элементе, а позиционированные рисуются позже
          обычных блоков — независимо от порядка в разметке. Без своего
          позиционирования лендинг оказывается ПОД холстом на всём
          нахлёсте.
          Ловится это не сразу: элементы с прозрачностью меньше единицы
          образуют собственный контекст наложения и всплывают вместе с
          позиционированными. На экране получалось, что подписи и сноски
          видны, а заголовки и абзацы — нет. */}
      <div
        className="relative z-10"
        style={{ marginTop: `calc(${прокрутка.нахлёстВЭкранах} * -100dvh)` }}
      >
        <Landing />
      </div>
    </main>
  )
}
