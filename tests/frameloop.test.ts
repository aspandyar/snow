import { describe, expect, it } from 'vitest'

import { режимКадров, создатьПереключательКадров } from '@/lib/scroll/frameloop'

const ПУТЬ = 2700

describe('режим кадров', () => {
  it('кадры идут, пока сцена видна, и стоят, когда лендинг её закрыл', () => {
    expect(режимКадров(0, ПУТЬ)).toBe('always')
    expect(режимКадров(ПУТЬ - 1, ПУТЬ)).toBe('always')
    // Ровно на отметке лендинг встаёт вровень с верхом окна и закрывает
    // кадр целиком — считать дальше нечего.
    expect(режимКадров(ПУТЬ, ПУТЬ)).toBe('never')
    expect(режимКадров(ПУТЬ * 10, ПУТЬ)).toBe('never')
  })

  it('вырожденное окно НЕ останавливает кадры', () => {
    // Нулевая высота окна даёт нулевой путь, и «сдвиг ≥ пути» стало бы
    // истиной при самом первом вызове: холст замёрз бы навсегда, ещё до
    // того как зритель что-нибудь прокрутил. Такое окно встречается
    // взаправду — вкладка, которую ещё не разложили по месту, отдаёт
    // innerHeight равный нулю.
    expect(режимКадров(0, 0)).toBe('always')
    expect(режимКадров(0, -100)).toBe('always')
  })
})

describe('переключатель кадров', () => {
  it('трогает R3F только на пересечении, а не на каждом событии', () => {
    // Главное свойство. Событие прокрутки приходит десятки раз в секунду,
    // а setFrameloop у R3F не бесплатен: он ОСТАНАВЛИВАЕТ И ЗАВОДИТ ЗАНОВО
    // часы сцены. Дёрганный каждым событием, он обнуляет и время сцены, и
    // шаг кадра — ровно во время прокрутки, когда они и нужны.
    const применения: string[] = []
    const переключить = создатьПереключательКадров((р) => применения.push(р))

    for (let сдвиг = 0; сдвиг < ПУТЬ; сдвиг += 10) переключить(сдвиг, ПУТЬ)

    expect(применения).toEqual(['always'])
  })

  it('первый вызов задаёт режим, даже если он совпал с ожидаемым', () => {
    // R3F заводится в режиме 'always', но полагаться на это нельзя:
    // компонент могли смонтировать на уже прокрученной странице.
    const применения: string[] = []
    const переключить = создатьПереключательКадров((р) => применения.push(р))
    переключить(ПУТЬ * 2, ПУТЬ)
    expect(применения).toEqual(['never'])
  })

  it('применяет ровно столько раз, сколько было пересечений', () => {
    const применения: string[] = []
    const переключить = создатьПереключательКадров((р) => применения.push(р))

    переключить(0, ПУТЬ)
    переключить(100, ПУТЬ)
    переключить(ПУТЬ + 50, ПУТЬ)
    переключить(ПУТЬ + 400, ПУТЬ)
    переключить(ПУТЬ - 1, ПУТЬ)
    переключить(0, ПУТЬ)

    expect(применения).toEqual(['always', 'never', 'always'])
  })
})
