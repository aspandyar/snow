import { create } from 'zustand'

/** Хранилище прогресса прокрутки: одно поле и установщик, ничего лишнего.
 *
 *  ВАЖНО: внутри кадра (useFrame) читать его нужно через
 *  `useХранилищеПрокрутки.getState()`, а НЕ вызовом хука. Вызов хука
 *  подписал бы компонент сцены на изменения и заставил бы его
 *  перерисовываться на каждый пиксель прокрутки — при частоте кадра это
 *  сцену и положит. Хук уместен только там, где нужна настоящая реакция
 *  React на изменение (перерисовка DOM-разметки вне холста), а внутри
 *  сцены такого места нет: там всё читается императивно в useFrame. */
interface ХранилищеПрокрутки {
  /** Прогресс прокрутки, от 0 до 1. Считается толкателем
   *  (ScrollDriver.tsx) чистой функцией прогрессПрокрутки из
   *  lib/scroll/progress.ts. */
  прогресс: number

  /** Установщик прогресса. Единственный способ менять поле извне. */
  задатьПрогресс: (прогресс: number) => void
}

export const useХранилищеПрокрутки = create<ХранилищеПрокрутки>((set) => ({
  прогресс: 0,
  задатьПрогресс: (прогресс) => set({ прогресс }),
}))
