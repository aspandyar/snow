/** Режим отрисовки R3F: кадры идут или кадры стоят. */
export type РежимКадров = 'always' | 'never'

/** Нужны ли кадры при таком положении прокрутки.
 *
 *  Считать нечего, когда лендинг закрыл холст целиком: пятьсот кирпичей,
 *  снег и цепочка постобработки продолжали бы работать в никуда, пока
 *  зритель читает текст.
 *
 *  Строго больше или равно: ровно на этой отметке лендинг встаёт вровень
 *  с верхом окна.
 *
 *  ВЫРОЖДЕННЫЙ ПУТЬ — отдельный случай, и не теоретический. Путь
 *  считается из высоты окна, а вкладка, которую браузер ещё не разложил
 *  по месту, отдаёт нулевую высоту: «сдвиг ≥ пути» стало бы истиной при
 *  самом первом вызове, и холст замёрз бы навсегда, ещё до того как
 *  зритель что-нибудь прокрутил. */
export function режимКадров(сдвиг: number, путь: number): РежимКадров {
  if (путь <= 0) return 'always'
  return сдвиг >= путь ? 'never' : 'always'
}

/** Переключатель, который трогает R3F ТОЛЬКО на пересечении отметки.
 *
 *  Зачем помнить прошлый режим, вместо того чтобы просто задавать нужный
 *  каждый раз. `setFrameloop` у R3F не безобидная установка поля: он
 *  останавливает часы сцены, обнуляет накопленное время и заводит их
 *  заново. Событие прокрутки приходит десятки раз в секунду — и каждое
 *  такое «задать тот же самый режим» сбрасывало время сцены в ноль, а шаг
 *  кадра превращало во время, прошедшее с прошлого события, а не с
 *  прошлого кадра.
 *
 *  Последствия видны глазами ровно там, где обиднее всего: во время
 *  прокрутки. Снег замирает — он анимируется по накопленному времени, а
 *  оно всё время возвращается к нулю. Подтяжка кирпичей под курсором
 *  стоит — ей нужен честный шаг, а он схлопывается почти в ноль. Сцена
 *  выглядит показом слайдов именно тогда, когда зритель ею управляет.
 *
 *  Сам R3F внутри защищается точно так же — сравнивает с текущим режимом
 *  прежде чем вызвать (см. обработку свойства frameloop у Canvas). Здесь
 *  та же защита, потому что вызов идёт мимо него.
 *
 *  Первый вызов применяет режим ВСЕГДА, даже если он совпал с
 *  ожидаемым: полагаться на то, что R3F завёлся в 'always', нельзя —
 *  компонент могли смонтировать на уже прокрученной странице. */
export function создатьПереключательКадров(задать: (режим: РежимКадров) => void) {
  let текущий: РежимКадров | null = null

  return (сдвиг: number, путь: number) => {
    const следующий = режимКадров(сдвиг, путь)
    if (следующий === текущий) return
    текущий = следующий
    задать(следующий)
  }
}
