import { Matrix4, Quaternion, Vector3 } from 'three'

/** Параметры раскладки. Передаются аргументом, а не читаются из конфига:
 *  иначе функцию нельзя протестировать независимо от настроек сцены. */
export type ПараметрыРаскладки = {
  радиус: number
  колец: number
  коэффициент: number
  толщина: number
  шов: number
  смещениеВразбежку: number
}

/** Широта середины кольца, радианы, от северного полюса.
 *
 *  Именно середины. На границе широта нулевого кольца равна нулю, нормаль
 *  совпадает с мировой вертикалью, и векторное произведение для касательной
 *  вырождается в нулевой вектор — базис рассыпается, кирпичи встают как
 *  попало. Полшага сдвига убирают вырождение при любом числе колец. */
export function широтаКольца(колец: number, кольцо: number): number {
  return ((кольцо + 0.5) * Math.PI) / колец
}

/** Сколько кирпичей в кольце.
 *
 *  Синус широты здесь не для красоты: длина кольца равна 2πR·sinθ, и при
 *  делении на это количество синусы сокращаются — ширина кирпича выходит
 *  одинаковой от полюса до экватора. Без синуса кирпичи у полюсов
 *  сплющились бы в иглы.
 *
 *  Единица снизу нужна на случай малого числа колец: округление до нуля
 *  оставило бы кольцо пустым, и в сфере появилась бы сквозная дыра. */
export function количествоВКольце(
  п: Pick<ПараметрыРаскладки, 'колец' | 'коэффициент'>,
  кольцо: number,
): number {
  const широта = широтаКольца(п.колец, кольцо)
  return Math.max(1, Math.round(п.коэффициент * п.колец * Math.sin(широта)))
}

export type Кирпич = {
  позиция: Vector3
  кватернион: Quaternion
  масштаб: Vector3
  нормаль: Vector3
  кольцо: number
  номерВКольце: number
}

const ВЕРТИКАЛЬ = new Vector3(0, 1, 0)

export function разложитьКирпичи(п: ПараметрыРаскладки): Кирпич[] {
  const кирпичи: Кирпич[] = []
  const радиусЦентров = п.радиус - п.толщина / 2

  for (let кольцо = 0; кольцо < п.колец; кольцо++) {
    const широта = широтаКольца(п.колец, кольцо)
    const количество = количествоВКольце(п, кольцо)

    for (let номер = 0; номер < количество; номер++) {
      const долгота = (номер * 2 * Math.PI) / количество

      const нормаль = new Vector3(
        Math.sin(широта) * Math.cos(долгота),
        Math.cos(широта),
        Math.sin(широта) * Math.sin(долгота),
      )

      // Полный базис из трёх осей, а не поворот «из вектора в вектор».
      // Поворот между двумя векторами оставляет вращение вокруг нормали
      // незакреплённым: сфера соберётся, но кирпичи будут стоять пьяно.
      // Это самая коварная из ошибок — она проявляется не сразу.
      const касательная = new Vector3().crossVectors(ВЕРТИКАЛЬ, нормаль).normalize()
      const меридиан = new Vector3().crossVectors(нормаль, касательная)

      // Порядок столбцов задаёт соответствие локальных осей геометрии:
      // X вдоль кольца (ширина), Y вдоль меридиана (высота), Z по нормали
      // (толщина). Базис правосторонний: касательная × меридиан = нормаль.
      const кватернион = new Quaternion().setFromRotationMatrix(
        new Matrix4().makeBasis(касательная, меридиан, нормаль),
      )

      кирпичи.push({
        позиция: нормаль.clone().multiplyScalar(радиусЦентров),
        кватернион,
        масштаб: new Vector3(1, 1, 1),
        нормаль,
        кольцо,
        номерВКольце: номер,
      })
    }
  }

  return кирпичи
}
