import { Quaternion, Vector3 } from 'three'

import { сглаженныйПереход } from '@/lib/hover/displacement'

/** Ось проёма: направление ОТ центра сферы К точке, где в оболочку
 *  входит камера.
 *
 *  Приходит противоположным направлению входа (оно смотрит от камеры к
 *  центру), поэтому знак меняется. */
export function осьПроёма(вход: Vector3): Vector3 {
  return вход.clone().negate().normalize()
}

/** Угол между нормалью кирпича и осью проёма, радианы.
 *
 *  Это единственная величина, по которой кирпич относится к проёму или
 *  остаётся в неподвижной кладке. Скалярное произведение зажимается: у
 *  нормализованных векторов оно и так лежит в [−1, 1], но накопленная
 *  погрешность даёт 1.0000000002, а acos от такого возвращает NaN — и
 *  кирпич улетает в никуда без единой ошибки в консоли. */
export function уголОтОси(нормаль: Vector3, ось: Vector3): number {
  return Math.acos(Math.min(1, Math.max(-1, нормаль.dot(ось))))
}

/** Доля участия кирпича в раскрытии: 1 у самой оси, 0 на краю зоны и
 *  дальше.
 *
 *  Линейная, а не сглаженная, и это важно. Сглаженный переход имеет
 *  нулевую производную на концах, то есть у самой оси все кирпичи
 *  расходились бы ОДИНАКОВО и оставались бы сбитой в кучу пробкой прямо
 *  посреди проёма. Линейный вес отодвигает ближний кирпич дальше
 *  соседнего ровно настолько, чтобы порядок колец сохранился, а дыра
 *  раскрылась. */
export function весКирпича(угол: number, угловойРадиусЗоны: number): number {
  if (угол >= угловойРадиусЗоны) return 0
  return 1 - угол / угловойРадиусЗоны
}

/** На сколько радиан кирпич отъезжает ОТ оси проёма по своему меридиану.
 *
 *  Отображение углов получается такое: угол' = проём + угол·(1 − проём/зона).
 *  Оно строго возрастает, пока проём меньше зоны, — значит кирпичи не
 *  перескакивают друг через друга и кольца не выворачиваются наизнанку.
 *  Кирпич у самой оси уезжает на весь угловой радиус проёма, кирпич на
 *  краю зоны не двигается вовсе. */
export function отъездОтОси(
  угол: number,
  угловойРадиусЗоны: number,
  угловойРадиусПроёма: number,
): number {
  return угловойРадиусПроёма * весКирпича(угол, угловойРадиусЗоны)
}

/** На сколько метров кирпич приподнимается над оболочкой.
 *
 *  Без подъёма механика не работает. Кирпичи, отъезжая к краю проёма,
 *  СГУЩАЮТСЯ по меридиану: шаг между кольцами сжимается в
 *  (1 − проём/зона) раз, и при рабочих числах это вдвое. Кирпичи высотой
 *  0.67 м оказались бы в 0.37 м друг от друга, то есть внутри соседа.
 *
 *  Подъём разводит их по радиусу: чем ближе кирпич был к оси, тем выше
 *  он всплывает, и вокруг проёма вырастает воронка. Сгущение никуда не
 *  девается, но происходит уже в разных слоях. */
export function подъёмКирпича(
  угол: number,
  угловойРадиусЗоны: number,
  максПодъём: number,
): number {
  return максПодъём * весКирпича(угол, угловойРадиусЗоны)
}

/** Ось, вокруг которой кирпич поворачивается, отъезжая от оси проёма.
 *
 *  Поворот идёт по меридиану, то есть в плоскости, натянутой на ось
 *  проёма и нормаль кирпича. Ось поворота — их векторное произведение.
 *
 *  ВЫРОЖДЕНИЕ. Если кирпич стоит ровно на оси проёма (или ровно
 *  напротив), произведение нулевое и направление отъезда не определено:
 *  кирпичу «в сторону» некуда, все стороны равноправны. Тогда берётся
 *  любая перпендикулярная ось — кирпич обязан уехать хоть куда-то, иначе
 *  он останется висеть ровно в середине проёма, куда влетает камера.
 *  Заполняет переданный вектор, а не создаёт новый. */
export function осьОтъезда(цель: Vector3, ось: Vector3, нормаль: Vector3): Vector3 {
  цель.crossVectors(ось, нормаль)
  if (цель.lengthSq() < 1e-12) {
    // Любая ось, неколлинеарная оси проёма. Две пробы вместо одной:
    // одна-единственная сама может оказаться коллинеарной.
    цель.crossVectors(ось, new Vector3(0, 1, 0))
    if (цель.lengthSq() < 1e-12) цель.crossVectors(ось, new Vector3(1, 0, 0))
  }
  return цель.normalize()
}

/** Кватернион отъезда кирпича. Заполняет переданный, а не создаёт новый:
 *  вызывается в кадре по разу на каждый кирпич проёма. */
export function поворотОтъезда(
  цель: Quaternion,
  осьОтъезда: Vector3,
  угол: number,
): Quaternion {
  return цель.setFromAxisAngle(осьОтъезда, угол)
}

/** Доля раскрытия от нуля до единицы по прогрессу прокрутки.
 *
 *  Считается ИЗ ПРОКРУТКИ, а не из расстояния до камеры: прокрутка —
 *  единственный источник времени в сцене, и одно её положение обязано
 *  давать одну и ту же картинку. Иначе кадр перестанет быть
 *  воспроизводимым, и «на моей машине выглядит иначе» станет нормой.
 *
 *  Переход сглаженный, а не линейный: линейный даёт излом скорости на
 *  обоих концах, и проём трогается рывком. Здесь сглаживание уместно —
 *  оно по ВРЕМЕНИ, а не по кирпичам (см. весКирпича). */
export function доляРаскрытия(прогресс: number, начало: number, конец: number): number {
  return сглаженныйПереход(начало, конец, прогресс)
}

/** Во сколько раз ослабить отклонение кирпичей от курсора.
 *
 *  Наведение и раскрытие двигают одни и те же кирпичи. Складывать их в
 *  лоб нельзя: кирпич уехал бы на сумму двух смещений и вылез бы из
 *  кладки. Поэтому наведение гаснет по мере раскрытия — к полностью
 *  раскрытому проёму отклик на курсор нулевой. Это ещё и честно по
 *  смыслу: когда сфера раскрылась, трогать кладку уже поздно. */
export function силаНаведения(раскрытие: number): number {
  return 1 - раскрытие
}
