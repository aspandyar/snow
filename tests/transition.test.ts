import { describe, expect, it } from 'vitest'
import { Vector3 } from 'three'

import { порогНахлёста } from '@/lib/scroll/progress'
import {
  конецСцены,
  началоВспышки,
  перегревВспышки,
  прогрессВхода,
  прогрессСцены,
  силаВспышки,
} from '@/lib/transition/flash'

// Числа свои, а не из конфига: тест ловит ошибку в формуле, а не краснеет
// от правки настройки.
const ПОРОГ = 0.5
const НАЧАЛО = началоВспышки(0.98, 0.5)
const КОНЕЦ = 0.88

describe('прогрессСцены', () => {
  it('растягивает прокрутку до порога на весь путь сцены', () => {
    expect(прогрессСцены(0, ПОРОГ)).toBe(0)
    expect(прогрессСцены(ПОРОГ / 2, ПОРОГ)).toBeCloseTo(0.5, 10)
    expect(прогрессСцены(ПОРОГ, ПОРОГ)).toBe(1)
  })

  it('после порога стоит на единице — сцена доиграла', () => {
    expect(прогрессСцены(0.8, ПОРОГ)).toBe(1)
    expect(прогрессСцены(1, ПОРОГ)).toBe(1)
  })

  it('не убывает', () => {
    let прежнее = -1
    for (let i = 0; i <= 100; i++) {
      const текущее = прогрессСцены(i / 100, ПОРОГ)
      expect(текущее).toBeGreaterThanOrEqual(прежнее)
      прежнее = текущее
    }
  })

  it('нулевой порог не роняет вычисление делением на ноль', () => {
    expect(прогрессСцены(0.5, 0)).toBe(1)
    expect(прогрессСцены(0.5, -1)).toBe(1)
  })
})

describe('сцена доигрывает до того, как лендинг закроет кадр', () => {
  // ЭТО ГЛАВНЫЙ ТЕСТ ЭТАПА. Именно отсутствие такой проверки дало
  // поломку: пороги раскрытия ставились отдельно от порога нахлёста, они
  // разошлись, и весь влёт внутрь сферы играл за заглушкой лендинга —
  // зритель его не видел вовсе, а ни один тест не покраснел.
  it('конец сцены никогда не заходит за порог нахлёста', () => {
    // Даже если долю сцены выкрутить в единицу вкусом, потолок держит.
    for (const экранов of [3, 4, 5, 6, 8]) {
      for (const нахлёст of [0, 0.5, 1, 2]) {
        for (const доля of [0.2, 0.5, 0.9, 1]) {
          const конец = конецСцены(доля, нахлёст, экранов)
          expect(конец).toBeLessThanOrEqual(порогНахлёста(нахлёст, экранов))
        }
      }
    }
  })

  it('к концу сцены она отыграна полностью', () => {
    for (const экранов of [3, 4, 5, 6, 8]) {
      for (const нахлёст of [0, 0.5, 1, 2]) {
        const конец = конецСцены(0.5, нахлёст, экранов)
        expect(прогрессСцены(конец, конец)).toBe(1)
      }
    }
  })

  it('скромная доля сцены проходит как есть, жадная ужимается', () => {
    // 4 экрана и нахлёст в 1 дают потолок 0.667.
    expect(конецСцены(0.5, 1, 4)).toBeCloseTo(0.5, 10)
    expect(конецСцены(0.9, 1, 4)).toBeCloseTo(порогНахлёста(1, 4), 10)
  })

  it('до конца сцена ещё не доиграла — иначе кадр стоял бы зря', () => {
    const конец = конецСцены(0.5, 1, 4)
    expect(прогрессСцены(конец - 0.01, конец)).toBeLessThan(1)
  })

  it('к концу сцены вспышка ещё еле заметна', () => {
    // Свет трогается РАНЬШЕ конца сцены — ровно на раскрытом проёме, — и
    // это нарочно: сфера открылась, из неё бьёт свет, и камера влетает
    // уже сквозь него. Но влёт обязан остаться видимым, значит к концу
    // сцены заливка должна быть слабой.
    const конец = конецСцены(0.5, 1, 4)
    const начало = началоВспышки(0.9, конец)
    expect(силаВспышки(конец, начало, КОНЕЦ)).toBeLessThan(0.15)
  })
})

describe('прогрессВхода', () => {
  const центр = new Vector3(0, 0, 0)

  // Прямая от (0,0,10) к началу координат: точка на доле t стоит в
  // 10·(1−t) от центра. Простая кривая вместо настоящей траектории —
  // так проверяется формула, а не пять опорных точек из конфига.
  const прямая = {
    getPointAt(доля: number, цель: Vector3) {
      return цель.set(0, 0, 10 * (1 - доля))
    },
  }

  it('находит долю пути, на которой камера входит внутрь', () => {
    // Радиус 6 достигается на 0.4 пути.
    expect(прогрессВхода(прямая, центр, 6, 1000)).toBeCloseTo(0.4, 2)
  })

  it('чем больше сфера, тем раньше вход', () => {
    expect(прогрессВхода(прямая, центр, 8, 1000)).toBeLessThan(
      прогрессВхода(прямая, центр, 4, 1000),
    )
  })

  it('путь, который внутрь не заходит, даёт единицу, а не ноль', () => {
    // Ноль означал бы «вошли сразу» и зажёг бы свет в первом же кадре.
    const мимо = {
      getPointAt(доля: number, цель: Vector3) {
        return цель.set(50, 0, 10 * (1 - доля))
      },
    }
    expect(прогрессВхода(мимо, центр, 6, 1000)).toBe(1)
  })

  it('камера, уже стоящая внутри, даёт ноль', () => {
    const внутри = {
      getPointAt(_доля: number, цель: Vector3) {
        return цель.set(0, 0, 1)
      },
    }
    expect(прогрессВхода(внутри, центр, 6, 1000)).toBe(0)
  })
})

describe('вспышка трогается ровно на входе внутрь сферы A', () => {
  // Ради этого и заведена функция: пока момент вспышки был отдельным
  // числом, он разъезжался с раскрытием — сфера успевала открыться,
  // камера подлетала вплотную, и только потом начинался свет. Между ними
  // висела пауза, в которой зритель крутил колесо впустую.
  it('переводит момент сцены в долю прокрутки', () => {
    expect(началоВспышки(0.98, 0.5)).toBeCloseTo(0.49, 10)
    expect(началоВспышки(1, 0.5)).toBeCloseTo(0.5, 10)
    expect(началоВспышки(0.5, 0.6)).toBeCloseTo(0.3, 10)
  })

  it('в этот самый момент камера как раз вошла внутрь', () => {
    const конец = конецСцены(0.5, 1, 4)
    const вход = 0.982
    const начало = началоВспышки(вход, конец)
    expect(прогрессСцены(начало, конец)).toBeCloseTo(вход, 10)
  })

  it('свет не трогается, пока камера ещё снаружи', () => {
    const конец = конецСцены(0.5, 1, 4)
    const начало = началоВспышки(0.982, конец)
    expect(силаВспышки(начало - 0.01, начало, КОНЕЦ)).toBe(0)
    expect(силаВспышки(начало + 0.01, начало, КОНЕЦ)).toBeGreaterThan(0)
  })

  it('вспышка трогается до конца сцены, а не после', () => {
    // Иначе между влётом и светом висела бы пауза на ровном кадре.
    const конец = конецСцены(0.5, 1, 4)
    expect(началоВспышки(0.982, конец)).toBeLessThan(конец)
  })
})

describe('силаВспышки', () => {
  it('до начала кадр живой, после конца залит целиком', () => {
    expect(силаВспышки(0, НАЧАЛО, КОНЕЦ)).toBe(0)
    expect(силаВспышки(НАЧАЛО, НАЧАЛО, КОНЕЦ)).toBe(0)
    expect(силаВспышки(КОНЕЦ, НАЧАЛО, КОНЕЦ)).toBe(1)
    expect(силаВспышки(1, НАЧАЛО, КОНЕЦ)).toBe(1)
  })

  it('не убывает', () => {
    let прежнее = -1
    for (let i = 0; i <= 100; i++) {
      const текущее = силаВспышки(i / 100, НАЧАЛО, КОНЕЦ)
      expect(текущее).toBeGreaterThanOrEqual(прежнее)
      прежнее = текущее
    }
  })
})

describe('перегревВспышки', () => {
  it('на обоих концах нулевой', () => {
    // На нуле кадр ещё живой, на единице обязан сойтись РОВНО в цвет
    // подложки: иначе на стыке с лендингом останется светлая полоса.
    expect(перегревВспышки(0)).toBe(0)
    expect(перегревВспышки(1)).toBe(0)
  })

  it('в середине выходит на полную — это и делает вспышку вспышкой', () => {
    expect(перегревВспышки(0.5)).toBeCloseTo(1, 10)
  })

  it('зажат в границах при любом входе', () => {
    for (const с of [-5, -0.1, 0.3, 0.9, 1.5, 12]) {
      const п = перегревВспышки(с)
      expect(п).toBeGreaterThanOrEqual(0)
      expect(п).toBeLessThanOrEqual(1)
    }
  })
})
