import { describe, expect, it } from 'vitest'
import { Quaternion, Vector3 } from 'three'

import {
  доляРаскрытия,
  нормальРаздела,
  поворотСтворки,
  сдвигСтворки,
  силаНаведения,
  сторонаКирпича,
} from '@/lib/opening/leaves'

// Числа здесь свои, а не из конфига: тест обязан ловить ошибку в
// формуле, а не краснеть каждый раз, когда в конфиге подкрутили
// настройку. Значения близки к рабочим, чтобы проверка про
// непересечение створок оставалась осмысленной.
const РАДИУС = 6
const СДВИГ = 3.5
const УГОЛ = 0.35
const ШИРИНА_КИРПИЧА = 1.3464

describe('нормальРаздела', () => {
  it('перпендикулярна направлению входа', () => {
    const вход = new Vector3(0.8, -0.1, -0.6).normalize()
    const н = нормальРаздела(вход)
    expect(н.dot(вход)).toBeCloseTo(0, 10)
  })

  it('строго горизонтальна: створки расходятся вбок, а не наискось', () => {
    const н = нормальРаздела(new Vector3(0.5, 0.8, -0.33).normalize())
    expect(н.y).toBe(0)
  })

  it('единичной длины', () => {
    const н = нормальРаздела(new Vector3(3, -7, 2).normalize())
    expect(н.length()).toBeCloseTo(1, 10)
  })

  it('не зависит от наклона входа — важен только его азимут', () => {
    const полого = нормальРаздела(new Vector3(1, -0.05, -1).normalize())
    const круто = нормальРаздела(new Vector3(1, -3, -1).normalize())
    expect(полого.angleTo(круто)).toBeCloseTo(0, 6)
  })
})

describe('сторонаКирпича', () => {
  const н = new Vector3(1, 0, 0)

  it('делит кладку на две створки по знаку проекции', () => {
    expect(сторонаКирпича(new Vector3(0.9, 0.1, 0.4).normalize(), н)).toBe(1)
    expect(сторонаКирпича(new Vector3(-0.9, 0.1, 0.4).normalize(), н)).toBe(-1)
  })

  it('кирпич ровно на шве уходит в створку, а не остаётся висеть', () => {
    expect(сторонаКирпича(new Vector3(0, 1, 0), н)).toBe(1)
    expect(сторонаКирпича(new Vector3(0, 0, 1), н)).toBe(1)
  })
})

describe('доляРаскрытия', () => {
  it('до начала створки стоят', () => {
    expect(доляРаскрытия(0, 0.58, 0.9)).toBe(0)
    expect(доляРаскрытия(0.57, 0.58, 0.9)).toBe(0)
  })

  it('после конца распахнуты полностью', () => {
    expect(доляРаскрытия(0.9, 0.58, 0.9)).toBe(1)
    expect(доляРаскрытия(1, 0.58, 0.9)).toBe(1)
  })

  it('на середине отрезка — ровно половина', () => {
    expect(доляРаскрытия(0.74, 0.58, 0.9)).toBeCloseTo(0.5, 10)
  })

  it('не убывает', () => {
    let прежнее = -1
    for (let i = 0; i <= 100; i++) {
      const текущее = доляРаскрытия(i / 100, 0.58, 0.9)
      expect(текущее).toBeGreaterThanOrEqual(прежнее)
      прежнее = текущее
    }
  })

  it('трогается и останавливается плавно: скорость на концах нулевая', () => {
    // Скорость сравнивается не с нулём в лоб, а с серединой отрезка: у
    // сглаженного перехода на концах она строго нулевая, но разностная
    // производная с конечным шагом даёт малый остаток, и «ровно ноль»
    // тест бы не прошёл никогда. Важно именно то, что на концах она на
    // порядки меньше, чем в середине.
    const ш = 1e-4
    const скорость = (у: number) =>
      Math.abs(доляРаскрытия(у + ш, 0.58, 0.9) - доляРаскрытия(у, 0.58, 0.9)) / ш
    const вСередине = скорость(0.74)
    expect(скорость(0.58)).toBeLessThan(вСередине / 100)
    expect(скорость(0.9 - ш)).toBeLessThan(вСередине / 100)
  })
})

describe('сдвигСтворки', () => {
  it('разводит створки в противоположные стороны на равные отрезки', () => {
    const н = new Vector3(1, 0, 0)
    const плюс = сдвигСтворки(new Vector3(), 1, н, СДВИГ)
    const минус = сдвигСтворки(new Vector3(), -1, н, СДВИГ)
    expect(плюс.length()).toBeCloseTo(СДВИГ, 10)
    expect(плюс.clone().add(минус).length()).toBeCloseTo(0, 10)
  })

  it('при нулевом раскрытии не двигает ничего', () => {
    const с = сдвигСтворки(new Vector3(), 1, new Vector3(0, 0, 1), 0)
    expect(с.length()).toBe(0)
  })
})

describe('поворотСтворки', () => {
  it('створки крутятся в разные стороны', () => {
    const плюс = поворотСтворки(new Quaternion(), 1, УГОЛ)
    const минус = поворотСтворки(new Quaternion(), -1, УГОЛ)
    expect(плюс.angleTo(минус)).toBeCloseTo(2 * УГОЛ, 10)
  })

  it('вокруг вертикали: полюса остаются на месте', () => {
    const полюс = new Vector3(0, 6, 0)
    полюс.applyQuaternion(поворотСтворки(new Quaternion(), 1, УГОЛ))
    expect(полюс.x).toBeCloseTo(0, 10)
    expect(полюс.z).toBeCloseTo(0, 10)
    expect(полюс.y).toBeCloseTo(6, 10)
  })

  it('при нулевом угле ничего не поворачивает', () => {
    const т = new Vector3(1, 2, 3)
    const было = т.clone()
    т.applyQuaternion(поворотСтворки(new Quaternion(), -1, 0))
    expect(т.distanceTo(было)).toBeCloseTo(0, 10)
  })
})

describe('створки не пересекаются', () => {
  // Главная проверка этапа. Берём пары кирпичей, стоящих вплотную по обе
  // стороны шва, разводим их полным раскрытием и смотрим, остался ли
  // зазор. Самое опасное место — ДАЛЬНИЙ край шва: там разворот работает
  // против сдвига и съедает его.
  const вход = new Vector3(1, 0, 0)
  const н = нормальРаздела(вход)

  const развести = (точка: Vector3, сторона: number) =>
    точка
      .clone()
      .applyQuaternion(поворотСтворки(new Quaternion(), сторона, УГОЛ))
      .add(сдвигСтворки(new Vector3(), сторона, н, СДВИГ))

  it('по всему шву зазор шире кирпича', () => {
    let наименьший = Infinity
    // Шов — большой круг в плоскости раздела. Обходим его целиком.
    for (let i = 0; i < 360; i++) {
      const угол = (i * Math.PI) / 180
      // Плоскость раздела натянута на вертикаль и на направление входа.
      const наШве = new Vector3()
        .addScaledVector(new Vector3(0, 1, 0), Math.sin(угол) * РАДИУС)
        .addScaledVector(вход, Math.cos(угол) * РАДИУС)
      наименьший = Math.min(наименьший, развести(наШве, 1).distanceTo(развести(наШве, -1)))
    }
    expect(наименьший).toBeGreaterThan(ШИРИНА_КИРПИЧА)
  })

  it('у БЛИЖНЕГО края, куда влетает камера, проём шире голого сдвига', () => {
    const ближний = вход.clone().multiplyScalar(-РАДИУС)
    const зазор = развести(ближний, 1).distanceTo(развести(ближний, -1))
    expect(зазор).toBeGreaterThan(2 * СДВИГ)
  })

  it('у дальнего края разворот съедает сдвиг, но кирпичи всё же расходятся', () => {
    const дальний = вход.clone().multiplyScalar(РАДИУС)
    const зазор = развести(дальний, 1).distanceTo(развести(дальний, -1))
    expect(зазор).toBeLessThan(2 * СДВИГ)
    expect(зазор).toBeGreaterThan(ШИРИНА_КИРПИЧА)
  })
})

describe('силаНаведения', () => {
  it('на закрытой сфере курсор работает в полную силу', () => {
    expect(силаНаведения(0)).toBe(1)
  })

  it('на распахнутой не работает вовсе', () => {
    expect(силаНаведения(1)).toBe(0)
  })

  it('гаснет по мере раскрытия', () => {
    expect(силаНаведения(0.25)).toBeGreaterThan(силаНаведения(0.75))
  })
})
