'use client'

import { useProgress } from '@react-three/drei'
import { useCallback, useEffect, useState } from 'react'

import { загрузка } from '@/lib/config'
import { useЯзык } from '@/lib/landing/language'
import { ТЕКСТЫ } from '@/lib/landing/texts'

import SceneCanvas from './SceneCanvas'

/** Сцена вместе с экраном ожидания.
 *
 *  Зачем отдельный слой поверх холста. Первая загрузка — это несколько
 *  мегабайт карт и панорама неба, и всё это время холст пуст. Без экрана
 *  ожидания зритель смотрит в ровный светлый прямоугольник и не может
 *  отличить «грузится» от «сломалось»; на медленной связи он уйдёт раньше,
 *  чем появится первый кадр.
 *
 *  Экран живёт В ЭТОМ ЖЕ куске сборки, что и холст, а не на странице.
 *  Причина простая: ход загрузки читается из useProgress, а он приходит из
 *  drei — вынеси его на страницу, и вся библиотека сцены поедет к зрителю
 *  раньше, чем понадобится. Тогда экран ожидания сам стал бы причиной
 *  ожидания. */
export default function SceneStage() {
  const { progress } = useProgress()
  const язык = useЯзык((с) => с.язык)
  const [готово, задатьГотово] = useState(false)
  const [скрыт, задатьСкрыт] = useState(false)

  // Заслонка снимается по ФАКТУ ОТРИСОВКИ, а проценты идут только в
  // полосу. Разница не косметическая: у вернувшегося зрителя файлы лежат
  // в кеше, загрузчик не заводит ни одного задания, и «загружено = всего»
  // не наступает никогда — заслонка висела бы вечно. Проверено: на втором
  // заходе счётчик остаётся нулевым, а сцена при этом уже нарисована.
  // Подробности у ReadySignal.
  const сообщить = useCallback(() => задатьГотово(true), [])

  useEffect(() => {
    if (!готово) return
    // Задержка на затухание: экран должен уехать плавно, а не мигнуть.
    // Снимается он ПОСЛЕ того, как прозрачность дойдёт до нуля, иначе
    // кадр под ним появится рывком.
    const таймер = setTimeout(() => задатьСкрыт(true), загрузка.затухание)
    return () => clearTimeout(таймер)
  }, [готово])

  if (скрыт) return <SceneCanvas приГотовности={сообщить} />

  return (
    <>
      <SceneCanvas приГотовности={сообщить} />
      <div
        className="absolute inset-0 z-20 flex flex-col items-center justify-center gap-4 transition-opacity"
        style={{
          background: 'var(--подложка)',
          opacity: готово ? 0 : 1,
          transitionDuration: `${загрузка.затухание}ms`,
          // Пока экран снимается, под ним уже живая сцена: он обязан
          // перестать перехватывать курсор раньше, чем исчезнет совсем,
          // иначе первые полсекунды наведение не работает.
          pointerEvents: готово ? 'none' : 'auto',
        }}
        aria-hidden={готово}
      >
        <div
          className="h-px w-40 overflow-hidden"
          style={{ background: 'var(--чернила-слабые)' }}
        >
          {/* Полоса, а не крутящееся колесо: колесо крутится одинаково и
              при живой загрузке, и при застрявшей, а полоса показывает,
              сколько уже пришло. */}
          <div
            className="h-full transition-[width] duration-200"
            style={{ background: 'var(--чернила)', width: `${progress.toFixed(0)}%` }}
          />
        </div>
        <p className="text-sm" style={{ color: 'var(--чернила-слабые)' }}>
          {ТЕКСТЫ[язык].загрузка}
        </p>
      </div>
    </>
  )
}
