import { createNoise2D } from 'simplex-noise'

/** Дюна: крупная форма рельефа, расставляемая вручную.
 *
 *  Крупные формы задаются списком, а не шумом, потому что чистый шум
 *  красив, но кадром не управляет: холм не поставить туда, где он нужен
 *  по композиции. */
export type Дюна = {
  x: number
  z: number
  радиус: number
  высота: number
}

/** Вклад одной дюны в высоту точки.
 *
 *  Финитный колокол, а НЕ гауссова кривая. У гауссовой бесконечный хвост,
 *  и гора в сотне метров приподнимает землю под объектом — сначала на
 *  сантиметры, потом на дециметры. Здесь за пределами радиуса ровно ноль.
 *
 *  Множитель t²·(3 − 2t) выбран не ради красоты формулы: его производная
 *  равна нулю на обоих концах. Поэтому дюна смыкается с равниной без
 *  излома, а на вершине не образует пика. */
export function вкладДюны(дюна: Дюна, x: number, z: number): number {
  const дx = x - дюна.x
  const дz = z - дюна.z
  const расстояние = Math.sqrt(дx * дx + дz * дz)
  if (расстояние >= дюна.радиус) return 0
  const t = 1 - расстояние / дюна.радиус
  return дюна.высота * t * t * (3 - 2 * t)
}

export type ВершинаКольца = {
  /** Куда смотрит вершина, радианы. */
  угол: number
  /** Угловая полуширина подножия, радианы: дальше вклад ровно ноль. */
  ширина: number
  высота: number
}

/** Кратчайшая разница между двумя углами, радианы, в пределах ±π.
 *
 *  Без неё вершина, стоящая у шва кольца, обрывалась бы: слева от нуля до
 *  неё «почти два π», справа — «почти ноль», и половина горы исчезала бы.
 *  Кратчайший путь по кругу делает шов таким же местом, как любое
 *  другое. */
export function угловаяРазница(первый: number, второй: number): number {
  const круг = Math.PI * 2
  let разница = (первый - второй) % круг
  if (разница > Math.PI) разница -= круг
  if (разница < -Math.PI) разница += круг
  return разница
}

/** Профиль горного кольца: сумма финитных колоколов ПО УГЛУ.
 *
 *  По углу, а не по длине дуги, и это не мелочь. Кольцо замкнуто: угол 0
 *  и угол 2π — одна и та же точка пространства. Считай мы профиль от
 *  дуги, в этой точке сошлись бы два разных значения высоты, и по всему
 *  кольцу сверху донизу прошла бы вертикальная ступенька — шов, который
 *  ничем не замазать.
 *
 *  Колокол тот же, что у дюн равнины: t²(3−2t). Финитный, потому что у
 *  гауссовой кривой бесконечный хвост и дальняя вершина незаметно
 *  приподнимала бы всё кольцо целиком. С нулевой производной на концах,
 *  потому что иначе подножие горы смыкается с горизонтом изломом.
 *
 *  Толщины у кольца нет намеренно: на трёх сотнях метров объём не
 *  прочитается, он тонет в дымке. Платить за него сеткой не за что. */
export function профильКольца(угол: number, вершины: ВершинаКольца[]): number {
  let высота = 0
  for (const вершина of вершины) {
    const расстояние = Math.abs(угловаяРазница(угол, вершина.угол))
    if (расстояние >= вершина.ширина) continue
    const t = 1 - расстояние / вершина.ширина
    высота += вершина.высота * t * t * (3 - 2 * t)
  }
  return высота
}

export type ПараметрыРельефа = {
  зерно: number
  наст: {
    амплитуда: number
    частота: number
    октав: number
  }
  дюны: Дюна[]
}

/** Генератор псевдослучайных чисел mulberry32.
 *
 *  Нужен, чтобы шум был воспроизводимым: без явного зерна рельеф менялся
 *  бы при каждой перезагрузке, а тесты стали бы невоспроизводимыми.
 *
 *  Числа внутри — константы алгоритма, а не настройка сцены. В конфиг они
 *  не выносятся: менять их нельзя, от них зависит качество распределения. */
export function генератор(зерно: number): () => number {
  let состояние = зерно >>> 0
  return () => {
    состояние = (состояние + 0x6d2b79f5) >>> 0
    let t = состояние
    t = Math.imul(t ^ (t >>> 15), t | 1)
    t ^= t + Math.imul(t ^ (t >>> 7), t | 61)
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296
  }
}

/** Собирает функцию высоты рельефа.
 *
 *  Фабрика, а не готовая функция: таблица перестановок шума строится один
 *  раз здесь, а не на каждом вызове. Полученная функция — единственный
 *  источник истины о форме земли. Ею пользуются трое: земля строит по ней
 *  вершины, туман по ней стелется, курсор находит по ней точку под собой.
 *  Пока формула жила внутри компонента земли, туман ложился плоским листом
 *  и резал холмы, а курсор мял снег не там, куда указывал. */
export function создатьВысотуРельефа(п: ПараметрыРельефа): (x: number, z: number) => number {
  const шум = createNoise2D(генератор(п.зерно))

  return (x: number, z: number): number => {
    let высота = 0

    // Октавы шума дают мелкую фактуру наста: каждая следующая вдвое чаще
    // и вдвое слабее. Шум отвечает только за фактуру — крупные формы
    // расставляются дюнами, иначе кадром не управлять.
    for (let октава = 0; октава < п.наст.октав; октава++) {
      const множитель = 2 ** октава
      высота +=
        (п.наст.амплитуда / множитель) *
        шум(x * п.наст.частота * множитель, z * п.наст.частота * множитель)
    }

    for (const дюна of п.дюны) высота += вкладДюны(дюна, x, z)

    return высота
  }
}

/** Высота поверхности тумана над точкой земли.
 *
 *  Вынесено функцией не ради сложности — она тривиальна, — а ради теста:
 *  соблазн положить туман плоским листом на постоянной высоте велик, и
 *  на общем плане разница почти не видна. Видна она там, где туман
 *  срезает дюну, и замечается это обычно через этап. */
export function высотаТумана(высотаЗемли: number, надЗемлёй: number): number {
  return высотаЗемли + надЗемлёй
}

/** Перевод локальных координат вершины плоскости в мировые.
 *
 *  Плоскость создаётся лежащей в XY и поворачивается на −90° вокруг оси X.
 *  Поворот отображает локальную вершину (x, y) в мировую точку (x, 0, −y):
 *  мировая z равна МИНУС локальной y.
 *
 *  Вынесено отдельной функцией именно ради теста. Внутри цикла по вершинам
 *  этот знак не проверить ничем, кроме глаза, а на глаз зеркальный рельеф
 *  неотличим от правильного. */
export function локальныеВМировые(x: number, y: number): [number, number] {
  return [x, -y === 0 ? 0 : -y]
}
