import { Vector3 } from 'three'

import { сглаженныйПереход } from '@/lib/hover/displacement'
import { порогНахлёста } from '@/lib/scroll/progress'

/** Доля прокрутки, на которой сцена обязана доиграть.
 *
 *  Берётся МЕНЬШЕЕ из двух: желаемой доли и порога нахлёста. Желаемая
 *  задаётся вкусом — насколько быстро зритель должен получить развязку.
 *  Порог нахлёста — жёсткий потолок: после него лендинг наезжает на кадр,
 *  и всё, что играет позже, зритель просто не видит. Именно так и было,
 *  пока это не связали формулой.
 *
 *  Минимум, а не проверка с ошибкой: настройку правят вкусом, и уронить
 *  сцену из-за перебора на сотую — хуже, чем молча ужаться до потолка. */
export function конецСцены(
  доля: number,
  нахлёстВЭкранах: number,
  высотаВЭкранах: number,
): number {
  return Math.min(доля, порогНахлёста(нахлёстВЭкранах, высотаВЭкранах))
}

/** Прогресс СЦЕНЫ из прогресса прокрутки.
 *
 *  Сцена обязана доиграть до того, как лендинг начнёт наезжать на кадр.
 *  Раньше это держалось на честном слове: пороги раскрытия ставились
 *  отдельно от порога нахлёста, и в какой-то момент разошлись — весь влёт
 *  внутрь сферы играл за заглушкой лендинга, зритель его не видел вовсе.
 *
 *  Теперь связь структурная. Камера и раскрытие получают не сырой
 *  прогресс, а этот: он растянут на отрезок до порога и дальше замер на
 *  единице. Подвинуть нахлёст, не подвинув сцену, физически нельзя —
 *  порог входит в формулу.
 *
 *  Порог ноль или меньше означает, что нахлёст съел всю прокрутку. Тогда
 *  сцена считается доигравшей сразу: делить на ноль нельзя, а показывать
 *  первый кадр вечно — хуже, чем показать последний. */
export function прогрессСцены(прогресс: number, порог: number): number {
  if (порог <= 0) return 1
  return Math.min(1, Math.max(0, прогресс / порог))
}

/** Кривая, у которой можно спросить точку по доле длины. Ровно то, что
 *  умеет CatmullRomCurve3, и ровно столько, сколько нужно функции ниже:
 *  так её можно проверить на простой прямой, не поднимая всю траекторию. */
export type Кривая = {
  getPointAt(доля: number, цель: Vector3): Vector3
}

/** Доля прокрутки, на которой разгорание заканчивается.
 *
 *  Это порог нахлёста — момент, когда лендинг начинает наезжать на кадр.
 *  Не отдельная настройка: раньше здесь стояло число 0.88, и разгорание
 *  тянулось почти до самого низа страницы, хотя смотреть там уже было
 *  не на что — кадр наполовину закрыт. Свет обязан доиграть РОВНО к
 *  приходу страницы: быстрее нельзя (свет оборвётся, не дойдя до цвета
 *  подложки, и на стыке будет видна граница), медленнее незачем.
 *
 *  Отсюда же и темп: окно разгорания — это всё, что осталось от прокрутки
 *  между концом сцены и приходом лендинга. Хочешь быстрее — двигай не
 *  это число, а конец сцены или нахлёст. */
export function конецРазгорания(
  нахлёстВЭкранах: number,
  высотаВЭкранах: number,
): number {
  return порогНахлёста(нахлёстВЭкранах, высотаВЭкранах)
}

/** Доля пути СЦЕНЫ, на которой камера входит внутрь сферы A.
 *
 *  Ищется перебором по длине дуги, а не решается уравнением: кривая
 *  Катмулла-Рома через пять точек — многочлен, у которого пересечение со
 *  сферой аналитически не выражается. Шаг берётся мелкий, погрешность в
 *  доли процента прокрутки на глаз неразличима.
 *
 *  Возвращает единицу, если камера внутрь так и не заходит. Это не
 *  ошибка: путь может проходить мимо, и тогда вспышке разумно начаться в
 *  конце сцены, а не никогда. */
export function прогрессВхода(
  путь: Кривая,
  центр: Vector3,
  радиус: number,
  шагов: number,
): number {
  const точка = new Vector3()
  for (let i = 0; i <= шагов; i++) {
    const доля = i / шагов
    путь.getPointAt(доля, точка)
    if (точка.distanceTo(центр) <= радиус) return доля
  }
  return 1
}

/** Доля прокрутки, на которой ТРОГАЕТСЯ вспышка.
 *
 *  Не отдельная настройка, а перевод момента из времени СЦЕНЫ во время
 *  ПРОКРУТКИ. Сцена занимает отрезок от нуля до конецСцены, поэтому
 *  перевод — произведение.
 *
 *  Момент задаётся входом камеры внутрь сферы A: свет из Б обязан пойти
 *  ровно тогда, когда зритель оказывается внутри. Раньше здесь стоял
 *  конец раскрытия, и это было не то: проём успевал открыться, когда до
 *  оболочки оставалось ещё 12.8 метра, и свет разгорался, пока зритель
 *  только подлетал.
 *
 *  А до того это было просто числом в конфиге, и оно разъезжалось со
 *  всем подряд. Правило по итогам трёх таких случаев: если два момента
 *  обязаны совпадать, они обязаны быть ОДНОЙ формулой. */
export function началоВспышки(моментСцены: number, конецСцены: number): number {
  return моментСцены * конецСцены
}

/** Сила вспышки от нуля до единицы по прогрессу прокрутки.
 *
 *  Считается из ПРОКРУТКИ, а не из прогресса сцены: вспышка живёт как раз
 *  в той трети, где сцена уже замерла, и от прогресса сцены не зависела бы
 *  вовсе. */
export function силаВспышки(прогресс: number, начало: number, конец: number): number {
  return сглаженныйПереход(начало, конец, прогресс)
}

/** Доля доводки кадра до цвета подложки, из доли разгорания.
 *
 *  Основную работу перехода делает сам шарик Б: он раздувается, и его
 *  ореол съедает кладку. Но белый ореол — это чистый белый, а лендинг
 *  лежит на цвете подложки, и на стыке была бы видна светлая полоса.
 *  Поэтому в хвосте разгорания поверх добавляется мягкая доводка.
 *
 *  Порог не ноль: доводка обязана включаться, когда кадр УЖЕ почти белый,
 *  иначе она гасит его раньше, чем шарик успел разгореться, и переход
 *  читается затуханием вместо вспышки. */
export function силаЗаливки(доляСвета: number, порог: number): number {
  if (порог >= 1) return 0
  return сглаженныйПереход(порог, 1, доляСвета)
}

/** Перегрев вспышки: насколько кадр в этот момент ярче цвета подложки.
 *
 *  Нужен, чтобы переход читался вспышкой, а не затуханием. Без него кадр
 *  просто плавно заливается цветом страницы, и «свет из шара» превращается
 *  в аккуратное исчезновение.
 *
 *  Колокол, а не рост: на нуле вспышки перегрева нет (кадр ещё живой), на
 *  единице тоже нет (кадр обязан сойтись РОВНО в цвет подложки, иначе на
 *  стыке с лендингом будет видна светлая полоса). Пик посередине. */
export function перегревВспышки(сила: number): number {
  const с = Math.min(1, Math.max(0, сила))
  return 4 * с * (1 - с)
}
