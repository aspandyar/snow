'use client'

import { useEffect, useMemo, useRef } from 'react'
import { useFrame } from '@react-three/fiber'
import { CanvasTexture } from 'three'

import { лучКурсора, рельеф, следы } from '@/lib/config'
import { нарисоватьПятно, погаситьПолотно } from '@/lib/footprints/trail'
import { найтиТочкуНаЗемле } from '@/lib/terrain/raycast'
import { высотаСцены } from '@/lib/terrain/scene-height'

/** Холст следов на снегу.
 *
 *  Каждый кадр: под курсором рисуется мягкое тёмное пятно, затем всё
 *  полотно заливается почти прозрачным белым. Заливка и есть весь
 *  механизм затухания — старые пятна выцветают сами, без таймеров и
 *  списка точек (см. lib/footprints/trail.ts). Готовый холст отдаётся
 *  наружу текстурой; земля берёт её картой смещения.
 *
 *  Хук, а не компонент: карта следов нужна материалу земли обычным
 *  React-пропом (displacementMap на meshStandardMaterial), а не отдельным
 *  узлом дерева сцены — своей разметки у неё нет. */
// Правило react-hooks/rules-of-hooks распознаёт хуки по регулярному
// выражению, которое проверяет ТОЛЬКО латиницу после «use» — кириллическое
// «К» в useКартаСледов под него не попадает, и линтер считает функцию
// обычной, а вызовы хуков внутри — нарушением. Идентификаторы в проекте
// по-русски намеренно (см. AGENTS.md), а сама функция правилам хуков
// следует буквально: все вызовы безусловны, в одном порядке, при каждом
// рендере. Отключение точечное — только эта функция, только это правило.
/* eslint-disable react-hooks/rules-of-hooks */
export function useКартаСледов(): CanvasTexture {
  // Холст и текстура создаются один раз на время жизни компонента,
  // использующего хук. Для холста нет декларативного JSX-примитива вроде
  // <planeGeometry>, который R3F убрал бы за собой сам (так решена та же
  // задача для геометрии земли в Snowfield.tsx) — значит, создание и
  // освобождение здесь ручные, эффектом ниже.
  const { контекст, текстура } = useMemo(() => {
    const холст = document.createElement('canvas')
    холст.width = следы.размерХолста
    холст.height = следы.размерХолста

    const контекст = холст.getContext('2d')
    if (!контекст) {
      // 2D-контекст отсутствует только в средах без Canvas API — сцена и
      // без того требует WebGL, так что до этой точки такая среда не
      // добралась бы. Явная ошибка лучше, чем тихая работа без следов.
      throw new Error('2D-контекст холста следов недоступен')
    }

    // Белый фон — исходный уровень снега: карта смещения поднимает
    // вершины по яркости, а полностью белый пиксель — это отсутствие
    // вмятины. Без начальной заливки холст был бы прозрачным (чёрным
    // для карты смещения) и равнина вздулась бы буграми ещё до первого
    // движения мыши.
    контекст.fillStyle = '#ffffff'
    контекст.fillRect(0, 0, холст.width, холст.height)

    const текстура = new CanvasTexture(холст)
    return { контекст, текстура }
  }, [])

  // Освобождение видеопамяти при размонтировании. В этом проекте уже была
  // утечка на неосвобождённой геометрии — здесь та же дисциплина для
  // текстуры.
  //
  // Строгий режим React в разработке дважды вызывает эффект на
  // монтировании (mount → cleanup → mount), но не пересоздаёт объект из
  // useMemo — тот же холст возвращается снова. Для геометрии земли это
  // было ловушкой: её needsUpdate выставляется один раз, и синтетический
  // cleanup оставил бы её разрушенной навсегда. Здесь ловушки нет —
  // needsUpdate у текстуры следов выставляется КАЖДЫЙ второй кадр в
  // useFrame ниже, и даже преждевременный dispose из синтетического
  // cleanup затянется на следующем же настоящем кадре.
  useEffect(() => {
    return () => {
      текстура.dispose()
      // У самого холста нет .dispose(): он не подключён к DOM и не
      // держит ничего, кроме пиксельных данных. Сборщик мусора заберёт
      // его сам, как только эта переменная перестанет существовать.
    }
  }, [текстура])

  // Чередование кадров для загрузки в видеопамять — обычный ref, а не
  // состояние React: перерисовка компонента на каждый кадр положила бы
  // сцену. Рисовать при этом нужно КАЖДЫЙ кадр, иначе след при быстром
  // движении мыши станет пунктирным — прерывистой становится только
  // отправка холста на видеокарту, а не сама заливка.
  const чётныйКадр = useRef(false)

  // Приоритет по умолчанию. Любой приоритет больше нуля отключает
  // автоматическую отрисовку в R3F, и экран чернеет без единой ошибки в
  // консоли.
  useFrame((состояние) => {
    состояние.raycaster.setFromCamera(состояние.pointer, состояние.camera)
    const луч = состояние.raycaster.ray

    // Точка ищется маршем луча по функции высоты — тому же источнику
    // истины о форме земли, что и у самой равнины. Начало и направление
    // берутся прямо из объекта луча: он уже Vector3 с полями x, y, z и
    // подходит под тип Точка без создания лишних объектов.
    const точка = найтиТочкуНаЗемле(луч.origin, луч.direction, высотаСцены, лучКурсора)

    if (точка) {
      // Плоскость земли центрирована в начале координат и занимает
      // [-размер/2, размер/2] по обеим осям — так её создаёт
      // <planeGeometry> в Snowfield.tsx. Перевод в пиксели холста линеен:
      // центр плоскости совпадает с центром холста.
      const x = (точка.x / рельеф.размер + 0.5) * следы.размерХолста
      const y = (точка.z / рельеф.размер + 0.5) * следы.размерХолста

      // Точка вне холста отбрасывается. Курсор за краем равнины даёт
      // координату вне полотна: рисование по ней либо ничего не заденет,
      // либо (не будь этой проверки, вздумай кто-то завернуть координату
      // остатком от деления вместо отбраковки) оставило бы след на
      // противоположной стороне равнины.
      const наХолсте = x >= 0 && x <= следы.размерХолста && y >= 0 && y <= следы.размерХолста

      if (наХолсте) {
        // Радиус пятна задан в метрах равнины — переводится в пиксели
        // тем же масштабом, что и координаты точки.
        const радиусВПикселях = (следы.радиусПятна / рельеф.размер) * следы.размерХолста
        нарисоватьПятно(контекст, x, y, радиусВПикселях, следы.яркостьПятна)
      }
    }

    погаситьПолотно(контекст, следы.размерХолста, следы.затухание)

    чётныйКадр.current = !чётныйКадр.current
    if (чётныйКадр.current) текстура.needsUpdate = true
  })

  return текстура
}
/* eslint-enable react-hooks/rules-of-hooks */
