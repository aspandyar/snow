/** Схемы страницы.
 *
 *  ВСЕ ЧИСЛА ЗДЕСЬ ПРИХОДЯТ ИЗ ТЕХ ЖЕ ФУНКЦИЙ, ЧТО СЧИТАЮТ СЦЕНУ. Ни одна
 *  схема не нарисована отдельно «для иллюстрации»: отдельная реализация
 *  разошлась бы с кодом на первой же правке и начала бы врать, а врущая
 *  схема хуже отсутствующей.
 *
 *  Рисуется всё в SVG, а не третьим холстом WebGL: страница уже держит
 *  контекст сцены, а десяток лишних контекстов браузер просто не даст.
 *
 *  Координаты внутри SVG — числа разметки, а не настройки проекта: они
 *  описывают, как схема ложится в свой прямоугольник, и к сцене
 *  отношения не имеют. Поэтому их место здесь, а не в lib/config.ts. */

const ШИРИНА = 640
const ВЫСОТА = 200
const ПОЛЕ = 28

function Frame({ children }: { children: React.ReactNode }) {
  return (
    <svg
      viewBox={`0 0 ${ШИРИНА} ${ВЫСОТА}`}
      className="w-full h-auto"
      role="img"
      aria-hidden="true"
    >
      {children}
    </svg>
  )
}

/** Кирпичей в каждом кольце, от полюса к полюсу. */
export function DiagramMasonry() {
  const кольца = useMemo(
    () =>
      Array.from({ length: сфера.колец }, (_, i) => ({
        кольцо: i,
        количество: количествоВКольце(сфера, i),
        широта: широтаКольца(сфера.колец, i),
      })),
    [],
  )
  const макс = Math.max(...кольца.map((к) => к.количество))
  const шаг = (ШИРИНА - ПОЛЕ * 2) / кольца.length

  return (
    <Frame>
      {кольца.map((к) => {
        const в = ((ВЫСОТА - ПОЛЕ * 2) * к.количество) / макс
        return (
          <rect
            key={к.кольцо}
            x={ПОЛЕ + к.кольцо * шаг}
            y={ВЫСОТА - ПОЛЕ - в}
            width={Math.max(1, шаг - 2)}
            height={в}
            fill="var(--чернила-слабые)"
          />
        )
      })}
      <line
        x1={ПОЛЕ}
        y1={ВЫСОТА - ПОЛЕ}
        x2={ШИРИНА - ПОЛЕ}
        y2={ВЫСОТА - ПОЛЕ}
        stroke="var(--чернила)"
        strokeWidth="1"
      />
      <text x={ПОЛЕ} y={ПОЛЕ} fill="var(--чернила)" fontSize="13">
        {макс} шт.
      </text>
    </Frame>
  )
}

/** Профиль высоты вдоль линии через равнину. */
export function DiagramPlain() {
  const точки = useMemo(() => {
    const половина = рельеф.размер / 2
    const n = 240
    return Array.from({ length: n + 1 }, (_, i) => {
      const x = -половина + (рельеф.размер * i) / n
      return { x, h: высотаСцены(x, 0) }
    })
  }, [])

  const макс = Math.max(...точки.map((т) => т.h))
  const мин = Math.min(...точки.map((т) => т.h))
  const размах = Math.max(1e-6, макс - мин)

  const путь = точки
    .map((т, i) => {
      const px = ПОЛЕ + ((ШИРИНА - ПОЛЕ * 2) * i) / (точки.length - 1)
      const py = ВЫСОТА - ПОЛЕ - ((ВЫСОТА - ПОЛЕ * 2) * (т.h - мин)) / размах
      return `${i === 0 ? 'M' : 'L'}${px.toFixed(1)} ${py.toFixed(1)}`
    })
    .join(' ')

  return (
    <Frame>
      <path d={путь} fill="none" stroke="var(--чернила)" strokeWidth="1.5" />
      <text x={ПОЛЕ} y={ПОЛЕ} fill="var(--чернила)" fontSize="13">
        {макс.toFixed(1)} м
      </text>
      <text x={ПОЛЕ} y={ВЫСОТА - ПОЛЕ + 16} fill="var(--чернила)" fontSize="13">
        {мин.toFixed(1)} м
      </text>
    </Frame>
  )
}

/** Сколько остаётся от следа через n кадров.
 *
 *  Затухание — это заливка полотна белым с прозрачностью, то есть каждый
 *  кадр от следа остаётся доля (1 − затухание). За n кадров — эта доля в
 *  степени n. */
export function DiagramTrail() {
  const кадров = 180
  const точки = useMemo(
    () =>
      Array.from({ length: кадров + 1 }, (_, n) => ({
        n,
        доля: Math.pow(1 - следы.затухание, n),
      })),
    [],
  )

  const путь = точки
    .map((т, i) => {
      const px = ПОЛЕ + ((ШИРИНА - ПОЛЕ * 2) * i) / кадров
      const py = ВЫСОТА - ПОЛЕ - (ВЫСОТА - ПОЛЕ * 2) * т.доля
      return `${i === 0 ? 'M' : 'L'}${px.toFixed(1)} ${py.toFixed(1)}`
    })
    .join(' ')

  // Через сколько кадров остаётся половина — самая понятная отметка.
  const половина = Math.log(0.5) / Math.log(1 - следы.затухание)
  const пх = ПОЛЕ + ((ШИРИНА - ПОЛЕ * 2) * половина) / кадров

  return (
    <Frame>
      <path d={путь} fill="none" stroke="var(--чернила)" strokeWidth="1.5" />
      <line
        x1={пх}
        y1={ПОЛЕ}
        x2={пх}
        y2={ВЫСОТА - ПОЛЕ}
        stroke="var(--чернила-слабые)"
        strokeWidth="1"
        strokeDasharray="3 3"
      />
      <text x={пх + 6} y={ПОЛЕ + 12} fill="var(--чернила)" fontSize="13">
        ½ за {Math.round(половина)} кадров
      </text>
    </Frame>
  )
}

/** Углы колец до раскрытия и после.
 *
 *  Верхний ряд — где кольцо стоит в покое, нижний — куда оно уезжает при
 *  полном раскрытии. Видно и то, что внутри проёма не остаётся никого, и
 *  то, что кольца сгущаются к его краю. */
export function DiagramAperture() {
  const ряды = useMemo(() => {
    const шагКольца = Math.PI / сфера.колец
    const углы: number[] = []
    for (let у = 0; у <= раскрытие.угловойРадиусЗоны; у += шагКольца) углы.push(у)
    return углы.map((у) => ({
      было: у,
      стало: у + отъездОтОси(у, раскрытие.угловойРадиусЗоны, раскрытие.угловойРадиусПроёма),
    }))
  }, [])

  const вПиксели = (угол: number) =>
    ПОЛЕ + ((ШИРИНА - ПОЛЕ * 2) * угол) / раскрытие.угловойРадиусЗоны
  const верх = ПОЛЕ + 20
  const низ = ВЫСОТА - ПОЛЕ - 20

  return (
    <Frame>
      <rect
        x={ПОЛЕ}
        y={низ - 10}
        width={вПиксели(раскрытие.угловойРадиусПроёма) - ПОЛЕ}
        height={20}
        fill="var(--чернила-слабые)"
        opacity="0.35"
      />
      {ряды.map((р, i) => (
        <g key={i}>
          <line
            x1={вПиксели(р.было)}
            y1={верх}
            x2={вПиксели(р.стало)}
            y2={низ}
            stroke="var(--чернила-слабые)"
            strokeWidth="1"
          />
          <circle cx={вПиксели(р.было)} cy={верх} r="3" fill="var(--чернила)" />
          <circle cx={вПиксели(р.стало)} cy={низ} r="3" fill="var(--чернила)" />
        </g>
      ))}
      <text x={ПОЛЕ} y={верх - 8} fill="var(--чернила)" fontSize="13">
        покой
      </text>
      <text x={ПОЛЕ} y={низ + 22} fill="var(--чернила)" fontSize="13">
        раскрыто · проём слева пуст
      </text>
    </Frame>
  )
}

/** Полоса прокрутки с отмеченными моментами.
 *
 *  Отметки считаются теми же функциями, что задают их сцене, поэтому
 *  схема не может разойтись с происходящим. */
export function DiagramScroll() {
  const отметки = useMemo(() => {
    const центр = new Vector3(0, сцена.высотаПарения, 0)
    const конСцены = конецСцены(
      прокрутка.разгораниеВЭкранах,
      прокрутка.нахлёстВЭкранах,
      прокрутка.экранов,
    )
    return {
      сцена: конСцены,
      светНачало: началоВспышки(
        прогрессВхода(путьПозиции, центр, сфера.радиус, вспышка.шаговПоиска),
        конСцены,
      ),
      светКонец: конецРазгорания(прокрутка.нахлёстВЭкранах, прокрутка.экранов),
    }
  }, [])

  const вПиксели = (доля: number) => ПОЛЕ + (ШИРИНА - ПОЛЕ * 2) * доля
  const полоса = ВЫСОТА / 2

  const метки: { доля: number; подпись: string }[] = [
    { доля: отметки.сцена, подпись: `сцена ${отметки.сцена.toFixed(2)}` },
    { доля: отметки.светКонец, подпись: `страница ${отметки.светКонец.toFixed(2)}` },
  ]

  return (
    <Frame>
      <rect
        x={ПОЛЕ}
        y={полоса - 10}
        width={вПиксели(отметки.сцена) - ПОЛЕ}
        height={20}
        fill="var(--чернила-слабые)"
        opacity="0.5"
      />
      <rect
        x={вПиксели(отметки.светНачало)}
        y={полоса - 10}
        width={вПиксели(отметки.светКонец) - вПиксели(отметки.светНачало)}
        height={20}
        fill="var(--чернила)"
        opacity="0.25"
      />
      <line
        x1={ПОЛЕ}
        y1={полоса + 10}
        x2={ШИРИНА - ПОЛЕ}
        y2={полоса + 10}
        stroke="var(--чернила)"
        strokeWidth="1"
      />
      {метки.map((м) => (
        <g key={м.подпись}>
          <line
            x1={вПиксели(м.доля)}
            y1={полоса - 22}
            x2={вПиксели(м.доля)}
            y2={полоса + 10}
            stroke="var(--чернила)"
            strokeWidth="1"
          />
          <text
            x={вПиксели(м.доля)}
            y={полоса - 28}
            fill="var(--чернила)"
            fontSize="13"
            textAnchor="middle"
          >
            {м.подпись}
          </text>
        </g>
      ))}
      <text x={ПОЛЕ} y={полоса + 32} fill="var(--чернила)" fontSize="13">
        0
      </text>
      <text
        x={ШИРИНА - ПОЛЕ}
        y={полоса + 32}
        fill="var(--чернила)"
        fontSize="13"
        textAnchor="end"
      >
        1
      </text>
    </Frame>
  )
}

/** Время кадра по точкам прокрутки: медиана и хвост.
 *
 *  Единственная схема на странице, которая рисуется по ЗАПИСАННЫМ данным,
 *  а не считается на месте. Производительность нельзя вывести из кода —
 *  её можно только измерить, и рядом с числами обязаны стоять условия
 *  замера. Они в lib/landing/measurements.ts. */
/** Гребень горного кольца: крупные вершины и то, что делает из них хребет.
 *
 *  Тонкой линией — только крупные вершины, восемь гладких колоколов.
 *  Толстой — итоговый гребень с отрогами. Разница между ними и есть весь
 *  ответ на вопрос, чем гора отличается от насыпи: пересечения колоколов
 *  дают изломы, которых у одиночного колокола быть не может. */
export function DiagramHorizon() {
  const кольцо = горы.кольца[0]
  const { основа, гребень } = useMemo(() => {
    const считать = создатьГребень(кольцо.вершины, горы.дробление, горы.зерно + кольцо.радиус)
    const n = 720
    // Показывается треть круга: на всех 360 градусах отроги сливаются в
    // штриховку и разницы с колоколом не видно — а она здесь главное.
    const сектор = (Math.PI * 2) / 3
    const углы = Array.from({ length: n + 1 }, (_, i) => (сектор * i) / n)
    return {
      основа: углы.map((у) => профильКольца(у, кольцо.вершины)),
      гребень: углы.map((у) => считать(у)),
    }
  }, [кольцо])

  const макс = Math.max(...гребень)
  const путь = (значения: number[]) =>
    значения
      .map((в, i) => {
        const px = ПОЛЕ + ((ШИРИНА - ПОЛЕ * 2) * i) / (значения.length - 1)
        const py = ВЫСОТА - ПОЛЕ - ((ВЫСОТА - ПОЛЕ * 2) * в) / макс
        return `${i === 0 ? 'M' : 'L'}${px.toFixed(1)} ${py.toFixed(1)}`
      })
      .join(' ')

  return (
    <Frame>
      <path
        d={путь(основа)}
        fill="none"
        stroke="var(--чернила-слабые)"
        strokeWidth="1"
      />
      <path d={путь(гребень)} fill="none" stroke="var(--чернила)" strokeWidth="1.5" />
      <text x={ПОЛЕ} y={ПОЛЕ} fill="var(--чернила)" fontSize="13">
        {макс.toFixed(0)} м
      </text>
    </Frame>
  )
}

export function DiagramNumbers() {
  const язык = useЯзык((с) => с.язык)
  const подписи = ТЕКСТЫ[язык].замеры

  const макс = Math.max(...ЗАМЕРЫ.точки.map((т) => т.хвост))
  const шаг = (ШИРИНА - ПОЛЕ * 2) / ЗАМЕРЫ.точки.length
  const толщина = шаг * 0.42
  const низ = ВЫСОТА - ПОЛЕ - 14

  return (
    <Frame>
      {ЗАМЕРЫ.точки.map((т, i) => {
        const x = ПОЛЕ + i * шаг + шаг / 2
        const вМедианы = ((низ - ПОЛЕ) * т.медиана) / макс
        const вХвоста = ((низ - ПОЛЕ) * т.хвост) / макс
        return (
          <g key={т.ключ}>
            {/* Хвост стоит позади медианы более бледным: так видно и то,
                и другое, и не нужно двух рядов столбиков. */}
            <rect
              x={x - толщина / 2}
              y={низ - вХвоста}
              width={толщина}
              height={вХвоста}
              fill="var(--чернила-слабые)"
            />
            <rect
              x={x - толщина / 2}
              y={низ - вМедианы}
              width={толщина}
              height={вМедианы}
              fill="var(--чернила)"
              opacity="0.55"
            />
            <text x={x} y={низ - вХвоста - 6} fill="var(--чернила)" fontSize="13" textAnchor="middle">
              {т.медиана} / {т.хвост}
            </text>
            <text x={x} y={низ + 16} fill="var(--чернила)" fontSize="12" textAnchor="middle" opacity="0.6">
              {подписи.точки[т.ключ]}
            </text>
          </g>
        )
      })}
      <line x1={ПОЛЕ} y1={низ} x2={ШИРИНА - ПОЛЕ} y2={низ} stroke="var(--чернила)" strokeWidth="1" />
    </Frame>
  )
}

