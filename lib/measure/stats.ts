/** Медиана выборки.
 *
 *  Не среднее. Среднее по временам кадров врёт: один кадр, в который
 *  влезла сборка мусора или переключение вкладки, тянет его вверх на
 *  десятки процентов, и в отчёт попадает число, которого зритель не
 *  видел ни разу. Медиана к таким выбросам глуха.
 *
 *  Выборка копируется перед сортировкой: сортировка на месте испортила бы
 *  массив вызывающего, а он обычно нужен ещё и для других сводок. */
export function медиана(выборка: number[]): number {
  if (выборка.length === 0) return 0
  const по = [...выборка].sort((а, б) => а - б)
  const середина = Math.floor(по.length / 2)
  return по.length % 2 === 0 ? (по[середина - 1] + по[середина]) / 2 : по[середина]
}

/** Значение, ниже которого лежит заданная доля выборки.
 *
 *  Нужен именно хвост, а не только медиана: рывок раз в двадцать кадров
 *  зритель чувствует, а медиана его не показывает вовсе. Отчёт без хвоста
 *  выглядит красиво и ничего не говорит о том, дёргается ли картинка. */
export function квантиль(выборка: number[], доля: number): number {
  if (выборка.length === 0) return 0
  const по = [...выборка].sort((а, б) => а - б)
  const место = Math.min(по.length - 1, Math.max(0, Math.ceil(доля * по.length) - 1))
  return по[место]
}

/** Кадров в секунду из времени кадра в миллисекундах. Ноль в ноль, а не
 *  в бесконечность: нулевое время означает, что мерить не удалось. */
export function кадровВСекунду(мс: number): number {
  return мс > 0 ? 1000 / мс : 0
}
