/**
 * Добывает CC0-материалы с ambientCG, конвертирует в WebP и раскладывает
 * в public/textures.
 *
 * Запускается ВРУЧНУЮ: `npm run textures`. Частью сборки скрипт быть не
 * должен. Если сделать его частью, деплой начнёт зависеть от чужого
 * сайта: сменится адрес, упадёт источник, включится ограничение по
 * частоте запросов — и сборка ляжет на хостинге, а не у вас. Готовые
 * WebP лежат в репозитории.
 */
import { execFile } from 'node:child_process'
import { mkdir, rm, writeFile } from 'node:fs/promises'
import path from 'node:path'
import { promisify } from 'node:util'

import sharp from 'sharp'

const выполнить = promisify(execFile)

const КОРЕНЬ = path.resolve(import.meta.dirname, '..')
const ВЫХОД = path.join(КОРЕНЬ, 'public', 'textures')
const ВРЕМЕННАЯ = path.join(КОРЕНЬ, '.textures-tmp')

/**
 * Качество WebP по типам карт.
 *
 * Живёт здесь, а не в lib/config.ts, намеренно: конфиг попадает в
 * браузерный пакет, и настройки сборки в нём — балласт, который скачает
 * каждый посетитель.
 *
 * У нормалей качество выше остальных: артефакты сжатия в карте нормалей
 * превращаются не в размытие, а в рябь освещения — глаз читает её как
 * грязь на поверхности.
 */
const КАЧЕСТВО = { color: 82, 'normal-gl': 92, roughness: 82 }

/**
 * Сторона карты после уменьшения, пиксели.
 *
 * Исходники ambientCG приходят в 2K, и это ВДВОЕ больше, чем сцена
 * способна показать. Считается это, а не выбирается на глаз: тайл земли
 * укладывается в три метра, значит 2K даёт 683 текселя на метр, а ближний
 * метр земли занимает на экране около сотни пикселей — камера никогда не
 * опускается ниже шести метров над снегом. Даже с шестикратным запасом на
 * скользящий угол 1K избыточен. У кирпича запас ещё больше: тайл в
 * полметра при 1K — это две тысячи текселей на метр против трёх сотен
 * пикселей у кирпича в самом крупном плане.
 *
 * Плата за прежние 2K была настоящей: карта нормалей снега весила 2.2 МБ
 * и в одиночку тянулась три секунды — половина всей первой загрузки ради
 * подробностей, которых не видно.
 *
 * Мыло от скользящего угла лечится НЕ разрешением, а анизотропной
 * фильтрацией, и она включена (см. Snowfield.tsx). Разрешение здесь ни
 * при чём — это проверено на этапе текстур.
 */
const СТОРОНА = 1024

/**
 * Насыщенность карты цвета, доля от исходной.
 *
 * Снятый с натуры снег на фотографии почти всегда тёплый: свет вокруг
 * него жёлтый, и материал уносит в песочный. В кадре это читается не
 * снегом, а пустыней — палитра сцены должна быть почти обесцвеченной,
 * насыщенный цвет выдаёт игровую графику.
 *
 * Ноль убил бы и полезное: лёгкий разброс оттенка добавляет глубины.
 * Применяется только к цвету: обесцвечивать нормали и шероховатость
 * нельзя, в них хранится не цвет, а числа.
 */
const НАСЫЩЕННОСТЬ_ЦВЕТА = 0.25

/**
 * Панорама неба с polyhaven, HDRI 1K, «чистое небо» без запечённой
 * земли: своя земля уже есть в сцене, и вторая, из панорамы, проступала
 * бы за её краем.
 *
 * В отличие от материалов ниже, файл НЕ конвертируется в WebP и
 * НЕ проходит через sharp: WebP хранит восемь бит на канал, а панорама
 * нужна с полным диапазоном яркости — иначе она перестанет работать
 * источником освещения, ради которого её и берут. Файл просто качается
 * и кладётся как есть.
 */
const ПАНОРАМА = {
  адрес: 'https://dl.polyhaven.org/file/ph-assets/HDRIs/hdr/1k/snow_field_puresky_1k.hdr',
  выход: path.join(ВЫХОД, 'sky.hdr'),
}

const НАБОРЫ = [
  {
    источник: 'Snow006',
    префикс: 'snow',
    // NormalGL, а НЕ NormalDX. Отличаются знаком зелёного канала.
    // С DX свет на неровностях ложится наизнанку: выпуклости читаются
    // впадинами. На однородном насте это почти незаметно, и ошибка
    // доживает до этапа, где её уже никто не свяжет с текстурами.
    карты: { Color: 'color', NormalGL: 'normal-gl', Roughness: 'roughness' },
  },
  {
    источник: 'Ice002',
    префикс: 'ice',
    // Кирпичу нужны только нормали: цвет и шероховатость у него свои,
    // подобранные так, чтобы он оставался темнее снега.
    карты: { NormalGL: 'normal-gl' },
  },
]

async function добытьПанораму() {
  console.log('качаю панораму неба')
  await выполнить('curl', ['-sL', '--max-time', '300', '-o', ПАНОРАМА.выход, ПАНОРАМА.адрес])
  console.log(`  ${path.basename(ПАНОРАМА.выход)}`)
}

async function добыть(набор) {
  const архив = path.join(ВРЕМЕННАЯ, `${набор.источник}.zip`)
  const адрес = `https://ambientcg.com/get?file=${набор.источник}_2K-PNG.zip`

  console.log(`качаю ${набор.источник}`)
  await выполнить('curl', ['-sL', '--max-time', '300', '-o', архив, адрес])
  await выполнить('unzip', ['-qo', архив, '-d', path.join(ВРЕМЕННАЯ, набор.источник)])

  for (const [исходная, имя] of Object.entries(набор.карты)) {
    const вход = path.join(
      ВРЕМЕННАЯ,
      набор.источник,
      `${набор.источник}_2K-PNG_${исходная}.png`,
    )
    const выход = path.join(ВЫХОД, `${набор.префикс}-${имя}.webp`)
    const конвейер = sharp(вход).resize(СТОРОНА, СТОРОНА)
    if (имя === 'color') конвейер.modulate({ saturation: НАСЫЩЕННОСТЬ_ЦВЕТА })
    await конвейер.webp({ quality: КАЧЕСТВО[имя] }).toFile(выход)
    console.log(`  ${path.basename(выход)}`)
  }
}

await rm(ВРЕМЕННАЯ, { recursive: true, force: true })
await mkdir(ВРЕМЕННАЯ, { recursive: true })
await mkdir(ВЫХОД, { recursive: true })

for (const набор of НАБОРЫ) await добыть(набор)
await добытьПанораму()

await writeFile(
  path.join(ВЫХОД, 'SOURCES.md'),
  [
    '# Откуда взяты текстуры',
    '',
    'Материалы с ambientCG под лицензией CC0: использование без',
    'ограничений и без указания авторства.',
    '',
    ...НАБОРЫ.map((н) => `- \`${н.префикс}-*\` — ambientCG ${н.источник}`),
    '',
    '- `sky.hdr` — polyhaven «Snow Field (Pure Sky)», лицензия CC0.',
    '  Формат HDR, не WebP: нужен полный диапазон яркости для освещения.',
    '',
    'Обновить набор: `npm run textures`.',
    '',
  ].join('\n'),
)

await rm(ВРЕМЕННАЯ, { recursive: true, force: true })
console.log('готово')
