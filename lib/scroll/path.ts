import { CatmullRomCurve3, Vector3 } from 'three'

import { траектория } from '@/lib/config'

/** Кривые пути камеры, построенные ОДИН раз на весь срок жизни страницы.
 *
 *  Живут отдельным модулем, а не внутри компонента камеры, потому что
 *  нужны двоим: камере — вести кадр, вспышке — узнать, на какой доле
 *  прокрутки камера входит внутрь сферы A. Две копии кривой означали бы,
 *  что правка траектории чинит одно и ломает другое.
 *
 *  Пересборка кривой Катмулла-Рома не бесплатна: она заново считает
 *  таблицу длин дуги, без которой getPointAt не даёт равномерного
 *  движения. Поэтому именно модульные константы, а не фабрика. */
export const путьПозиции = new CatmullRomCurve3(
  траектория.позиции.map(([x, y, z]) => new Vector3(x, y, z)),
)

export const путьЦели = new CatmullRomCurve3(
  траектория.цели.map(([x, y, z]) => new Vector3(x, y, z)),
)
