'use client'

import { RoundedBoxGeometry, useTexture } from '@react-three/drei'
import { useFrame, useThree } from '@react-three/fiber'
import { useLayoutEffect, useMemo, useRef } from 'react'
import { InstancedMesh, Matrix4, NoColorSpace, Quaternion, RepeatWrapping, Sphere, Vector2, Vector3 } from 'three'

import { материалКирпича, наведение, раскрытие, сфера, сцена, текстуры, траектория } from '@/lib/config'
import { подтянуть, цельСмещения } from '@/lib/hover/displacement'
import { размерыКирпича, разложитьКирпичи } from '@/lib/layout/bricks'
import {
  доляРаскрытия,
  нормальРаздела,
  поворотСтворки,
  сдвигСтворки,
  силаНаведения,
  сторонаКирпича,
} from '@/lib/opening/leaves'
import { useХранилищеПрокрутки } from '@/lib/scroll/store'
import { числоПовторов } from '@/lib/textures/tiling'

/** Набор путей вынесен на уровень модуля по той же причине, что и в
 *  Snowfield: литерал внутри компонента создавал бы новый объект на
 *  каждой отрисовке, useTexture получал бы новый ключ и заново
 *  приостанавливал дерево через Suspense — компонент пересобирался бы
 *  по кругу, а сцена не дорисовывалась до конца. */
const КАРТЫ_КИРПИЧА = {
  normalMap: текстуры.кирпич.нормали,
}

export default function BrickSphere() {
  const ссылка = useRef<InstancedMesh>(null)
  const кирпичи = useMemo(() => разложитьКирпичи(сфера), [])
  const размеры = useMemo(() => размерыКирпича(сфера), [])

  // Смещения живут в обычном массиве, а не в состоянии React: они
  // меняются каждый кадр, и перерисовка компонента на каждое движение
  // мыши положила бы страницу.
  const смещения = useRef(new Float32Array(кирпичи.length))

  // Невидимая гладкая сфера для луча. Пересечение с ней считается
  // аналитически. Луч по самим инстансам перебирал бы все 506 копий по
  // полторы сотни треугольников — семьдесят пять тысяч проверок на
  // каждое движение мыши, а их до ста двадцати в секунду.
  // Невидимая гладкая сфера для луча. Её центр НЕ задаётся числом, а
  // берётся из мировой позиции самого меша каждый кадр.
  //
  // Раньше он был жёстко в начале координат, и это сломалось молча, когда
  // сфера уехала в группу на высоту парения: невидимая сфера осталась под
  // землёй, луч перестал в неё попадать, наведение умерло. Ни тесты, ни
  // сборка этого не видят — математика отклонения покрыта, а привязка к
  // мировым координатам нет. Пусть центр следует за мешем сам.
  const сфераЛуча = useMemo(() => new Sphere(new Vector3(0, 0, 0), сфера.радиус), [])
  const косинусГраницы = useMemo(() => Math.cos(наведение.угловойРадиус), [])

  // Плоскость раздела створок. Направление входа берётся из конфига —
  // от ПРЕДПОСЛЕДНЕЙ точки траектории (последняя уже внутри сферы) к её
  // центру. Считается один раз, а не каждый кадр от настоящего положения
  // камеры: раздел обязан быть ОДИН И ТОТ ЖЕ на всём пути, иначе шов
  // поедет по кладке вслед за камерой.
  const нормаляРаздела = useMemo(() => {
    const предпоследняя = траектория.позиции[траектория.позиции.length - 2]
    const вход = new Vector3(
      -предпоследняя[0],
      сцена.высотаПарения - предпоследняя[1],
      -предпоследняя[2],
    ).normalize()
    return нормальРаздела(вход)
  }, [])

  // Принадлежность каждого кирпича к створке считается ОДИН РАЗ при
  // раскладке: она зависит только от нормали кирпича и от плоскости
  // раздела, а обе величины за время жизни сцены не меняются. В кадре
  // остаётся чтение из массива.
  const стороны = useMemo(
    () => Float32Array.from(кирпичи, (к) => сторонаКирпича(к.нормаль, нормаляРаздела)),
    [кирпичи, нормаляРаздела],
  )

  const карты = useTexture(КАРТЫ_КИРПИЧА)
  const { gl } = useThree()

  // Двумерный вектор силы рельефа: в конфиге одно число, но normalScale
  // материала применяет его к обеим осям карты одинаково.
  const силаРельефа = useMemo(
    () => new Vector2(текстуры.кирпич.сила, текстуры.кирпич.сила),
    [],
  )

  // Все рабочие объекты выделяются один раз. Создавать вектор или матрицу
  // внутри кадра — значит выбрасывать шестьдесят объектов в секунду
  // сборщику мусора, а он останавливает кадр в непредсказуемый момент.
  const точка = useRef(new Vector3())
  const направлениеНаКурсор = useRef(new Vector3())
  const центрМира = useRef(new Vector3())
  const матрица = useRef(new Matrix4())
  const положение = useRef(new Vector3())
  const поворотПлюс = useRef(new Quaternion())
  const поворотМинус = useRef(new Quaternion())
  const кватернионИтог = useRef(new Quaternion())
  const сдвигПлюс = useRef(new Vector3())
  const сдвигМинус = useRef(new Vector3())

  useLayoutEffect(() => {
    смещения.current.fill(0)
  }, [кирпичи])

  useLayoutEffect(() => {
    // Повтор считается от ширины кирпича, а не от стороны плоскости:
    // кирпич мелкий, и повтор в три метра (как у земли) растянул бы одну
    // текстуру на десяток кирпичей.
    const повторов = числоПовторов(размеры.ширина, текстуры.кирпич.метраж)

    карты.normalMap.wrapS = RepeatWrapping
    карты.normalMap.wrapT = RepeatWrapping
    карты.normalMap.repeat.set(повторов, повторов)
    карты.normalMap.anisotropy = gl.capabilities.getMaxAnisotropy()

    // Карта нормалей обязана остаться линейной. Пропустить её через sRGB —
    // значит увести освещение едва заметно и повсеместно, а искать причину
    // будут в свете, а не в текстуре.
    карты.normalMap.colorSpace = NoColorSpace

    карты.normalMap.needsUpdate = true
  }, [карты, gl, размеры.ширина])

  // Приоритет по умолчанию. Любой приоритет больше нуля отключает
  // автоматическую отрисовку в R3F, и экран чернеет без единой ошибки
  // в консоли.
  useFrame((состояние, шаг) => {
    const меш = ссылка.current
    if (!меш) return

    меш.getWorldPosition(центрМира.current)
    сфераЛуча.center.copy(центрМира.current)

    состояние.raycaster.setFromCamera(состояние.pointer, состояние.camera)
    const попал = состояние.raycaster.ray.intersectSphere(сфераЛуча, точка.current)

    // Точка касания приходит в мировых координатах, а нормали кирпичей
    // посчитаны вокруг начала координат группы. Без вычитания центра
    // направление считалось бы от начала мира, и отклонение уезжало бы
    // тем сильнее, чем выше поднята сфера.
    const направление = попал
      ? направлениеНаКурсор.current.copy(точка.current).sub(центрМира.current).normalize()
      : null

    // Прогресс читается через getState(), а не хуком: хук перерисовывал
    // бы компонент на каждый пиксель прокрутки, а здесь всё императивно.
    const { прогресс } = useХранилищеПрокрутки.getState()
    const доля = доляРаскрытия(прогресс, раскрытие.начало, раскрытие.конец)
    const силаКурсора = силаНаведения(доля)

    // Повороты и сдвиги створок считаются ОДИН раз на кадр, а не на
    // кирпич: их всего по два на пятьсот шесть кирпичей.
    const угол = доля * раскрытие.максУгол
    const отступ = доля * раскрытие.сдвиг
    поворотСтворки(поворотПлюс.current, 1, угол)
    поворотСтворки(поворотМинус.current, -1, угол)
    сдвигСтворки(сдвигПлюс.current, 1, нормаляРаздела, отступ)
    сдвигСтворки(сдвигМинус.current, -1, нормаляРаздела, отступ)

    for (let i = 0; i < кирпичи.length; i++) {
      const к = кирпичи[i]
      const цель = цельСмещения(к.нормаль, направление, косинусГраницы, наведение.максСмещение)
      смещения.current[i] = подтянуть(смещения.current[i], цель, наведение.скорость, шаг)

      положение.current
        .copy(к.позиция)
        .addScaledVector(к.нормаль, смещения.current[i] * силаКурсора)
      кватернионИтог.current.copy(к.кватернион)

      // Ветка, а не безусловный поворот на нулевой угол: пока створки
      // закрыты, это пятьсот шесть лишних поворотов вектора и
      // умножений кватернионов в каждом кадре — то есть почти всю
      // прокрутку.
      if (доля > 0) {
        const плюс = стороны[i] > 0
        const поворот = плюс ? поворотПлюс.current : поворотМинус.current
        // Сперва поворот вокруг оси сферы, потом сдвиг вбок. Обратный
        // порядок повернул бы и сам сдвиг, и створки разъехались бы не
        // поперёк шва, а наискось — проём открылся бы мимо камеры.
        положение.current.applyQuaternion(поворот).add(плюс ? сдвигПлюс.current : сдвигМинус.current)
        // premultiply, а не multiply: поворот створки применяется В
        // СИСТЕМЕ СФЕРЫ, поверх собственной ориентации кирпича. Обратный
        // порядок повернул бы кирпич вокруг его же осей, и кладка
        // разъехалась бы веером вместо того, чтобы уехать целой створкой.
        кватернионИтог.current.premultiply(поворот)
      }

      матрица.current.compose(положение.current, кватернионИтог.current, к.масштаб)
      меш.setMatrixAt(i, матрица.current)
    }
    меш.instanceMatrix.needsUpdate = true
  })

  return (
    <instancedMesh ref={ссылка} args={[undefined!, undefined!, кирпичи.length]} castShadow>
      <RoundedBoxGeometry
        args={[размеры.ширина, размеры.высота, размеры.толщина]}
        radius={размеры.толщина * материалКирпича.фаска}
        smoothness={материалКирпича.гладкостьФаски}
      />
      <meshPhysicalMaterial
        color={материалКирпича.цвет}
        roughness={материалКирпича.шероховатость}
        metalness={материалКирпича.металличность}
        sheen={материалКирпича.контурноеСвечение}
        sheenRoughness={материалКирпича.шероховатостьСвечения}
        sheenColor={материалКирпича.цветСвечения}
        normalMap={карты.normalMap}
        normalScale={силаРельефа}
      />
    </instancedMesh>
  )
}
