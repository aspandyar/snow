'use client'

import { useLayoutEffect, useRef } from 'react'
import type { PlaneGeometry } from 'three'

import { рельеф, туман } from '@/lib/config'
import { высотаТумана, локальныеВМировые } from '@/lib/terrain/height'
import { высотаСцены } from '@/lib/terrain/scene-height'

export default function GroundFog() {
  const геометрия = useRef<PlaneGeometry>(null)

  // Вершины поднимаются по функции высоты после создания геометрии.
  //
  // Геометрия объявлена в разметке, а не построена императивно и передана
  // свойством — как в Snowfield.tsx. R3F убирает за собой только то, что
  // создал сам: императивно созданная сетка осталась бы висеть в
  // видеопамяти после каждого перемонтирования.
  useLayoutEffect(() => {
    const г = геометрия.current
    if (!г) return
    const позиции = г.attributes.position

    for (let i = 0; i < позиции.count; i++) {
      const [x, z] = локальныеВМировые(позиции.getX(i), позиции.getY(i))
      // Смещение идёт по локальной оси Z, которая после поворота станет
      // мировой вертикалью. Туман обязан повторять рельеф земли, а не
      // лежать плоским листом — иначе дюны будут торчать из него, как
      // из воды.
      позиции.setZ(i, высотаТумана(высотаСцены(x, z), туман.надЗемлёй))
    }
    позиции.needsUpdate = true

    // Нормали здесь пересчитывать не нужно: материал не освещается, и
    // они ни на что не влияют.
  }, [])

  return (
    <mesh rotation-x={-Math.PI / 2}>
      <planeGeometry
        ref={геометрия}
        args={[рельеф.размер, рельеф.размер, туман.сегментов, туман.сегментов]}
      />
      {/* Без освещения, прозрачный, с отключённой записью глубины — иначе
          туман закроет собой то, что должно сквозь него просвечивать, и
          вместо тумана получится матовое стекло. */}
      <meshBasicMaterial
        color={туман.цвет}
        transparent
        opacity={туман.непрозрачность}
        depthWrite={false}
      />
    </mesh>
  )
}
