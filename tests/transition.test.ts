import { describe, expect, it } from 'vitest'

import { порогНахлёста } from '@/lib/scroll/progress'
import {
  конецСцены,
  перегревВспышки,
  прогрессСцены,
  силаВспышки,
} from '@/lib/transition/flash'

// Числа свои, а не из конфига: тест ловит ошибку в формуле, а не краснеет
// от правки настройки.
const ПОРОГ = 0.5
const НАЧАЛО = 0.5
const КОНЕЦ = 0.88

describe('прогрессСцены', () => {
  it('растягивает прокрутку до порога на весь путь сцены', () => {
    expect(прогрессСцены(0, ПОРОГ)).toBe(0)
    expect(прогрессСцены(ПОРОГ / 2, ПОРОГ)).toBeCloseTo(0.5, 10)
    expect(прогрессСцены(ПОРОГ, ПОРОГ)).toBe(1)
  })

  it('после порога стоит на единице — сцена доиграла', () => {
    expect(прогрессСцены(0.8, ПОРОГ)).toBe(1)
    expect(прогрессСцены(1, ПОРОГ)).toBe(1)
  })

  it('не убывает', () => {
    let прежнее = -1
    for (let i = 0; i <= 100; i++) {
      const текущее = прогрессСцены(i / 100, ПОРОГ)
      expect(текущее).toBeGreaterThanOrEqual(прежнее)
      прежнее = текущее
    }
  })

  it('нулевой порог не роняет вычисление делением на ноль', () => {
    expect(прогрессСцены(0.5, 0)).toBe(1)
    expect(прогрессСцены(0.5, -1)).toBe(1)
  })
})

describe('сцена доигрывает до того, как лендинг закроет кадр', () => {
  // ЭТО ГЛАВНЫЙ ТЕСТ ЭТАПА. Именно отсутствие такой проверки дало
  // поломку: пороги раскрытия ставились отдельно от порога нахлёста, они
  // разошлись, и весь влёт внутрь сферы играл за заглушкой лендинга —
  // зритель его не видел вовсе, а ни один тест не покраснел.
  it('конец сцены никогда не заходит за порог нахлёста', () => {
    // Даже если долю сцены выкрутить в единицу вкусом, потолок держит.
    for (const экранов of [3, 4, 5, 6, 8]) {
      for (const нахлёст of [0, 0.5, 1, 2]) {
        for (const доля of [0.2, 0.5, 0.9, 1]) {
          const конец = конецСцены(доля, нахлёст, экранов)
          expect(конец).toBeLessThanOrEqual(порогНахлёста(нахлёст, экранов))
        }
      }
    }
  })

  it('к концу сцены она отыграна полностью', () => {
    for (const экранов of [3, 4, 5, 6, 8]) {
      for (const нахлёст of [0, 0.5, 1, 2]) {
        const конец = конецСцены(0.5, нахлёст, экранов)
        expect(прогрессСцены(конец, конец)).toBe(1)
      }
    }
  })

  it('скромная доля сцены проходит как есть, жадная ужимается', () => {
    // 4 экрана и нахлёст в 1 дают потолок 0.667.
    expect(конецСцены(0.5, 1, 4)).toBeCloseTo(0.5, 10)
    expect(конецСцены(0.9, 1, 4)).toBeCloseTo(порогНахлёста(1, 4), 10)
  })

  it('до конца сцена ещё не доиграла — иначе кадр стоял бы зря', () => {
    const конец = конецСцены(0.5, 1, 4)
    expect(прогрессСцены(конец - 0.01, конец)).toBeLessThan(1)
  })

  it('вспышка трогается не раньше, чем сцена доиграла', () => {
    const конец = конецСцены(0.5, 1, 4)
    expect(силаВспышки(конец - 0.01, НАЧАЛО, КОНЕЦ)).toBe(0)
  })
})

describe('силаВспышки', () => {
  it('до начала кадр живой, после конца залит целиком', () => {
    expect(силаВспышки(0, НАЧАЛО, КОНЕЦ)).toBe(0)
    expect(силаВспышки(0.5, НАЧАЛО, КОНЕЦ)).toBe(0)
    expect(силаВспышки(КОНЕЦ, НАЧАЛО, КОНЕЦ)).toBe(1)
    expect(силаВспышки(1, НАЧАЛО, КОНЕЦ)).toBe(1)
  })

  it('не убывает', () => {
    let прежнее = -1
    for (let i = 0; i <= 100; i++) {
      const текущее = силаВспышки(i / 100, НАЧАЛО, КОНЕЦ)
      expect(текущее).toBeGreaterThanOrEqual(прежнее)
      прежнее = текущее
    }
  })
})

describe('перегревВспышки', () => {
  it('на обоих концах нулевой', () => {
    // На нуле кадр ещё живой, на единице обязан сойтись РОВНО в цвет
    // подложки: иначе на стыке с лендингом останется светлая полоса.
    expect(перегревВспышки(0)).toBe(0)
    expect(перегревВспышки(1)).toBe(0)
  })

  it('в середине выходит на полную — это и делает вспышку вспышкой', () => {
    expect(перегревВспышки(0.5)).toBeCloseTo(1, 10)
  })

  it('зажат в границах при любом входе', () => {
    for (const с of [-5, -0.1, 0.3, 0.9, 1.5, 12]) {
      const п = перегревВспышки(с)
      expect(п).toBeGreaterThanOrEqual(0)
      expect(п).toBeLessThanOrEqual(1)
    }
  })
})
