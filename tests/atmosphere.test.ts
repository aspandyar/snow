import { describe, expect, it } from 'vitest'

import { горы, рельеф, снег } from '@/lib/config'
import { создатьСнежинки } from '@/lib/snow/flakes'
import {
  создатьГребень,
  создатьВысотуРельефа,
  высотаТумана,
  профильКольца,
  угловаяРазница,
  type ПараметрыРельефа,
} from '@/lib/terrain/height'

const параметры: ПараметрыРельефа = {
  зерно: 4242,
  наст: { амплитуда: 0.5, частота: 0.05, октав: 3 },
  дюны: [{ x: 0, z: 0, радиус: 40, высота: 5 }],
}

describe('туман по рельефу', () => {
  const земля = создатьВысотуРельефа(параметры)

  it('отстоит от земли ровно на заданную высоту в любой точке', () => {
    // Плоский лист срезал бы холмы, и дюны торчали бы из тумана,
    // как из воды. Туман обязан повторять рельеф.
    for (const [x, z] of [[0, 0], [15, -22], [-60, 40], [120, 120]]) {
      expect(высотаТумана(земля(x, z), 1.5) - земля(x, z)).toBeCloseTo(1.5, 12)
    }
  })

  it('над дюной поднимается вместе с ней', () => {
    const наДюне = высотаТумана(земля(0, 0), 1.5)
    const вдали = высотаТумана(земля(300, 300), 1.5)
    expect(наДюне).toBeGreaterThan(вдали)
  })
})

describe('профиль горного кольца', () => {
  const вершины = [
    { угол: 1, ширина: 0.5, высота: 18 },
    { угол: 3, ширина: 0.4, высота: 12 },
  ]

  it('замкнут: тот же угол плюс полный круг даёт то же самое', () => {
    // Кольцо замкнуто, и профиль обязан замкнуться вместе с ним. Считай
    // мы высоту от длины дуги, у шва сошлись бы два разных значения и по
    // всему кольцу прошла бы вертикальная ступенька.
    for (const угол of [0, 0.7, 1.2, 2.5, 4.4, 6.1]) {
      expect(профильКольца(угол + Math.PI * 2, вершины)).toBeCloseTo(
        профильКольца(угол, вершины),
        12,
      )
    }
  })

  it('вершина у самого шва не разрезается пополам', () => {
    // Вершина в нуле: слева от шва до неё «почти два π», справа «почти
    // ноль». Без кратчайшей угловой разницы половина горы исчезла бы.
    const ушва = [{ угол: 0, ширина: 0.5, высота: 20 }]
    expect(профильКольца(0.2, ушва)).toBeCloseTo(профильКольца(-0.2, ушва), 12)
    expect(профильКольца(Math.PI * 2 - 0.2, ушва)).toBeCloseTo(
      профильКольца(0.2, ушва),
      12,
    )
  })

  it('в вершине даёт её высоту', () => {
    expect(профильКольца(1, вершины)).toBeCloseTo(18, 6)
  })

  it('за подножием всех вершин ровно ноль', () => {
    expect(профильКольца(2, вершины)).toBe(0)
    expect(профильКольца(5, вершины)).toBe(0)
  })

  it('перекрывающиеся вершины НЕ складываются, берётся высшая', () => {
    // Сумма дала бы на пересечении двух гор купол, и они слились бы в
    // одну гладкую насыпь. Максимум оставляет там излом — ребро, ради
    // которого всё и затевалось.
    const рядом = [
      { угол: 0, ширина: 0.5, высота: 10 },
      { угол: 0, ширина: 0.5, высота: 5 },
    ]
    expect(профильКольца(0, рядом)).toBeCloseTo(10, 6)
  })
})

describe('кратчайшая угловая разница', () => {
  it('никогда не выходит за половину круга', () => {
    for (const [a, b] of [[0, 6.1], [6.1, 0], [3, -3], [-1, 1], [10, 0]]) {
      expect(Math.abs(угловаяРазница(a, b))).toBeLessThanOrEqual(Math.PI)
    }
  })

  it('через шов идёт коротким путём, а не длинным', () => {
    expect(угловаяРазница(0.1, Math.PI * 2 - 0.1)).toBeCloseTo(0.2, 12)
  })
})

describe('расстановка колец гор', () => {
  it('все кольца стоят за краем равнины', () => {
    // Кольцо внутри равнины воткнулось бы в снег и читалось бы не планом,
    // а торчащим из земли куском.
    for (const кольцо of горы.кольца) {
      expect(кольцо.радиус).toBeGreaterThan(рельеф.размер / 2)
    }
  })

  it('каждое следующее кольцо дальше предыдущего', () => {
    const радиусы = горы.кольца.map((к) => к.радиус)
    for (let i = 1; i < радиусы.length; i++) {
      expect(радиусы[i]).toBeGreaterThan(радиусы[i - 1])
    }
  })

  it('видимая высота растёт с дальностью, иначе дальние прячутся', () => {
    // Высота, делённая на дальность, — это и есть то, что видит глаз.
    // Сделай её одинаковой у всех колец, и дальние спрячутся за ближним
    // ровно за его силуэтом: три кольца сольются в одно.
    const видимые = горы.кольца.map(
      (к) => Math.max(...к.вершины.map((в) => в.высота)) / к.радиус,
    )
    for (let i = 1; i < видимые.length; i++) {
      expect(видимые[i]).toBeGreaterThan(видимые[i - 1])
    }
  })

  it('вершины разных колец не выстроены в затылок', () => {
    // Совпади углы, планы перестали бы читаться раздельно.
    for (let i = 1; i < горы.кольца.length; i++) {
      for (const своя of горы.кольца[i].вершины) {
        for (const чужая of горы.кольца[i - 1].вершины) {
          expect(Math.abs(угловаяРазница(своя.угол, чужая.угол))).toBeGreaterThan(0.1)
        }
      }
    }
  })
})

describe('дробление гребня', () => {
  const дробление = [
    { отрогов: 40, подъём: 0.3, доляШирины: 0.7 },
    { отрогов: 120, подъём: 0.16, доляШирины: 0.6 },
  ]
  const вершины = [
    { угол: 1, ширина: 0.5, высота: 40 },
    { угол: 4, ширина: 0.4, высота: 30 },
  ]

  it('гребень замкнут', () => {
    const гребень = создатьГребень(вершины, дробление, 7)
    for (const угол of [0.2, 1.1, 3.0, 4.6, 6.1]) {
      expect(гребень(угол + Math.PI * 2)).toBeCloseTo(гребень(угол), 10)
    }
  })

  it('на ровном месте отрогов не вырастает', () => {
    // Отрог поднимается НАД основой под собой, а не имеет своей высоты.
    // Иначе ровный горизонт между хребтами покрылся бы бугорками из
    // ниоткуда.
    const гребень = создатьГребень(вершины, дробление, 7)
    for (const угол of [2.2, 2.5, 5.5, 5.8]) {
      expect(гребень(угол)).toBe(0)
    }
  })

  it('гребень нигде не уходит ниже равнины', () => {
    const гребень = создатьГребень(вершины, дробление, 7)
    for (let i = 0; i < 2000; i++) {
      expect(гребень((i / 2000) * Math.PI * 2)).toBeGreaterThanOrEqual(0)
    }
  })

  it('рёбер на горе несколько, а не одно', () => {
    // Ровно то, ради чего дробление и заведено. Гладкий колокол даёт одну
    // вершину на гору; хребет обязан дать несколько, иначе он холм.
    // Шум этой проверки не проходил: с ним рёбер было меньше двух на
    // гору.
    const гребень = создатьГребень(вершины, дробление, 7)
    const шагов = 4000
    const значения = Array.from({ length: шагов }, (_, i) =>
      гребень((i / шагов) * Math.PI * 2),
    )
    let рёбер = 0
    for (let i = 1; i < шагов - 1; i++) {
      if (значения[i] > значения[i - 1] && значения[i] >= значения[i + 1]) рёбер++
    }
    expect(рёбер).toBeGreaterThan(20)
  })

  it('одно зерно даёт один и тот же хребет', () => {
    const первый = создатьГребень(вершины, дробление, 7)
    const второй = создатьГребень(вершины, дробление, 7)
    for (let i = 0; i < 100; i++) {
      const у = (i / 100) * Math.PI * 2
      expect(первый(у)).toBe(второй(у))
    }
  })

  it('разные зёрна дают разные хребты, иначе кольца повторяют друг друга', () => {
    const первый = создатьГребень(вершины, дробление, 7)
    const второй = создатьГребень(вершины, дробление, 8)
    const углы = Array.from({ length: 200 }, (_, i) => (i / 200) * Math.PI * 2)
    expect(углы.some((у) => Math.abs(первый(у) - второй(у)) > 0.5)).toBe(true)
  })
})

describe('раскладка снежинок', () => {
  it('все лежат внутри куба', () => {
    const { позиции } = создатьСнежинки(200, снег.коробка, снег.зерно)
    for (const координата of позиции) {
      expect(координата).toBeGreaterThanOrEqual(0)
      expect(координата).toBeLessThan(снег.коробка)
    }
  })

  it('фаза каждой снежинки лежит в полном круге', () => {
    // Фазы разводят качание: без разброса весь снег качался бы в такт и
    // читался бы колеблющейся сеткой, а не хаосом.
    const { фазы } = создатьСнежинки(200, снег.коробка, снег.зерно)
    for (const фаза of фазы) {
      expect(фаза).toBeGreaterThanOrEqual(0)
      expect(фаза).toBeLessThan(Math.PI * 2)
    }
  })

  it('одно зерно даёт одну и ту же раскладку', () => {
    // Без этого кадр перестал бы повторяться от перезагрузки к
    // перезагрузке, а тест стал бы невоспроизводимым.
    const первый = создатьСнежинки(50, снег.коробка, снег.зерно)
    const второй = создатьСнежинки(50, снег.коробка, снег.зерно)
    expect(Array.from(первый.позиции)).toEqual(Array.from(второй.позиции))
  })

  it('разные зёрна дают разные раскладки', () => {
    const первый = создатьСнежинки(50, снег.коробка, снег.зерно)
    const второй = создатьСнежинки(50, снег.коробка, снег.зерно + 1)
    expect(Array.from(первый.позиции)).not.toEqual(Array.from(второй.позиции))
  })
})
