'use client'

import { Canvas } from '@react-three/fiber'

import BrickAxes from './BrickAxes'
import BrickSphere from './BrickSphere'
import CameraRig from './CameraRig'
import FrameGate from './FrameGate'
import Measure from './Measure'
import ReadySignal from './ReadySignal'
import GroundFog from './GroundFog'
import { OuterLight, InnerLight } from './Lights'
import Postprocessing from './Postprocessing'
import Mountains from './Mountains'
import ScrollDriver from './ScrollDriver'
import Sky from './Sky'
import Snow from './Snow'
import Snowfield from './Snowfield'
import { сцена } from '@/lib/config'

type Свойства = {
  /** Зовётся один раз, когда сцена впервые нарисовала кадр. По нему
   *  снимается заслонка ожидания — см. SceneStage.tsx. */
  приГотовности: () => void
}

export default function SceneCanvas({ приГотовности }: Свойства) {
  return (
    <Canvas camera={{ position: сцена.камера.позиция, fov: сцена.камера.полеЗрения }}>
      {/* Толкатель прогресса ставится ПЕРВЫМ: обработчики useFrame при
          одинаковом приоритете вызываются в порядке подписки, и всё, что
          читает прогресс прокрутки из хранилища (камера ниже), должно
          получать уже посчитанное на этом кадре число, а не прошлое.
          Сам он ничего не рисует. */}
      <ScrollDriver />
      {/* Останавливает кадры, когда лендинг закрыл холст целиком. */}
      <FrameGate />
      {/* Замер включается только адресом ?measure и в обычном показе
          ничего не делает. */}
      <Measure />
      {/* Докладывает наружу о первом нарисованном кадре. Ставится рядом с
          замером: оба ничего не рисуют и только смотрят на сцену. */}
      <ReadySignal приГотовности={приГотовности} />
      {/* Камера ставится сразу за толкателем прогресса и по той же
          причине: она подписывается на useFrame следующей и обязана
          читать уже посчитанный на этом кадре прогресс. */}
      <CameraRig />
      {/* Заливка фона (<color attach="background">) сюда не возвращается:
          она и панорама неба спорят за один и тот же слот фона сцены, и
          заливка либо перекроет панораму, либо будет перекрыта ею — в
          обоих случаях одна из них лишняя. Цвет сцена.фон остаётся
          подложкой страницы в app/layout.tsx до первого кадра WebGL. */}
      <Sky />
      <OuterLight />
      <Snowfield />
      <GroundFog />
      {/* За краем равнины: замкнутым кольцом, а не стеной с одной
          стороны — камера облетает сферу, и открытый край равнины попадал
          бы в кадр. Рисуются после земли и тумана, но порядок здесь не
          важен: сортировка по глубине делает своё дело независимо от
          порядка в дереве. */}
      <Mountains />
      {/* Снег ставится ПОСЛЕ всего непрозрачного. Он прозрачный и в буфер
          глубины не пишет, так что рисоваться обязан поверх уже готовой
          картинки, иначе снежинки перед сферой окажутся под ней. */}
      <Snow />
      {/* Внутренний свет едет вместе со сферой: оба принадлежат объекту,
          а не сцене, и должны подниматься на одну высоту. */}
      <group position={[0, сцена.высотаПарения, 0]}>
        <BrickSphere />
        <InnerLight />
      </group>
      <BrickAxes />
      {/* Постобработка ставится ПОСЛЕДНЕЙ: она забирает готовый кадр
          сцены. Состав цепочки задаётся один раз и не меняется всю
          прокрутку — см. Postprocessing.tsx. */}
      <Postprocessing />
    </Canvas>
  )
}
