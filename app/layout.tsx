import type { Metadata } from "next";
import "./globals.css";

import { сцена } from "@/lib/config";

const НАЗВАНИЕ = 'snow'
const ОПИСАНИЕ =
  'Ледяная сфера из кирпичей над заснеженной равниной — трёхмерная сцена на прокрутке.'

export const metadata: Metadata = {
  title: НАЗВАНИЕ,
  description: ОПИСАНИЕ,
  // Описание для ссылки, которой делятся. Без него в мессенджере и в
  // ленте от сайта остаётся голый адрес: ни названия, ни строки о том,
  // что там внутри. Заголовок и описание берутся из тех же двух
  // переменных, что и обычные метаданные, — двух записей у одного и того
  // же текста быть не должно.
  openGraph: {
    title: НАЗВАНИЕ,
    description: ОПИСАНИЕ,
    type: 'website',
    locale: 'ru_RU',
  },
  twitter: { card: 'summary_large_image', title: НАЗВАНИЕ, description: ОПИСАНИЕ },
}

export default function RootLayout({ children }: LayoutProps<"/">) {
  return (
    // Язык разметки — русский: страница открывается по-русски, а
    // переключатель меняет его на лету (см. lib/landing/language.ts).
    // Задать его здесь по выбранному языку нельзя: выбор живёт в
    // localStorage, читается только в браузере, и сервер отдал бы другую
    // разметку, чем построил бы клиент.
    <html lang="ru" className="h-full antialiased">
      {/* Цвет подложки приходит переменной CSS из ОДНОГО значения в
          конфиге — того же, в которое сходится кадр на переходе. Второй
          записи у него быть не должно: разойдутся, и на стыке сцены со
          страницей появится граница.
          Без подложки страница прозрачна, и до первого кадра WebGL
          зритель с тёмной темой браузера видит чёрную вспышку вместо
          задуманного светлого снега. */}
      <body
        className="min-h-full flex flex-col"
        style={{ '--подложка': сцена.фон } as React.CSSProperties}
      >
        {children}
      </body>
    </html>
  );
}
