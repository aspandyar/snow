import { BlendFunction, Effect } from 'postprocessing'
import { Color, Uniform, Vector2 } from 'three'

/** ЕДИНСТВЕННЫЙ САМОПИСНЫЙ ШЕЙДЕР ПРОЕКТА.
 *
 *  Всё остальное в сцене собрано из готовых материалов и эффектов
 *  намеренно: свой шейдер — это риск и время. Здесь он оправдан, потому
 *  что готового «свет разрастается из точки на экране и выжигает кадр» не
 *  существует, а именно это и есть переход.
 *
 *  ВСЕ ИМЕНА ВНУТРИ GLSL ЛАТИНИЦЕЙ, в нарушение общего правила проекта, —
 *  и uniform-переменные, и местные. Это не небрежность: GLSL допускает в
 *  идентификаторах только ASCII. Кириллическая переменная роняет
 *  компиляцию шейдера с «syntax error» на строке, где имя выглядит
 *  совершенно нормально, — на этом уже обжёгся. Русскими остаются
 *  комментарии и всё, что живёт на стороне TypeScript.
 *
 *  ЧИСЕЛ В ШЕЙДЕРЕ НЕТ. Все пороги и радиусы приходят снаружи из
 *  lib/config.ts. В шейдере это правило важнее, чем где-либо ещё: число,
 *  зашитое в строку GLSL, не находит ни поиск по типам, ни компилятор —
 *  оно просто живёт там годами. */
const ФРАГМЕНТ = /* glsl */ `
uniform float amount;      // сила вспышки, 0..1
uniform float overshoot;   // насколько кадр сейчас ярче цвета подложки
uniform vec2 origin;       // экранное положение шарика в координатах текстуры
uniform vec3 tint;         // цвет, в который сходится кадр
uniform float aspect;      // ширина к высоте: без неё круг станет овалом
uniform float reach;       // до какой доли экрана дорастает фронт
uniform float softness;    // ширина размытия фронта

void mainImage(const in vec4 inputColor, const in vec2 uv, out vec4 outputColor) {
  // Расстояние до центра вспышки. По горизонтали умножается на отношение
  // сторон: в координатах текстуры экран всегда квадрат от нуля до
  // единицы, и без поправки фронт растекался бы овалом.
  vec2 d = uv - origin;
  d.x *= aspect;
  float dist = length(d);

  // Фронт растёт от нуля до reach. Дальность считается с запасом за
  // единицу, иначе углы кадра остаются нетронутыми в самом конце: угол
  // дальше от центра, чем край.
  float front = amount * reach;
  float glow = 1.0 - smoothstep(front - softness, front, dist);

  // Перегрев уводит цвет заливки выше подложки — это и делает вспышку
  // вспышкой. На краях вспышки он нулевой, и кадр сходится РОВНО в цвет
  // страницы: иначе на стыке с лендингом останется светлая полоса.
  vec3 fill = mix(tint, vec3(1.0), overshoot);

  outputColor = vec4(mix(inputColor.rgb, fill, glow), inputColor.a);
}
`

/** Обёртка эффекта. Значения uniform-переменных меняются каждый кадр
 *  императивно, а сам эффект создаётся ОДИН раз: библиотека постобработки
 *  пересобирает цепочку при смене состава и падает на сериализации
 *  объектов сцены. */
export class ЭффектВспышки extends Effect {
  constructor() {
    super('ЭффектВспышки', ФРАГМЕНТ, {
      blendFunction: BlendFunction.NORMAL,
      uniforms: new Map<string, Uniform>([
        ['amount', new Uniform(0)],
        ['overshoot', new Uniform(0)],
        ['origin', new Uniform(new Vector2(0.5, 0.5))],
        ['tint', new Uniform(new Color('#ffffff'))],
        ['aspect', new Uniform(1)],
        ['reach', new Uniform(1)],
        ['softness', new Uniform(0.1)],
      ]),
    })
  }

  /** Числовая переменная по имени. Возвращает сам Uniform, а не значение:
   *  вызывающий меняет .value на месте, без выделения объектов в кадре. */
  переменная(имя: string): Uniform {
    const у = this.uniforms.get(имя)
    if (!у) throw new Error(`ЭффектВспышки: нет переменной ${имя}`)
    return у
  }
}
