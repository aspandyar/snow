'use client'

import { create } from 'zustand'

/** Язык страницы. Русский первым: проект написан по-русски, и он же
 *  остаётся значением по умолчанию на сервере. */
export type Язык = 'ru' | 'en'

const КЛЮЧ = 'snow.язык'

interface ХранилищеЯзыка {
  язык: Язык
  задатьЯзык: (язык: Язык) => void
  /** Подхватить выбор, сделанный в прошлый раз. Вызывается ОДИН раз из
   *  эффекта после монтирования, а не при создании хранилища.
   *
   *  Причина в серверной отрисовке: на сервере localStorage нет, и если
   *  читать его при создании, разметка сервера и первая разметка клиента
   *  разойдутся. React такое чинит повторной отрисовкой и ругается в
   *  консоль. Поэтому сервер и первый кадр клиента всегда русские, а
   *  сохранённый выбор применяется следом. */
  вспомнить: () => void
}

export const useЯзык = create<ХранилищеЯзыка>((set) => ({
  язык: 'ru',

  задатьЯзык: (язык) => {
    set({ язык })
    try {
      window.localStorage.setItem(КЛЮЧ, язык)
    } catch {
      // Приватный режим запрещает запись. Язык всё равно переключился —
      // просто не переживёт перезагрузку. Ронять из-за этого страницу
      // нельзя.
    }
  },

  вспомнить: () => {
    try {
      const сохранённый = window.localStorage.getItem(КЛЮЧ)
      if (сохранённый === 'ru' || сохранённый === 'en') set({ язык: сохранённый })
    } catch {
      // См. выше.
    }
  },
}))
