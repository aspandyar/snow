import { генератор } from '@/lib/terrain/height'

export type Снежинки = {
  /** Тройки координат внутри куба со стороной `сторона`. */
  позиции: Float32Array
  /** По одному числу на снежинку: сдвиг фазы качания. Без него все
   *  снежинки качались бы в такт, как строй, и снегопад читался бы
   *  колеблющейся сеткой, а не хаосом. */
  фазы: Float32Array
}

/** Раскладка снежинок по кубу.
 *
 *  Считается ОДИН раз при сборке сцены. Дальше эти числа не меняются
 *  никогда: падение, повтор и качание живут в вершинном шейдере, и в
 *  кадре наружу уходит одна переменная — время. Пересчитывать полторы
 *  тысячи координат процессором в каждом кадре значило бы платить за то,
 *  что видеокарта делает даром.
 *
 *  Зерно обязательно: без него снег пересобирался бы при каждой
 *  перезагрузке — кадр перестал бы повторяться, а тест стал бы
 *  невоспроизводимым. Та же причина, что и у зерна рельефа, и тот же
 *  генератор. */
export function создатьСнежинки(частиц: number, сторона: number, зерно: number): Снежинки {
  const случайное = генератор(зерно)
  const позиции = new Float32Array(частиц * 3)
  const фазы = new Float32Array(частиц)

  for (let i = 0; i < частиц; i++) {
    позиции[i * 3] = случайное() * сторона
    позиции[i * 3 + 1] = случайное() * сторона
    позиции[i * 3 + 2] = случайное() * сторона
    // Фаза в пределах полного круга: шейдер подставляет её прямо в синус.
    фазы[i] = случайное() * Math.PI * 2
  }

  return { позиции, фазы }
}
