import { describe, expect, it } from 'vitest'
import { Vector3 } from 'three'

import { подтянуть, сглаженныйПереход, цельСмещения } from '@/lib/hover/displacement'

const УГЛОВОЙ_РАДИУС = 0.3
const КОСИНУС_ГРАНИЦЫ = Math.cos(УГЛОВОЙ_РАДИУС)
const МАКС = 0.3

describe('сглаженный переход', () => {
  it('зажимается по краям', () => {
    expect(сглаженныйПереход(0, 1, -5)).toBe(0)
    expect(сглаженныйПереход(0, 1, 5)).toBe(1)
  })

  it('в середине даёт половину', () => {
    expect(сглаженныйПереход(0, 1, 0.5)).toBeCloseTo(0.5, 12)
  })
})

describe('цель смещения', () => {
  const наКурсор = new Vector3(0, 1, 0)

  it('без курсора смещение нулевое', () => {
    expect(цельСмещения(new Vector3(0, 1, 0), null, КОСИНУС_ГРАНИЦЫ, МАКС)).toBe(0)
  })

  it('прямо под курсором смещение максимально', () => {
    expect(цельСмещения(new Vector3(0, 1, 0), наКурсор, КОСИНУС_ГРАНИЦЫ, МАКС)).toBeCloseTo(МАКС, 12)
  })

  it('за границей влияния смещение нулевое', () => {
    const далеко = new Vector3(Math.sin(0.5), Math.cos(0.5), 0)
    expect(цельСмещения(далеко, наКурсор, КОСИНУС_ГРАНИЦЫ, МАКС)).toBe(0)
  })

  it('на обратной стороне сферы смещение нулевое', () => {
    expect(цельСмещения(new Vector3(0, -1, 0), наКурсор, КОСИНУС_ГРАНИЦЫ, МАКС)).toBe(0)
  })

  it('смещение убывает с углом', () => {
    const ближе = new Vector3(Math.sin(0.1), Math.cos(0.1), 0)
    const дальше = new Vector3(Math.sin(0.2), Math.cos(0.2), 0)
    const а = цельСмещения(ближе, наКурсор, КОСИНУС_ГРАНИЦЫ, МАКС)
    const б = цельСмещения(дальше, наКурсор, КОСИНУС_ГРАНИЦЫ, МАКС)
    expect(а).toBeGreaterThan(б)
    expect(б).toBeGreaterThan(0)
  })
})

describe('подтягивание', () => {
  it('движется к цели', () => {
    expect(подтянуть(0, 1, 8, 1 / 60)).toBeGreaterThan(0)
    expect(подтянуть(0, 1, 8, 1 / 60)).toBeLessThan(1)
  })

  it('не зависит от частоты кадров', () => {
    // Главный смысл экспоненты. С линейной долей два полушага дали бы
    // не то же, что один целый, и на слабой машине кирпичи возвращались
    // бы медленнее, чем на быстрой.
    const целиком = подтянуть(0, 1, 8, 1 / 30)
    const половинками = подтянуть(подтянуть(0, 1, 8, 1 / 60), 1, 8, 1 / 60)
    expect(половинками).toBeCloseTo(целиком, 12)
  })

  it('в цели остаётся на месте', () => {
    expect(подтянуть(0.3, 0.3, 8, 1 / 60)).toBeCloseTo(0.3, 12)
  })
})
