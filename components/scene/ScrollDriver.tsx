'use client'

import { useFrame } from '@react-three/fiber'
import { useRef } from 'react'

import { прокрутка } from '@/lib/config'
import { догнатьПрогресс, прогрессПрокрутки } from '@/lib/scroll/progress'
import { useХранилищеПрокрутки } from '@/lib/scroll/store'

/** Толкатель прогресса прокрутки.
 *
 *  Каждый кадр читает положение прокрутки окна и высоту блока сцены,
 *  считает прогресс чистой функцией (lib/scroll/progress.ts) и кладёт
 *  результат в хранилище через setState — не хуком, см. store.ts.
 *
 *  Именно в кадре, а не по обработчику события scroll: событие приходит
 *  чаще кадра и заставляет считать впустую, а на мобильных ещё и
 *  запаздывает за инерцией прокрутки — посчитанное по нему число не
 *  успевает за пальцем.
 *
 *  Высота блока не измеряется через DOM, а вычисляется: блок в
 *  app/page.tsx построен как `прокрутка.экранов × 100dvh`, то есть его
 *  пиксельная высота — это высота окна, умноженная на то же число
 *  экранов. Так толкатель не зависит от разметки страницы и не тянет
 *  через неё ref.
 *
 *  Компонент должен стоять ПЕРВЫМ в дереве сцены (см. SceneCanvas.tsx):
 *  обработчики useFrame при одинаковом приоритете вызываются в порядке
 *  подписки, и камера, которая появится на следующем этапе, обязана
 *  прочитать уже посчитанный на этом кадре прогресс, а не прошлый.
 *
 *  В хранилище кладётся ДОГНАННОЕ значение, а не сырое положение
 *  прокрутки. У прокрутки колесом нет промежуточных значений: щелчок
 *  двигает камеру сразу на пять метров, и вся сцена читается показом
 *  слайдов, хотя кадры при этом идут исправно. Догон растягивает каждый
 *  щелчок на несколько кадров — см. догнатьПрогресс, там же объяснено,
 *  почему сглаживать надо здесь, а не в камере.
 *
 *  Ничего не рендерит — только считает и пишет в хранилище. */
export default function ScrollDriver() {
  // Догнанное значение живёт между кадрами и потому в ref, а не в
  // состоянии React: перерисовывать компонент шестьдесят раз в секунду
  // ради числа, которое читается императивно, значит положить сцену.
  // Пустое значение означает «первого кадра ещё не было».
  const догнанный = useRef<number | null>(null)

  // Приоритет по умолчанию. Любое значение больше нуля отключает в R3F
  // автоматическую отрисовку, и экран чернеет без единой ошибки в
  // консоли — на этом уже обжигались.
  useFrame((_, шаг) => {
    const высотаОкна = window.innerHeight
    const высотаБлока = прокрутка.экранов * высотаОкна
    const сдвиг = window.scrollY

    const цель = прогрессПрокрутки(сдвиг, высотаБлока, высотаОкна)
    догнанный.current = догнатьПрогресс(
      догнанный.current,
      цель,
      прокрутка.скоростьДогона,
      шаг,
    )
    useХранилищеПрокрутки.getState().задатьПрогресс(догнанный.current)
  })

  return null
}
