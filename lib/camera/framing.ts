/** Поле зрения, подогнанное под форму окна.
 *
 *  ЗАЧЕМ. У перспективной камеры в three поле зрения задаётся ПО
 *  ВЕРТИКАЛИ, а горизонтальный охват получается из него и отношения
 *  сторон. На широком экране это даёт задуманный кадр; на телефоне окно
 *  вытянуто вверх, горизонтальный охват падает вдвое с лишним — и общий
 *  план перестаёт читаться как «объект посреди равнины». Сфера крупная,
 *  простора нет, а к середине прокрутки она уже не помещается в кадр.
 *
 *  Лечится это не подбором отдельного числа для телефона (два числа,
 *  которые должны согласоваться, в этом проекте уже четырежды расходились),
 *  а пересчётом: чем у́же окно, тем шире поле зрения по вертикали, и
 *  горизонтальный охват держится тем же.
 *
 *  ПОЧЕМУ С ПРЕДЕЛОМ. Точная привязка на телефоне требует около 115
 *  градусов — это уже не кадр, а рыбий глаз: прямые линии выгибаются, а
 *  сфера уезжает в даль точкой. Предел останавливает пересчёт там, где
 *  простор вернулся, но искажение ещё не началось. Значит на узком экране
 *  горизонтальный охват всё равно меньше — полностью это лечится только
 *  другой траекторией, а не полем зрения. */
export function полеЗренияПоКадру(
  базовое: number,
  опорноеОтношение: number,
  отношение: number,
  предел: number,
): number {
  // Окно шире опорного — не трогаем. Сужать поле зрения на широком
  // экране значило бы обрезать то, ради чего его туда и поставили.
  if (отношение >= опорноеОтношение) return базовое

  // Половина угла в тангенсах: именно тангенс половины угла линейно
  // связан с размером кадра на единичной дальности, поэтому пересчёт
  // делается на нём, а не на самом угле. Градусы в радианы и обратно —
  // отсюда π/360 и 360/π вместо привычных π/180.
  const тангенс = Math.tan((базовое * Math.PI) / 360) * (опорноеОтношение / отношение)
  return Math.min((360 / Math.PI) * Math.atan(тангенс), предел)
}
