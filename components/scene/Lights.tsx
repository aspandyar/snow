'use client'

import { useFrame } from '@react-three/fiber'
import { useMemo, useRef } from 'react'
import { Vector3 } from 'three'
import type { Mesh, MeshStandardMaterial } from 'three'

import { вспышка, прокрутка, свет, сфера, сцена } from '@/lib/config'
import { путьПозиции } from '@/lib/scroll/path'
import { useХранилищеПрокрутки } from '@/lib/scroll/store'
import {
  конецРазгорания,
  конецСцены,
  началоВспышки,
  прогрессВхода,
  силаВспышки,
} from '@/lib/transition/flash'

// Рассеянный свет и солнце принадлежат сцене и остаются на месте, даже
// когда сфера поднимается над равниной.
//
// ТЕНЕЙ В СЦЕНЕ НЕТ. Тень от сферы лежала на снегу вытянутым серым пятном
// и портила кадр: равнина светлая и почти без деталей, пятно на ней
// читается грязью, а не опорой. Отказ от тени убрал заодно целый проход
// отрисовки — карту теней 2048 приходилось перерисовывать каждый кадр
// ради одного этого пятна.
export function ВнешнийСвет() {
  return (
    <>
      <ambientLight intensity={свет.рассеянный} />
      <directionalLight
        position={свет.солнце.положение}
        intensity={свет.солнце.яркость}
        color={свет.солнце.цвет}
      />
    </>
  )
}

// Точечный источник и самосветящийся шарик принадлежат сфере: у точечного
// ограничена дальность (лежит в конфиге), и он обязан ехать вместе со
// сферой наверх, иначе она погаснет изнутри.
export function ВнутреннийСвет() {
  const шарик = useRef<Mesh>(null)
  const вещество = useRef<MeshStandardMaterial>(null)
  const центр = useMemo(() => new Vector3(0, сцена.высотаПарения, 0), [])

  // Момент, с которого шарик начинает разгораться, — тот же, что у
  // доводки кадра в Postprocessing.tsx, и считается той же формулой.
  // Два отдельных числа здесь разъехались бы: свет пошёл бы от экрана
  // раньше или позже, чем от тела.
  const окно = useMemo(
    () => ({
      начало: началоВспышки(
        прогрессВхода(путьПозиции, центр, сфера.радиус, вспышка.шаговПоиска),
        конецСцены(прокрутка.доляСцены, прокрутка.нахлёстВЭкранах, прокрутка.экранов),
      ),
      конец: конецРазгорания(прокрутка.нахлёстВЭкранах, прокрутка.экранов),
    }),
    [центр],
  )

  // Во сколько раз шарик раздувается на полном разгорании. Считается из
  // двух радиусов, а не задаётся отдельным множителем: множитель молча
  // разъехался бы с радиусом покоя при первой же его правке.
  const рост = свет.шарик.радиусРазгоревшийся / свет.шарик.радиус

  useFrame(() => {
    const меш = шарик.current
    const мат = вещество.current
    if (!меш || !мат) return

    const { прогресс } = useХранилищеПрокрутки.getState()
    const разгорание = силаВспышки(прогресс, окно.начало, окно.конец)

    // Масштаб, а не пересборка геометрии: менять радиус sphereGeometry в
    // кадре значит каждый кадр строить заново пару сотен треугольников и
    // заливать их в видеопамять.
    меш.scale.setScalar(1 + (рост - 1) * разгорание)
    мат.emissiveIntensity =
      свет.шарик.яркость +
      (свет.шарик.яркостьРазгоревшаяся - свет.шарик.яркость) * разгорание
  })

  return (
    <>
      <pointLight
        position={[0, 0, 0]}
        intensity={свет.точечный.яркость}
        distance={свет.точечный.дальность}
        decay={свет.точечный.затухание}
      />
      <mesh ref={шарик}>
        <sphereGeometry args={[свет.шарик.радиус, свет.шарик.сегменты, свет.шарик.сегменты]} />
        {/* Шарик ничего не освещает: он только ярко виден через щели, а
            на переходе разгорается и раздувается, съедая кладку ореолом.
            toneMapped выключен, иначе тональная компрессия срежет
            яркость выше единицы и весь смысл пропадёт. */}
        <meshStandardMaterial
          ref={вещество}
          color="#000000"
          emissive={свет.шарик.цвет}
          emissiveIntensity={свет.шарик.яркость}
          toneMapped={false}
        />
      </mesh>
    </>
  )
}
