import { подтянуть } from '@/lib/hover/displacement'

// Прогресс прокрутки от нуля до единицы.
// Сдвиг делится на расстояние, которое вообще можно пролистать (высотаБлока − высотаОкна).
// Последний экран уже виден, когда прокрутка дошла до конца, поэтому путь меньше высоты блока.
export function прогрессПрокрутки(
  сдвиг: number,
  высотаБлока: number,
  высотаОкна: number
): number {
  // Прокручиваемый путь — это не высота блока, а (высотаБлока − высотаОкна)
  const путь = высотаБлока - высотаОкна

  // Защита от деления на ноль: если путь нулевой или отрицательный, блок не прокручивается
  if (путь <= 0) {
    return 0
  }

  // Прогресс — пролистанная часть делится на прокручиваемый путь
  const прогресс = сдвиг / путь

  // Зажимаем результат в границах [0, 1]
  return Math.max(0, Math.min(1, прогресс))
}

// Порог, при котором нахлёст начинает закрывать сцену.
// Нахлёст съедает прокрутку с конца: страница начинает закрывать кадр раньше, чем траектория доиграна.
// Формула: 1 − нахлёст / (экранов − 1)
export function порогНахлёста(нахлёстВЭкранах: number, высотаВЭкранах: number): number {
  // Защита от деления на ноль: если экранов минус один равно нулю или меньше
  if (высотаВЭкранах <= 1) {
    return 0
  }

  // Порог вычисляется по формуле: 1 − нахлёст / (экранов − 1)
  const порог = 1 - нахлёстВЭкранах / (высотаВЭкранах - 1)

  // Зажимаем результат в границах [0, 1]
  return Math.max(0, Math.min(1, порог))
}

/** Догон прогресса за прокруткой, шаг за шагом.
 *
 *  ЗАЧЕМ ВООБЩЕ ДОГОНЯТЬ, а не брать положение прокрутки как есть.
 *  Потому что у прокрутки колесом нет промежуточных значений. Вся
 *  траектория камеры — шестьдесят восемь метров — укладывается примерно в
 *  тысячу двести пикселей прокрутки, а один щелчок колеса даёт около ста:
 *  на всё приближение приходится штук двенадцать положений, и камера
 *  прыгает по пять метров за раз. Кадры при этом идут исправно — просто
 *  показывать между щелчками нечего, и выглядит это ровно как показ
 *  слайдов. Ни одна оптимизация отрисовки такого не лечит: не хватает не
 *  кадров, а значений на входе.
 *
 *  Догон превращает двенадцать ступенек в непрерывное движение: цель
 *  скачет, а показанное значение подъезжает к ней за несколько кадров.
 *
 *  ОДНО ЗНАЧЕНИЕ НА ВСЮ СЦЕНУ. Догонять надо там же, где прогресс
 *  считается, и класть в хранилище уже сглаженный — иначе камера поедет
 *  плавно, а раскрытие и разгорание останутся на сырой прокрутке и
 *  разъедутся с ней. В этом проекте два числа, которые обязаны совпадать,
 *  расходились уже четырежды.
 *
 *  Экспонента, а не постоянная доля за кадр: доля привязала бы скорость
 *  догона к частоте кадров. То же соображение, что и у подтяжки кирпичей
 *  под курсором, и та же функция.
 *
 *  Пустое текущее значение — это первый кадр, и догонять на нём нечего:
 *  страницу могли перезагрузить посреди прокрутки, браузер вернёт
 *  положение сам, и догон устроил бы зрителю пролёт от начала пути к
 *  тому месту, где он и так стоит. */
export function догнатьПрогресс(
  текущее: number | null,
  цель: number,
  скорость: number,
  шаг: number,
): number {
  if (текущее === null) return цель
  return подтянуть(текущее, цель, скорость, шаг)
}
