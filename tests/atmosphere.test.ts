import { describe, expect, it } from 'vitest'

import { создатьВысотуРельефа, высотаТумана, type ПараметрыРельефа } from '@/lib/terrain/height'

const параметры: ПараметрыРельефа = {
  зерно: 4242,
  наст: { амплитуда: 0.5, частота: 0.05, октав: 3 },
  дюны: [{ x: 0, z: 0, радиус: 40, высота: 5 }],
}

describe('туман по рельефу', () => {
  const земля = создатьВысотуРельефа(параметры)

  it('отстоит от земли ровно на заданную высоту в любой точке', () => {
    // Плоский лист срезал бы холмы, и дюны торчали бы из тумана,
    // как из воды. Туман обязан повторять рельеф.
    for (const [x, z] of [[0, 0], [15, -22], [-60, 40], [120, 120]]) {
      expect(высотаТумана(земля(x, z), 1.5) - земля(x, z)).toBeCloseTo(1.5, 12)
    }
  })

  it('над дюной поднимается вместе с ней', () => {
    const наДюне = высотаТумана(земля(0, 0), 1.5)
    const вдали = высотаТумана(земля(300, 300), 1.5)
    expect(наДюне).toBeGreaterThan(вдали)
  })
})
