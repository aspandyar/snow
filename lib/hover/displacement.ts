import type { Vector3 } from 'three'

/** Плавный переход от нуля к единице между двумя краями. */
export function сглаженныйПереход(край0: number, край1: number, значение: number): number {
  const t = Math.min(1, Math.max(0, (значение - край0) / (край1 - край0)))
  return t * t * (3 - 2 * t)
}

/** На сколько метров кирпич должен отойти от поверхности.
 *
 *  Сравнение идёт по косинусу угла, а не по самому углу: арккосинус на
 *  полтысячи кирпичей в каждом кадре не нужен, а порог переводится в
 *  косинус один раз при чтении конфига. */
export function цельСмещения(
  нормаль: Vector3,
  направлениеНаКурсор: Vector3 | null,
  косинусГраницы: number,
  максСмещение: number,
): number {
  if (!направлениеНаКурсор) return 0
  const косинус = нормаль.dot(направлениеНаКурсор)
  return максСмещение * сглаженныйПереход(косинусГраницы, 1, косинус)
}

/** Подтягивание текущего значения к цели за шаг времени.
 *
 *  Экспонента, а не постоянная доля: доля привязала бы скорость возврата
 *  к частоте кадров, и на слабой машине кирпичи возвращались бы медленнее,
 *  чем на быстрой. С экспонентой два полушага в точности равны одному
 *  целому шагу. */
export function подтянуть(
  текущее: number,
  цель: number,
  скорость: number,
  шаг: number,
): number {
  return текущее + (цель - текущее) * (1 - Math.exp(-скорость * шаг))
}
