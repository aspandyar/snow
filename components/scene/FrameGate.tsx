'use client'

import { useThree } from '@react-three/fiber'
import { useEffect } from 'react'

import { прокрутка } from '@/lib/config'

/** Останавливает отрисовку, когда лендинг закрыл холст целиком.
 *
 *  Без этого сцена продолжает считаться под непрозрачной страницей: пять
 *  сотен кирпичей, тени, цепочка постобработки — и всё это в никуда, пока
 *  зритель читает текст. На ноутбуке это слышно вентилятором.
 *
 *  ОСТАНАВЛИВАЕТСЯ ИМЕННО ОТРИСОВКА, а не размонтируется холст.
 *  Размонтирование потеряло бы контекст WebGL: текстуры уехали бы из
 *  видеопамяти, и прокрутка обратно вверх ждала бы полной пересборки
 *  сцены с чёрным экраном вместо кадра. Возврат обязан быть мгновенным.
 *
 *  ПОДПИСКА НА СОБЫТИЕ ПРОКРУТКИ, а не чтение в кадре, — и это
 *  единственное место в проекте, где так. Причина простая: в кадре читать
 *  нечем, когда кадры остановлены. Обработчик события продолжает
 *  приходить и умеет их вернуть; обработчик кадра — нет. */
export default function FrameGate() {
  const задатьРежим = useThree((с) => с.setFrameloop)

  useEffect(() => {
    // Высота блока считается из конфига, а не измеряется по разметке:
    // блок построен как прокрутка.экранов × 100dvh, и прокручиваемый путь
    // — это высота окна, умноженная на число экранов минус один.
    const пересчитать = () => {
      const путь = (прокрутка.экранов - 1) * window.innerHeight
      // Строго больше или равно: ровно на этой отметке заглушка лендинга
      // встаёт вровень с верхом окна и закрывает кадр целиком.
      задатьРежим(window.scrollY >= путь ? 'never' : 'always')
    }

    пересчитать()
    window.addEventListener('scroll', пересчитать, { passive: true })
    window.addEventListener('resize', пересчитать)
    return () => {
      window.removeEventListener('scroll', пересчитать)
      window.removeEventListener('resize', пересчитать)
      // Режим возвращается принудительно: компонент могли снять во время
      // остановки, и тогда холст остался бы замороженным навсегда.
      задатьРежим('always')
    }
  }, [задатьРежим])

  return null
}
