'use client'

import { useFrame, useThree } from '@react-three/fiber'
import { Bloom, EffectComposer } from '@react-three/postprocessing'
import { useMemo, useRef } from 'react'
import { Color, Vector3 } from 'three'

import { вспышка, свечение, сцена } from '@/lib/config'
import { ЭффектВспышки } from '@/lib/transition/FlashEffect'
import { перегревВспышки, силаВспышки } from '@/lib/transition/flash'
import { useХранилищеПрокрутки } from '@/lib/scroll/store'

/** Обёртка эффекта вспышки в дерево R3F.
 *
 *  Эффект создаётся ОДИН раз и живёт всю прокрутку с силой ноль почти всё
 *  время. Убирать его из цепочки, когда он не нужен, нельзя: библиотека
 *  пересобирает цепочку при смене состава и падает на сериализации
 *  объектов сцены, а режим пропуска необратим — обратно шейдер уже не
 *  собирается. Это записано ещё в первой спеке проекта. */
function Вспышка() {
  const { camera, size } = useThree()
  const эффект = useMemo(() => new ЭффектВспышки(), [])

  // Рабочие объекты выделяются один раз вне кадра: сборщик мусора
  // останавливает кадр в непредсказуемый момент.
  const центрМира = useMemo(() => new Vector3(0, сцена.высотаПарения, 0), [])
  const проекция = useMemo(() => new Vector3(), [])

  useMemo(() => {
    эффект.переменная('tint').value = new Color(сцена.фон)
    эффект.переменная('reach').value = вспышка.дальность
    эффект.переменная('softness').value = вспышка.мягкость
  }, [эффект])

  useFrame(() => {
    const { прогресс } = useХранилищеПрокрутки.getState()
    const сила = силаВспышки(прогресс, вспышка.начало, вспышка.конец)

    эффект.переменная('amount').value = сила
    эффект.переменная('overshoot').value = перегревВспышки(сила)
    эффект.переменная('aspect').value = size.width / size.height

    // Центр вспышки — экранное положение шарика, а не число в конфиге.
    // Камера в конце прокрутки движется и влетает внутрь сферы; зашитый
    // центр уехал бы, и свет бил бы мимо источника.
    проекция.copy(центрМира).project(camera)
    const источник = эффект.переменная('origin').value as { x: number; y: number }
    // Из координат отсечения в координаты текстуры. Проекция за спиной
    // камеры даёт бессмыслицу, но здесь этого не случается: к моменту
    // вспышки камера смотрит ровно на шарик.
    источник.x = проекция.x * 0.5 + 0.5
    источник.y = проекция.y * 0.5 + 0.5
  })

  return <primitive object={эффект} dispose={null} />
}

/** Цепочка постобработки. Состав задаётся один раз и не меняется. */
export default function Постобработка() {
  return (
    <EffectComposer>
      {/* Свечение идёт ПЕРВЫМ: вспышка заливает кадр цветом подложки, и
          ореол от уже залитого кадра был бы ореолом от ровной заливки —
          то есть ничем. */}
      <Bloom
        mipmapBlur
        luminanceThreshold={свечение.порог}
        luminanceSmoothing={свечение.мягкость}
        intensity={свечение.сила}
        radius={свечение.радиус}
      />
      <Вспышка />
    </EffectComposer>
  )
}
