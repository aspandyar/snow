import { Quaternion, Vector3 } from 'three'

import { сглаженныйПереход } from '@/lib/hover/displacement'

/** Вертикальная ось. Не число проекта, а определение «верха» в правой
 *  тройке координат three: створки разворачиваются вокруг вертикали, и
 *  выбирать эту ось нечем. */
const ВЕРТИКАЛЬ = new Vector3(0, 1, 0)

/** Нормаль плоскости, по которой оболочка делится на две створки.
 *
 *  Плоскость проходит через вертикальную ось сферы и через направление,
 *  откуда прилетает камера. Значит её нормаль — горизонталь,
 *  перпендикулярная этому направлению.
 *
 *  Вертикальная составляющая направления входа отбрасывается намеренно:
 *  створки обязаны расходиться строго вбок. Если оставить наклон, шов
 *  поедет по диагонали, и «двустворчатая дверь» станет похожа на
 *  расколотую скорлупу. */
export function нормальРаздела(вход: Vector3): Vector3 {
  return new Vector3(вход.z, 0, -вход.x).normalize()
}

/** Сдвиг створки от плоскости раздела, в местных координатах сферы.
 *
 *  Одного разворота НЕ ХВАТАЕТ, и это выяснилось на картинке. Если
 *  поворачивать половины вокруг дальнего края шва, они уезжают вбок
 *  целиком, силуэт шара разваливается и вместо раскрытой сферы видно
 *  два бесформенных кома. Если поворачивать вокруг собственной оси
 *  сферы, форма сохраняется, но половины СХЛОПЫВАЮТСЯ сзади и проходят
 *  друг сквозь друга.
 *
 *  Поэтому движений два. Сдвиг вдоль нормали раздела разводит половины
 *  РОВНО НА СТОЛЬКО ЖЕ по всему шву, включая дальний край и полюса, где
 *  разворот почти ничего не даёт. Он и отвечает за то, что кирпичи не
 *  пересекаются. Разворот добавляется сверху и даёт ощущение
 *  распахнутой двери, а не двух разъехавшихся половинок. */
export function сдвигСтворки(
  цель: Vector3,
  сторона: number,
  нормальРаздела: Vector3,
  сдвиг: number,
): Vector3 {
  return цель.copy(нормальРаздела).multiplyScalar(сторона * сдвиг)
}

/** К какой створке принадлежит кирпич: +1 или −1.
 *
 *  Знак берётся от проекции нормали кирпича на нормаль раздела. Ноль
 *  уходит в +1, а не отбрасывается: кирпич обязан принадлежать какой-то
 *  створке, иначе он останется висеть в проёме. */
export function сторонаКирпича(нормаль: Vector3, нормальРаздела: Vector3): number {
  return нормаль.dot(нормальРаздела) >= 0 ? 1 : -1
}

/** Доля раскрытия от нуля до единицы по прогрессу прокрутки.
 *
 *  Считается ИЗ ПРОКРУТКИ, а не из расстояния до камеры: прокрутка —
 *  единственный источник времени в сцене, и одно её положение обязано
 *  давать одну и ту же картинку. Иначе кадр перестанет быть
 *  воспроизводимым, и «на моей машине выглядит иначе» станет нормой.
 *
 *  Переход сглаженный, а не линейный: линейный даёт излом скорости на
 *  обоих концах, и створки трогаются рывком. */
export function доляРаскрытия(прогресс: number, начало: number, конец: number): number {
  return сглаженныйПереход(начало, конец, прогресс)
}

/** Кватернион поворота створки на её угол.
 *
 *  Ось поворота — СОБСТВЕННАЯ вертикальная ось сферы, проходящая через
 *  её центр. Полюса на ней и остаются, поэтому силуэт шара не
 *  разваливается: половины проворачиваются по своей же поверхности.
 *
 *  Знак угла ОБРАТЕН стороне, и это не описка. Створка сдвинута вдоль
 *  нормали раздела в сторону своего знака; если крутить её в ту же
 *  сторону, разворот раскрывает ДАЛЬНИЙ край шва и поджимает ближний —
 *  тот самый, в который влетает камера. Проверено тестом: при сдвиге 3.5
 *  и угле 0.35 прямой знак оставлял у ближнего края 2.9 м вместо 11.1.
 *  Камера пролезала бы в щель, а распахивалось бы у неё за спиной.
 *
 *  Заполняет переданный кватернион, а не создаёт новый: вызывается в
 *  кадре. */
export function поворотСтворки(
  цель: Quaternion,
  сторона: number,
  угол: number,
): Quaternion {
  return цель.setFromAxisAngle(ВЕРТИКАЛЬ, -сторона * угол)
}

/** Во сколько раз ослабить отклонение кирпичей от курсора.
 *
 *  Наведение и раскрытие двигают одни и те же кирпичи. Складывать их в
 *  лоб нельзя: кирпич уехал бы на сумму двух смещений и вылез бы из
 *  створки. Поэтому наведение гаснет по мере раскрытия — к полностью
 *  распахнутым створкам отклик на курсор нулевой. Это ещё и честно по
 *  смыслу: когда сфера раскрылась, трогать кладку уже поздно. */
export function силаНаведения(раскрытие: number): number {
  return 1 - раскрытие
}
