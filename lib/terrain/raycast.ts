/** Точка в трёхмерном пространстве. */
export type Точка = { x: number; y: number; z: number }

/** Параметры марша луча. */
export type ПараметрыМарша = {
  /** Длина шага вдоль луча, метры. */
  шаг: number
  /** Дальность марша от начала луча, метры. */
  дальность: number
  /** Число делений отрезка пополам на уточнение точки пересечения. */
  уточнений: number
}

/** Функция высоты рельефа: x, z → высота земли в этой точке. */
export type ФункцияВысоты = (x: number, z: number) => number

/** Находит точку на земле под курсором маршем луча по функции высоты.
 *
 *  Пересекать луч с треугольниками земли (их сотни тысяч) стоило бы
 *  триста тысяч проверок на каждое движение мыши — а движений мыши до
 *  ста двадцати в секунду. Марш по функции высоты обходится десятками
 *  вычислений: шагаем вдоль луча, на каждом шаге сравниваем высоту луча
 *  с высотой снега под ним; как только луч оказался ниже поверхности —
 *  пересечение произошло между этим шагом и предыдущим, и остаётся
 *  уточнить его делением отрезка пополам.
 *
 *  Функция высоты приходит аргументом, а не импортируется: так её можно
 *  проверить на простых поверхностях — плоскости, наклоне — не завися
 *  от рельефа сцены. */
export function найтиТочкуНаЗемле(
  начало: Точка,
  направление: Точка,
  высота: ФункцияВысоты,
  п: ПараметрыМарша,
): Точка | null {
  const длина = Math.sqrt(
    направление.x * направление.x + направление.y * направление.y + направление.z * направление.z,
  )
  // Нулевое направление: шаг никогда не сдвинет луч с места, и без этой
  // проверки цикл ниже завис бы навсегда.
  if (длина === 0) return null

  const нx = направление.x / длина
  const нy = направление.y / длина
  const нz = направление.z / длина

  // Старт ниже снега: либо камера провалилась под землю, либо смотрит
  // изнутри рельефа. В обоих случаях искать пересечение бессмысленно —
  // луч дал бы точку позади камеры вместо точки под курсором.
  if (начало.y < высота(начало.x, начало.z)) return null

  const шагов = Math.ceil(п.дальность / п.шаг)

  let предыдущееT = 0

  for (let i = 1; i <= шагов; i++) {
    const t = Math.min(i * п.шаг, п.дальность)
    const x = начало.x + нx * t
    const y = начало.y + нy * t
    const z = начало.z + нz * t
    const высотаЗемли = высота(x, z)

    if (y < высотаЗемли) {
      // Пересечение между предыдущим шагом (луч ещё над землёй) и
      // текущим (луч уже под землёй). Уточняем делением пополам:
      // без этого точка легла бы на границу шага — до полутора
      // метров мимо места, на которое показывает курсор.
      let tНиз = предыдущееT
      let tВерх = t

      for (let j = 0; j < п.уточнений; j++) {
        const tСредний = (tНиз + tВерх) / 2
        const yСредний = начало.y + нy * tСредний
        const высотаЗемлиСредняя = высота(
          начало.x + нx * tСредний,
          начало.z + нz * tСредний,
        )
        const разностьСредняя = yСредний - высотаЗемлиСредняя

        if (разностьСредняя > 0) {
          tНиз = tСредний
        } else {
          tВерх = tСредний
        }
      }

      const tФинал = (tНиз + tВерх) / 2
      return {
        x: начало.x + нx * tФинал,
        y: начало.y + нy * tФинал,
        z: начало.z + нz * tФинал,
      }
    }

    предыдущееT = t
  }

  // Луч не оказался под землёй за всю дальность марша: направлен от
  // земли, либо параллелен поверхности и выше неё.
  return null
}
