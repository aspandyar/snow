'use client'

import { useFrame } from '@react-three/fiber'
import { useMemo, useRef } from 'react'
import { Color, NormalBlending } from 'three'
import type { ShaderMaterial } from 'three'

import { снег } from '@/lib/config'
import { создатьСнежинки } from '@/lib/snow/flakes'

/** ВТОРОЙ И ПОСЛЕДНИЙ САМОПИСНЫЙ ШЕЙДЕР ПРОЕКТА.
 *
 *  Как и у вспышки, все ИМЕНА ВНУТРИ GLSL ЛАТИНИЦЕЙ: язык допускает в
 *  идентификаторах только ASCII, а кириллическая переменная роняет
 *  компиляцию с «syntax error» на строке, которая выглядит совершенно
 *  нормально.
 *
 *  ЧИСЕЛ-НАСТРОЕК В ШЕЙДЕРЕ НЕТ, все приходят снаружи из lib/config.ts.
 *  Остаются только константы, которые настройками не являются: 0.0, 1.0,
 *  2.0 и половина — это определение системы координат точки, а не то, что
 *  кто-то захочет покрутить. */
const ВЕРШИННЫЙ = /* glsl */ `
uniform float time;        // секунды с начала показа
uniform float box;         // сторона куба со снегом, метры
uniform float speed;       // скорость падения, м/с
uniform float size;        // размер снежинки в пикселях на опорной дальности
uniform float pivot;       // опорная дальность, метры
uniform float sway;        // амплитуда бокового качания, метры
uniform float swayRate;    // частота качания, 1/с
uniform float fadeFrom;    // с какой дальности снежинка начинает гаснуть
uniform float fadeTo;      // где она гаснет полностью

attribute float phase;
varying float visibility;

void main() {
  // Куб привязан к КАМЕРЕ, а снежинка остаётся на месте в мире. Вычитание
  // положения камеры переводит её в систему куба, остаток от деления
  // возвращает внутрь: снежинка, ушедшая ниже дна, тем же выражением
  // оказывается под потолком. Поэтому снег не кончается никогда, куда бы
  // камера ни уехала, и при этом не едет за зрителем приклеенным.
  //
  // mod в GLSL для положительного делителя всегда даёт положительный
  // остаток — на этом всё и держится, обычный remainder дал бы дыру в
  // отрицательной половине.
  vec3 local = position - cameraPosition - vec3(0.0, time * speed, 0.0);
  vec3 wrapped = mod(local, box) - box * 0.5;

  // Качание добавляется ПОСЛЕ переноса: иначе снежинка у самой грани куба
  // качалась бы через границу и мигала.
  wrapped.x += sin(time * swayRate + phase) * sway;

  vec4 view = modelViewMatrix * vec4(cameraPosition + wrapped, 1.0);

  // Затухание к грани куба. Без него граница видна прямой линией, на
  // которой снег обрывается.
  visibility = 1.0 - smoothstep(fadeFrom, fadeTo, length(wrapped));

  // Размер падает с дальностью, как и положено перспективе, но ближе
  // опорной дальности расти перестаёт: снежинка вплотную к объективу
  // иначе раздувается в белое пятно на пол-экрана.
  gl_PointSize = size * pivot / max(-view.z, pivot);
  gl_Position = projectionMatrix * view;
}
`

const ФРАГМЕНТ = /* glsl */ `
uniform vec3 tint;
uniform float density;   // непрозрачность в середине снежинки
uniform float core;      // доля радиуса, остающаяся плотной

varying float visibility;

void main() {
  // Круг считается прямо здесь, а не берётся из карты: текстура ради
  // белого пятна — это лишний файл в отгрузке и лишняя выборка на каждый
  // пиксель каждой из полутора тысяч снежинок.
  //
  // gl_PointCoord идёт от нуля до единицы по квадрату точки, поэтому
  // середина — половина, а радиус приходится удваивать, чтобы получить
  // привычные 0..1 от центра к краю.
  float radius = length(gl_PointCoord - vec2(0.5)) * 2.0;
  if (radius > 1.0) discard;

  float softness = 1.0 - smoothstep(core, 1.0, radius);
  gl_FragColor = vec4(tint, density * visibility * softness);
}
`

/** Снег частицами: одна точечная система, движение целиком в шейдере.
 *
 *  Процессор в кадре не участвует вовсе — наружу уходит ОДНА переменная,
 *  время. Полторы тысячи снежинок стоят одного вызова отрисовки. */
export default function Snow() {
  const { позиции, фазы } = useMemo(
    () => создатьСнежинки(снег.частиц, снег.коробка, снег.зерно),
    [],
  )

  // Значения переменных собираются ОДИН раз: объект uniforms, созданный
  // заново при отрисовке, заставил бы three пересобирать шейдер.
  //
  // В кадре меняется только время, и меняется оно ЧЕРЕЗ САМ МАТЕРИАЛ, а
  // не через этот объект: набор переменных нужен отрисовке, а значение —
  // кадру, и путать эти два пути нельзя.
  const переменные = useMemo(() => ({
    time: { value: 0 },
    box: { value: снег.коробка },
    speed: { value: снег.скорость },
    size: { value: снег.размер },
    pivot: { value: снег.опора },
    sway: { value: снег.качание },
    swayRate: { value: снег.частотаКачания },
    // Обе границы затухания считаются от половины куба, а не задаются
    // порознь: это ровно та пара чисел, которая обязана совпадать с
    // размером коробки. Задай их отдельно — и правка коробки оставит
    // снег обрывающимся по старой границе.
    fadeFrom: { value: (снег.коробка / 2) * снег.началоЗатухания },
    fadeTo: { value: снег.коробка / 2 },
    tint: { value: new Color(снег.цвет) },
    density: { value: снег.плотность },
    core: { value: снег.ядро },
  }), [])

  const вещество = useRef<ShaderMaterial>(null)

  useFrame((состояние) => {
    const м = вещество.current
    if (!м) return
    м.uniforms.time.value = состояние.clock.elapsedTime
  })

  return (
    // frustumCulled выключен намеренно. Границы объекта three считает по
    // координатам вершин, а они лежат в кубе у начала координат — тогда
    // как рисуются снежинки вокруг камеры, где бы та ни была. С обычной
    // отсечкой снег пропадал бы целиком, стоит камере отъехать от центра
    // сцены, и это выглядело бы как сломанный компонент.
    <points frustumCulled={false}>
      <bufferGeometry>
        <bufferAttribute attach="attributes-position" args={[позиции, 3]} />
        <bufferAttribute attach="attributes-phase" args={[фазы, 1]} />
      </bufferGeometry>
      {/* Прозрачность есть, записи в буфер глубины нет: снежинки не
          должны загораживать друг друга ступеньками, а порядок между
          ними на глаз всё равно не читается.

          Смешивание ОБЫЧНОЕ, не складывающее. Складывающий свет на
          светлом фоне уводит снежинки в чистый белый, они пробивают порог
          свечения и дают по кадру мутную сыпь. На тёмном фоне выбор был
          бы обратным — у нас фон светлый. */}
      <shaderMaterial
        ref={вещество}
        vertexShader={ВЕРШИННЫЙ}
        fragmentShader={ФРАГМЕНТ}
        uniforms={переменные}
        transparent
        depthWrite={false}
        blending={NormalBlending}
      />
    </points>
  )
}
