import { describe, expect, it } from 'vitest'

import { кадровВСекунду, квантиль, медиана } from '@/lib/measure/stats'

describe('медиана', () => {
  it('берёт середину', () => {
    expect(медиана([3, 1, 2])).toBe(2)
    expect(медиана([4, 1, 3, 2])).toBe(2.5)
  })

  it('глуха к выбросу — ради этого она и выбрана вместо среднего', () => {
    const ровно = [16, 16, 17, 16, 17]
    const срывком = [16, 16, 17, 16, 400]
    expect(медиана(срывком)).toBe(медиана(ровно))
  })

  it('не портит переданную выборку', () => {
    const выборка = [3, 1, 2]
    медиана(выборка)
    expect(выборка).toEqual([3, 1, 2])
  })

  it('пустая выборка не роняет вычисление', () => {
    expect(медиана([])).toBe(0)
  })
})

describe('квантиль', () => {
  it('показывает хвост, которого медиана не видит', () => {
    const срывком = [16, 16, 16, 16, 16, 16, 16, 16, 16, 120]
    expect(медиана(срывком)).toBe(16)
    expect(квантиль(срывком, 0.95)).toBe(120)
  })

  it('крайние доли берут крайние значения', () => {
    const в = [1, 2, 3, 4, 5]
    expect(квантиль(в, 0)).toBe(1)
    expect(квантиль(в, 1)).toBe(5)
  })

  it('пустая выборка не роняет вычисление', () => {
    expect(квантиль([], 0.95)).toBe(0)
  })
})

describe('кадровВСекунду', () => {
  it('переводит время кадра в частоту', () => {
    expect(кадровВСекунду(16.67)).toBeCloseTo(60, 0)
    expect(кадровВСекунду(33.3)).toBeCloseTo(30, 0)
  })

  it('нулевое время даёт ноль, а не бесконечность', () => {
    // Ноль означает, что замер не удался, и бесконечность в отчёте была
    // бы хуже честного нуля.
    expect(кадровВСекунду(0)).toBe(0)
  })
})
