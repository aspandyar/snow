import { existsSync } from 'node:fs'
import path from 'node:path'

import { describe, expect, it } from 'vitest'

import { текстуры } from '@/lib/config'
import { числоПовторов } from '@/lib/textures/tiling'

describe('метраж на повтор', () => {
  it('делит сторону на метраж', () => {
    expect(числоПовторов(400, 4)).toBe(100)
    expect(числоПовторов(400, 2.5)).toBe(160)
  })

  it('не допускает нулевого и отрицательного метража', () => {
    // Ноль дал бы деление на ноль и бесконечное число повторов:
    // текстура схлопнулась бы в шум, а видеокарта — в свап.
    expect(() => числоПовторов(400, 0)).toThrow()
    expect(() => числоПовторов(400, -1)).toThrow()
  })
})

describe('файлы текстур', () => {
  // Эти проверки существуют ради одного: скачанные скриптом ассеты по
  // умолчанию попадают в исключения репозитория, и на хостинге сцена
  // падает с ошибкой 404 — в момент деплоя, дальше всего от места,
  // где это удобно чинить. Тест ловит пропажу до отправки.
  const пути = [
    текстуры.земля.цвет,
    текстуры.земля.нормали,
    текстуры.земля.шероховатость,
  ]

  it.each(пути)('файл %s лежит в public', (адрес) => {
    expect(existsSync(path.join(process.cwd(), 'public', адрес))).toBe(true)
  })

  it('используется вариант нормалей OpenGL, а не DirectX', () => {
    // Отличаются знаком зелёного канала. С DX свет на неровностях
    // ложится наизнанку: выпуклости читаются впадинами.
    expect(текстуры.земля.нормали).toContain('normal-gl')
    expect(текстуры.земля.нормали).not.toContain('dx')
  })
})
