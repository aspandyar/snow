'use client'

import { useLayoutEffect, useRef } from 'react'
import { useThree } from '@react-three/fiber'
import { useTexture } from '@react-three/drei'
import { NoColorSpace, RepeatWrapping, SRGBColorSpace, type PlaneGeometry } from 'three'

import { материалСнега, рельеф, следы, текстуры } from '@/lib/config'
import { локальныеВМировые } from '@/lib/terrain/height'
import { высотаСцены } from '@/lib/terrain/scene-height'
import { числоПовторов } from '@/lib/textures/tiling'

import { useКартаСледов } from './useTrail'

/** Набор путей к картам вынесен на уровень модуля намеренно.
 *
 *  Литерал внутри компонента создавал бы новый объект на каждой
 *  отрисовке. useTexture получал бы новый ключ, заново приостанавливал
 *  дерево через Suspense, компонент пересобирался — и так по кругу.
 *  В сети это видно как пятнадцать запросов вместо трёх, а на экране —
 *  как пустая сцена: отрисовка не доходит до конца ни разу. */
const КАРТЫ_ЗЕМЛИ = {
  map: текстуры.земля.цвет,
  normalMap: текстуры.земля.нормали,
  roughnessMap: текстуры.земля.шероховатость,
}

export default function Snowfield() {
  const геометрия = useRef<PlaneGeometry>(null)

  // Вершины поднимаются по функции высоты после создания геометрии.
  //
  // Геометрия объявлена в разметке, а не построена императивно и передана
  // свойством. Это принципиально: R3F убирает за собой только то, что
  // создал сам. Императивно созданная сетка на 148 тысяч вершин оставалась
  // бы в видеопамяти после каждого размонтирования — в сборке незаметно,
  // а в разработке строгий режим и горячая перезагрузка повторяют цикл
  // снова и снова, память кончается, контекст WebGL рвётся, и сцена
  // начинает мигать: появляется и гаснет.
  //
  // Освобождать её вручную в очистке эффекта тоже нельзя: строгий режим
  // размонтирует и монтирует заново, а useMemo возвращает ТОТ ЖЕ объект —
  // уже освобождённый, и сцена остаётся пустой.
  useLayoutEffect(() => {
    const г = геометрия.current
    if (!г) return
    const позиции = г.attributes.position

    for (let i = 0; i < позиции.count; i++) {
      const [x, z] = локальныеВМировые(позиции.getX(i), позиции.getY(i))
      // Смещение идёт по локальной оси Z, которая после поворота станет
      // мировой вертикалью.
      позиции.setZ(i, высотаСцены(x, z))
    }
    позиции.needsUpdate = true

    // Нормали пересчитываются после смещения: без этого вся земля
    // освещается как плоский лист и рельеф не читается вовсе.
    г.computeVertexNormals()

    // Карта затенения читается из канала uv1, которого у плоскости нет:
    // PlaneGeometry заводит только uv. Без этой строки aoMap молча не
    // применяется — ошибки нет, эффекта тоже. Развёртка та же самая,
    // поэтому канал просто указывает на существующий атрибут.
    if (!г.hasAttribute('uv1')) г.setAttribute('uv1', г.attributes.uv)
  }, [])

  const карты = useTexture(КАРТЫ_ЗЕМЛИ)
  const { gl } = useThree()
  const картаСледов = useКартаСледов()

  useLayoutEffect(() => {
    const повторов = числоПовторов(рельеф.размер, текстуры.земля.метраж)

    for (const карта of [карты.map, карты.normalMap, карты.roughnessMap]) {
      карта.wrapS = RepeatWrapping
      карта.wrapT = RepeatWrapping
      карта.repeat.set(повторов, повторов)

      // Анизотропная фильтрация — ПЕРВОЕ, что нужно включать при мыле.
      // Камера смотрит на снег скользяще, почти вдоль поверхности, и без
      // неё земля мылится независимо от разрешения карты: проблема не в
      // количестве пикселей, а в том, как они усредняются вдоль вытянутой
      // в перспективе ячейки. Значение берётся из возможностей видеокарты:
      // запрошенное сверх поддерживаемого молча игнорируется.
      карта.anisotropy = gl.capabilities.getMaxAnisotropy()

      карта.needsUpdate = true
    }

    // Цветовая карта декодируется как sRGB, остальные обязаны остаться
    // линейными. Если пропустить нормали через sRGB, освещение поедет
    // едва заметно и повсеместно — а искать причину будут в свете.
    карты.map.colorSpace = SRGBColorSpace
    карты.normalMap.colorSpace = NoColorSpace
    карты.roughnessMap.colorSpace = NoColorSpace
  }, [карты, gl])

  return (
    // Четверть оборота вокруг X кладёт плоскость горизонтально.
    // Знак отрицательный — именно он даёт мировую z равной минус
    // локальной y, что учтено в локальныеВМировые.
    <mesh rotation-x={-Math.PI / 2} receiveShadow>
      <planeGeometry
        ref={геометрия}
        args={[рельеф.размер, рельеф.размер, рельеф.сегментов, рельеф.сегментов]}
      />
      <meshStandardMaterial
        map={карты.map}
        normalMap={карты.normalMap}
        roughnessMap={карты.roughnessMap}
        roughness={материалСнега.шероховатость}
        metalness={материалСнега.металличность}
        // Формула встроенного смещения: normal * (карта.r * displacementScale
        // + displacementBias). Холст следов белый в состоянии покоя (r=1) и
        // темнеет под курсором (r→0) — см. useTrail.ts. Бias подобран так,
        // чтобы белый давал ровно ноль (следы.глубина − следы.глубина = 0) и
        // равнина оставалась на уровне, поднятом функцией высоты в
        // useLayoutEffect выше, а не вздувалась целиком под displacementScale.
        // Тёмный пиксель даёт (0 − следы.глубина) — смещение ПРОТИВ нормали,
        // то есть вмятину, а не бугор.
        // Тот же холст вторым назначением — картой затенения. Смещение
        // двигает вершины, но не пересчитывает нормали, и на однородном
        // белом снегу вмятина остаётся неразличимой: светотень не
        // меняется. Затенение даёт её напрямую.
        aoMap={картаСледов}
        aoMapIntensity={следы.затенение}
        displacementMap={картаСледов}
        displacementScale={следы.глубина}
        displacementBias={-следы.глубина}
      />
    </mesh>
  )
}
