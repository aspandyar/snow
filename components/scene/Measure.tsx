'use client'

import { useThree } from '@react-three/fiber'
import { useEffect } from 'react'

import { прокрутка } from '@/lib/config'
import { кадровВСекунду, квантиль, медиана } from '@/lib/measure/stats'

/** Режим замера. Включается только адресом `?measure`.
 *
 *  Отдельный режим, а не постоянный сбор: измерять на каждом показе
 *  значит платить за это кадром у всех зрителей, а нужно это раз в этап.
 *
 *  ЧТО ИМЕННО МЕРЯЕТСЯ. Время одного кадра целиком: подготовка сцены,
 *  обход пятисот кирпичей, отрисовка, цепочка постобработки. После
 *  каждого кадра из буфера читается ОДИН пиксель — это заставляет
 *  дождаться видеокарты. Без него замер показывал бы только время, за
 *  которое процессор успел отдать команды, а работа видеокарты уезжала бы
 *  в следующий кадр и в отчёт не попадала. Один пиксель, а не весь кадр:
 *  нужен сам факт ожидания, а не данные.
 *
 *  Замер идёт по нескольким положениям прокрутки, а не в одном: сцена в
 *  начале и на переходе — это разные объёмы работы, и одно число вместо
 *  трёх скрыло бы самое интересное. */
export default function Measure() {
  const состояние = useThree((с) => с.get)

  useEffect(() => {
    if (typeof window === 'undefined') return
    if (!new URLSearchParams(window.location.search).has('measure')) return

    let отменено = false

    const прогнать = async () => {
      const с = состояние()
      const холст = с.gl.domElement
      const кг = с.gl.getContext()
      const пиксель = new Uint8Array(4)
      const путь = (прокрутка.экранов - 1) * window.innerHeight
      const пауза = (мс: number) => new Promise((р) => setTimeout(р, мс))

      // ОЖИДАНИЕ ГОТОВНОСТИ. Первый замер вышел из одних нулей: он
      // стартовал сразу после монтирования, когда текстуры ещё грузились
      // и рисовать было нечего. Отчёт при этом получился внешне
      // правдоподобным — 0.1 мс на кадр — и это худший вид вранья:
      // цифра есть, а измерено ничего.
      //
      // Признак готовности — не таймер, а сам факт отрисовки: сцена
      // считается собранной, когда кадр даёт хоть один вызов отрисовки.
      for (let i = 0; i < ОЖИДАНИЙ; i++) {
        с.advance(performance.now())
        if (с.gl.info.render.calls > 0) break
        await пауза(100)
        if (отменено) return
      }
      if (с.gl.info.render.calls === 0) {
        console.warn('замер: сцена так и не собралась, цифр не будет')
        return
      }

      // Прогрев: первые кадры собирают шейдеры и заливают текстуры в
      // видеопамять. Их время к установившейся картинке отношения не
      // имеет, и включать их в отчёт значило бы соврать в худшую сторону.
      window.scrollTo(0, 0)
      for (let i = 0; i < ПРОГРЕВ; i++) {
        с.advance(performance.now())
        кг.readPixels(0, 0, 1, 1, кг.RGBA, кг.UNSIGNED_BYTE, пиксель)
      }

      const отчёт: Замер[] = []
      for (const точка of ТОЧКИ) {
        window.scrollTo(0, Math.round(путь * точка.доля))
        // Несколько холостых кадров: положение прокрутки меняет и камеру,
        // и раскрытие, и разгорание — им нужно доехать до нового
        // состояния, иначе замер поймает переходный процесс.
        for (let i = 0; i < УСПОКОЕНИЕ; i++) {
          с.advance(performance.now())
          кг.readPixels(0, 0, 1, 1, кг.RGBA, кг.UNSIGNED_BYTE, пиксель)
        }

        const времена: number[] = []
        // Счётчики отрисовки копятся ВРУЧНУЮ за все кадры и делятся в
        // конце. Автоматический сброс обнуляет их перед КАЖДЫМ проходом,
        // а проходов в кадре несколько: сцена, ступени свечения,
        // заливка. Прочитанное после цикла показывало бы только
        // последний проход — один полноэкранный треугольник. Первый
        // отчёт так и вышел: «1 вызов, 1 треугольник» на всю сцену из
        // пятисот кирпичей.
        с.gl.info.autoReset = false
        с.gl.info.reset()
        for (let i = 0; i < КАДРОВ; i++) {
          const до = performance.now()
          с.advance(performance.now())
          кг.readPixels(0, 0, 1, 1, кг.RGBA, кг.UNSIGNED_BYTE, пиксель)
          времена.push(performance.now() - до)
        }

        отчёт.push({
          точка: точка.имя,
          доля: точка.доля,
          медиана: +медиана(времена).toFixed(2),
          хвост: +квантиль(времена, 0.95).toFixed(2),
          кадров: Math.round(кадровВСекунду(медиана(времена))),
          вызововОтрисовки: Math.round(с.gl.info.render.calls / КАДРОВ),
          треугольников: Math.round(с.gl.info.render.triangles / КАДРОВ),
        })
        с.gl.info.autoReset = true
        if (отменено) return
      }

      window.scrollTo(0, 0)

      const итог = {
        снято: new Date().toISOString(),
        размерХолста: [холст.width, холст.height],
        программ: с.gl.info.programs?.length ?? 0,
        геометрий: с.gl.info.memory.geometries,
        текстур: с.gl.info.memory.textures,
        точки: отчёт,
      }

      // В глобальную переменную, а не только в консоль: отчёт нужно
      // забрать целиком и положить в lib/landing/measurements.ts, а
      // выковыривать его из консольного вывода — верный способ потерять
      // цифру.
      ;(window as unknown as { __замер: unknown }).__замер = итог
      console.log('замер', итог)
    }

    прогнать()
    return () => {
      отменено = true
    }
  }, [состояние])

  return null
}

/** Сколько раз проверить готовность сцены, с паузой в сотую долю секунды
 *  между попытками. Тридцать — это три секунды: столько хватает на
 *  распаковку трёх текстур 2K и панорамы неба даже с холодного диска. */
const ОЖИДАНИЙ = 30

/** Сколько кадров прогреть перед замером. Первые кадры собирают шейдеры и
 *  заливают текстуры — их время к установившейся картинке отношения не
 *  имеет. Тридцати хватает: дальше время выходит на полку. */
const ПРОГРЕВ = 30

/** Сколько холостых кадров дать после смены положения прокрутки. Камера,
 *  раскрытие и разгорание должны доехать до нового состояния, иначе замер
 *  поймает переходный процесс, а не то, что видит зритель. */
const УСПОКОЕНИЕ = 10

/** Сколько кадров усреднять. Сто — компромисс: меньше тридцати хвост
 *  становится случайным, больше двухсот замер тянется так долго, что в
 *  него влезает работа других вкладок. */
const КАДРОВ = 100

/** Положения прокрутки, в которых снимаются цифры. Это разные объёмы
 *  работы: на общем плане сфера мелкая и почти не закрывает экран, на
 *  раскрытии двигаются сотня кирпичей, на разгорании поверх всего идёт
 *  цепочка постобработки по всему кадру. */
const ТОЧКИ = [
  { имя: 'общий план', доля: 0 },
  { имя: 'облёт', доля: 0.3 },
  { имя: 'раскрытие', доля: 0.42 },
  { имя: 'разгорание', доля: 0.58 },
]

type Замер = {
  точка: string
  доля: number
  медиана: number
  хвост: number
  кадров: number
  вызововОтрисовки: number
  треугольников: number
}
