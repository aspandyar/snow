import { describe, expect, it } from 'vitest'
import { Vector3 } from 'three'

import {
  количествоВКольце,
  разложитьКирпичи,
  размерыКирпича,
  широтаКольца,
  type Кирпич,
  type ПараметрыРаскладки,
} from '@/lib/layout/bricks'

// Значения задаются здесь, а не берутся из lib/config.ts. Иначе тест
// покраснеет от безобидной правки числа, которое человек крутит руками.
const п: ПараметрыРаскладки = {
  радиус: 6,
  колец: 28,
  коэффициент: 1,
  толщина: 0.35,
  шов: 0.06,
  смещениеВразбежку: 0.5,
}

describe('кольца', () => {
  it('широта берётся в середине кольца, а не на границе', () => {
    // На границе широта нулевого кольца равнялась бы нулю, нормаль совпала
    // бы с мировой вертикалью, и векторное произведение для касательной
    // выродилось бы в нулевой вектор.
    expect(широтаКольца(28, 0)).toBeCloseTo(Math.PI / 56, 12)
    expect(широтаКольца(28, 0)).toBeGreaterThan(0)
  })

  it('широты симметричны относительно экватора', () => {
    expect(широтаКольца(28, 0) + широтаКольца(28, 27)).toBeCloseTo(Math.PI, 12)
  })

  it('количество в кольце следует формуле round(k · колец · sin θ)', () => {
    expect(количествоВКольце(п, 0)).toBe(2)
    expect(количествоВКольце(п, 1)).toBe(5)
    expect(количествоВКольце(п, 2)).toBe(8)
    expect(количествоВКольце(п, 3)).toBe(11)
    expect(количествоВКольце(п, 13)).toBe(28)
    expect(количествоВКольце(п, 27)).toBe(2)
  })

  it('в кольце никогда не бывает нуля кирпичей', () => {
    // При малом числе колец округление даёт ноль, и в сфере появляется дыра.
    const мелкая = { ...п, колец: 3, коэффициент: 1 }
    for (let кольцо = 0; кольцо < мелкая.колец; кольцо++) {
      expect(количествоВКольце(мелкая, кольцо)).toBeGreaterThanOrEqual(1)
    }
  })

  it('всего кирпичей 506 при 28 кольцах и коэффициенте 1', () => {
    let всего = 0
    for (let кольцо = 0; кольцо < п.колец; кольцо++) всего += количествоВКольце(п, кольцо)
    expect(всего).toBe(506)
  })
})

describe('раскладка', () => {
  const кирпичи = разложитьКирпичи(п)
  const ВЕРТИКАЛЬ = new Vector3(0, 1, 0)

  it('кирпичей ровно столько, сколько даёт формула', () => {
    expect(кирпичи.length).toBe(506)
  })

  it('все центры лежат на сфере радиуса R − толщина/2', () => {
    // Не R: radius в конфиге означает внешнюю поверхность кладки, то есть
    // то, что видно на экране, а не воображаемую срединную поверхность.
    const ожидаемый = п.радиус - п.толщина / 2
    for (const к of кирпичи) {
      expect(к.позиция.length()).toBeCloseTo(ожидаемый, 10)
    }
  })

  it('кватернионы нормированы', () => {
    for (const к of кирпичи) {
      expect(к.кватернион.length()).toBeCloseTo(1, 10)
    }
  })

  it('кирпичи не перекошены: касательная горизонтальна', () => {
    // Главный тест этапа. Поворот «из вектора в вектор» оставляет вращение
    // вокруг нормали незакреплённым, и кладка кренится — сфера собирается,
    // но кирпичи стоят пьяно. Здесь это ловится сразу.
    for (const к of кирпичи) {
      const касательная = new Vector3(1, 0, 0).applyQuaternion(к.кватернион)
      expect(Math.abs(касательная.dot(ВЕРТИКАЛЬ))).toBeLessThan(1e-9)
    }
  })

  it('локальная ось Z смотрит наружу', () => {
    for (const к of кирпичи) {
      const нормаль = new Vector3(0, 0, 1).applyQuaternion(к.кватернион)
      expect(нормаль.dot(к.позиция.clone().normalize())).toBeGreaterThan(0.999999)
    }
  })

  it('базис правосторонний', () => {
    // Левосторонний базис вывернет геометрию наизнанку: фаска окажется
    // внутри, а лицевые грани будут отбракованы отсечением задних граней.
    for (const к of кирпичи) {
      const x = new Vector3(1, 0, 0).applyQuaternion(к.кватернион)
      const y = new Vector3(0, 1, 0).applyQuaternion(к.кватернион)
      const z = new Vector3(0, 0, 1).applyQuaternion(к.кватернион)
      expect(new Vector3().crossVectors(x, y).distanceTo(z)).toBeLessThan(1e-9)
    }
  })

  it('поле нормаль совпадает с направлением от центра', () => {
    for (const к of кирпичи) {
      expect(к.нормаль.length()).toBeCloseTo(1, 10)
      expect(к.нормаль.dot(к.позиция.clone().normalize())).toBeGreaterThan(0.999999)
    }
  })
})

describe('размеры и масштаб', () => {
  const размеры = размерыКирпича(п)
  const кирпичи = разложитьКирпичи(п)

  it('кирпич вытянут ровно два к одному при коэффициенте 1', () => {
    expect(размеры.ширина / размеры.высота).toBeCloseTo(2, 12)
    expect(размеры.ширина).toBeCloseTo(1.3463968515, 8)
    expect(размеры.высота).toBeCloseTo(0.6731984258, 8)
  })

  it('коэффициент 2 даёт квадратную плитку', () => {
    const квадрат = размерыКирпича({ ...п, коэффициент: 2 })
    expect(квадрат.ширина / квадрат.высота).toBeCloseTo(1, 12)
  })

  it('масштаб по высоте и толщине одинаков у всех кирпичей', () => {
    for (const к of кирпичи) {
      expect(к.масштаб.y).toBeCloseTo(1 - п.шов, 12)
      expect(к.масштаб.z).toBeCloseTo(1, 12)
    }
  })

  it('вне полюсных колец ширина отклоняется меньше чем на 5%', () => {
    // Синусы в формуле сокращаются, поэтому ширина точно постоянна.
    // Портит её только округление количества, и заметно — лишь у полюсов.
    for (const к of кирпичи) {
      if (к.кольцо < 2 || к.кольцо > п.колец - 3) continue
      expect(к.масштаб.x / (1 - п.шов)).toBeGreaterThan(0.95)
      expect(к.масштаб.x / (1 - п.шов)).toBeLessThan(1.05)
    }
  })

  it('на полюсных кольцах ширина заметно меньше — это известное искажение', () => {
    // Округление 1.57 до 2 сужает кирпич на 21.5%. Затронуто по два
    // кирпича на полюс из 506. Тест фиксирует величину, чтобы она не
    // выросла незаметно при смене числа колец.
    const полюс = кирпичи.filter((к) => к.кольцо === 0)
    expect(полюс).toHaveLength(2)
    for (const к of полюс) {
      expect(к.масштаб.x / (1 - п.шов)).toBeCloseTo(0.785, 2)
    }
  })

  it('нечётные кольца сдвинуты вразбежку на полшага', () => {
    const первыйЧётного = кирпичи.find((к) => к.кольцо === 2 && к.номерВКольце === 0)!
    const первыйНечётного = кирпичи.find((к) => к.кольцо === 3 && к.номерВКольце === 0)!
    const долгота = (к: Кирпич) => Math.atan2(к.нормаль.z, к.нормаль.x)
    expect(Math.abs(долгота(первыйЧётного))).toBeLessThan(1e-9)
    expect(Math.abs(долгота(первыйНечётного))).toBeGreaterThan(1e-3)
  })

  it('соседи в кольце не пересекаются', () => {
    const радиусЦентров = п.радиус - п.толщина / 2
    for (const к of кирпичи) {
      const широта = широтаКольца(п.колец, к.кольцо)
      const количество = количествоВКольце(п, к.кольцо)
      const угловойШаг = (2 * Math.PI) / количество
      const угловаяШирина =
        (размеры.ширина * к.масштаб.x) / (радиусЦентров * Math.sin(широта))
      expect(угловаяШирина).toBeLessThan(угловойШаг)
    }
  })

  it('шов больше минимально допустимого', () => {
    // Ширина считается на внешней поверхности, а центры лежат глубже.
    // У внутренней грани кирпичи сходятся теснее, чем у внешней, и при
    // слишком малом шве внутренние рёбра пересекаются. Порог — толщина
    // делённая на два радиуса.
    expect(п.шов).toBeGreaterThan(п.толщина / (2 * п.радиус))
  })
})
