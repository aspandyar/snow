import { сглаженныйПереход } from '@/lib/hover/displacement'

/** Прогресс СЦЕНЫ из прогресса прокрутки.
 *
 *  Сцена обязана доиграть до того, как лендинг начнёт наезжать на кадр.
 *  Раньше это держалось на честном слове: пороги раскрытия ставились
 *  отдельно от порога нахлёста, и в какой-то момент разошлись — весь влёт
 *  внутрь сферы играл за заглушкой лендинга, зритель его не видел вовсе.
 *
 *  Теперь связь структурная. Камера и раскрытие получают не сырой
 *  прогресс, а этот: он растянут на отрезок до порога и дальше замер на
 *  единице. Подвинуть нахлёст, не подвинув сцену, физически нельзя —
 *  порог входит в формулу.
 *
 *  Порог ноль или меньше означает, что нахлёст съел всю прокрутку. Тогда
 *  сцена считается доигравшей сразу: делить на ноль нельзя, а показывать
 *  первый кадр вечно — хуже, чем показать последний. */
export function прогрессСцены(прогресс: number, порог: number): number {
  if (порог <= 0) return 1
  return Math.min(1, Math.max(0, прогресс / порог))
}

/** Сила вспышки от нуля до единицы по прогрессу прокрутки.
 *
 *  Считается из ПРОКРУТКИ, а не из прогресса сцены: вспышка живёт как раз
 *  в той трети, где сцена уже замерла, и от прогресса сцены не зависела бы
 *  вовсе. */
export function силаВспышки(прогресс: number, начало: number, конец: number): number {
  return сглаженныйПереход(начало, конец, прогресс)
}

/** Перегрев вспышки: насколько кадр в этот момент ярче цвета подложки.
 *
 *  Нужен, чтобы переход читался вспышкой, а не затуханием. Без него кадр
 *  просто плавно заливается цветом страницы, и «свет из шара» превращается
 *  в аккуратное исчезновение.
 *
 *  Колокол, а не рост: на нуле вспышки перегрева нет (кадр ещё живой), на
 *  единице тоже нет (кадр обязан сойтись РОВНО в цвет подложки, иначе на
 *  стыке с лендингом будет видна светлая полоса). Пик посередине. */
export function перегревВспышки(сила: number): number {
  const с = Math.min(1, Math.max(0, сила))
  return 4 * с * (1 - с)
}
