'use client'

import { useFrame } from '@react-three/fiber'
import { useRef } from 'react'

type Свойства = {
  /** Зовётся ОДИН раз, когда сцена впервые что-то нарисовала. */
  приГотовности: () => void
}

/** Сообщает наружу, что сцена ожила.
 *
 *  ПРИЗНАК ГОТОВНОСТИ — ФАКТ ОТРИСОВКИ, а не проценты загрузчика. Это уже
 *  выяснялось на этапе замеров: процент доходит до сотни раньше, чем
 *  текстура окажется в видеопамяти. Но у процентов есть беда похуже.
 *
 *  Когда файлы лежат в кеше браузера, загрузчик не заводит НИ ОДНОГО
 *  задания: считать нечего, всё уже есть. Счётчик остаётся нулевым, и
 *  экран ожидания, который ждёт «загружено = всего», висит вечно. Ловится
 *  это только у ВЕРНУВШЕГОСЯ зрителя — при первом заходе всё работает, и
 *  поэтому такую ошибку легко отгрузить.
 *
 *  Кадр, давший хоть один вызов отрисовки, врать не может: значит сцена
 *  собрана и нарисована. Счётчики читаются за ПРЕДЫДУЩИЙ кадр — useFrame
 *  вызывается до отрисовки, — и это ровно то, что нужно: к моменту снятия
 *  заслонки под ней уже готовая картинка, а не первый пустой кадр. */
export default function ReadySignal({ приГотовности }: Свойства) {
  const сообщено = useRef(false)

  useFrame((состояние) => {
    if (сообщено.current) return
    if (состояние.gl.info.render.calls === 0) return
    сообщено.current = true
    приГотовности()
  })

  return null
}
