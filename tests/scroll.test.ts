import { describe, expect, it } from 'vitest'

import { догнатьПрогресс, порогНахлёста, прогрессПрокрутки } from '@/lib/scroll/progress'

const ОКНО = 900
const БЛОК = ОКНО * 4

describe('прогресс прокрутки', () => {
  it('ноль в начале и единица в конце', () => {
    expect(прогрессПрокрутки(0, БЛОК, ОКНО)).toBe(0)
    expect(прогрессПрокрутки(БЛОК - ОКНО, БЛОК, ОКНО)).toBe(1)
  })

  it('середина пути даёт половину', () => {
    expect(прогрессПрокрутки((БЛОК - ОКНО) / 2, БЛОК, ОКНО)).toBeCloseTo(0.5, 12)
  })

  it('зажат в границах за пределами блока', () => {
    // Прокрутка вверх до отскока и вниз за конец блока не должны
    // выбрасывать камеру за края траектории.
    expect(прогрессПрокрутки(-500, БЛОК, ОКНО)).toBe(0)
    expect(прогрессПрокрутки(БЛОК * 10, БЛОК, ОКНО)).toBe(1)
  })

  it('НЕ зависит от высоты окна', () => {
    // Главное свойство: сцена зависит ровно от одного числа, и это число
    // одинаково на любом экране. Иначе кадр поедет при смене размера
    // окна и на мобильных, где адресная строка меняет высоту на ходу.
    const малое = прогрессПрокрутки((БЛОК - ОКНО) * 0.37, БЛОК, ОКНО)
    const большое = прогрессПрокрутки((ОКНО * 8 - ОКНО * 2) * 0.37, ОКНО * 8, ОКНО * 2)
    expect(малое).toBeCloseTo(большое, 12)
  })

  it('вырожденный блок не даёт деления на ноль', () => {
    expect(прогрессПрокрутки(100, ОКНО, ОКНО)).toBe(0)
    expect(прогрессПрокрутки(100, 0, ОКНО)).toBe(0)
  })
})

describe('порог нахлёста', () => {
  it('считается по формуле 1 − нахлёст / (экранов − 1)', () => {
    // Нахлёст съедает прокрутку с КОНЦА: страница начинает закрывать
    // кадр раньше, чем траектория доиграна.
    expect(порогНахлёста(1, 4)).toBeCloseTo(1 - 1 / 3, 12)
    expect(порогНахлёста(0.5, 4)).toBeCloseTo(1 - 0.5 / 3, 12)
  })

  it('без нахлёста порог равен единице', () => {
    expect(порогНахлёста(0, 4)).toBe(1)
  })

  it('больше нахлёст — раньше порог', () => {
    // Связь, из-за которой эти два числа нельзя править по отдельности:
    // сдвинешь нахлёст, не сдвинув пороги фаз, — страница полезет
    // поверх недоигранного перехода.
    expect(порогНахлёста(1.5, 4)).toBeLessThan(порогНахлёста(0.5, 4))
  })

  it('зажат в границах при нелепых значениях', () => {
    expect(порогНахлёста(99, 4)).toBe(0)
    expect(порогНахлёста(1, 1)).toBe(0)
  })
})

describe('догон прогресса', () => {
  it('первый кадр встаёт на цель без перелёта', () => {
    // Страницу могли перезагрузить посреди прокрутки: браузер вернёт
    // положение сам. Пустое текущее значение означает «первый кадр» — и
    // догонять тут нечего, иначе зритель увидит пролёт от начала пути к
    // тому месту, где он и так стоял.
    expect(догнатьПрогресс(null, 0.42, 12, 1 / 60)).toBe(0.42)
  })

  it('два полушага в точности равны одному целому', () => {
    // Свойство экспоненты, ради которого она и взята: скорость догона
    // одинакова на шестидесяти кадрах в секунду и на тридцати. С
    // постоянной долей за кадр сцена ехала бы медленнее на слабой машине
    // — то есть ровно там, где рывки и без того заметнее.
    const целиком = догнатьПрогресс(0, 1, 12, 0.1)
    const половина = догнатьПрогресс(догнатьПрогресс(0, 1, 12, 0.05), 1, 12, 0.05)
    expect(половина).toBeCloseTo(целиком, 12)
  })

  it('подходит к цели, но не перелетает её', () => {
    let значение = 0
    for (let i = 0; i < 200; i++) {
      значение = догнатьПрогресс(значение, 1, 12, 1 / 60)
      expect(значение).toBeLessThanOrEqual(1)
    }
    expect(значение).toBeCloseTo(1, 6)
  })

  it('огромный шаг не выбрасывает за цель', () => {
    // Первый кадр после возвращения на вкладку приходит с шагом в
    // несколько секунд. Экспонента при этом просто садится на цель, а
    // линейная подтяжка перелетела бы и качнулась обратно.
    expect(догнатьПрогресс(0, 1, 12, 30)).toBeCloseTo(1, 12)
  })

  it('нулевой шаг ничего не меняет', () => {
    expect(догнатьПрогресс(0.3, 0.9, 12, 0)).toBe(0.3)
  })
})
