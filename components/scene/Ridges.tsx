'use client'

import { useLayoutEffect, useRef } from 'react'
import type { PlaneGeometry } from 'three'

import { гряды, материалСнега } from '@/lib/config'
import { профильГряды, type Дюна } from '@/lib/terrain/height'

type СвойстваПлана = {
  расстояние: number
  ширина: number
  вершины: Дюна[]
}

/** Один план гряды: плоскость без толщины, изогнутая профилем по верхнему
 *  краю и утопленная под землю по нижнему, повёрнутая лицом к началу
 *  координат.
 *
 *  Компонент на план, а не общий цикл по гряды.планы внутри одного
 *  компонента: у каждого плана своя геометрия и свой хук её деформации,
 *  а хуки нельзя вызывать в цикле. */
function ПланГряды({ расстояние, ширина, вершины }: СвойстваПлана) {
  const геометрия = useRef<PlaneGeometry>(null)

  // Вершины поднимаются по профильГряды после создания геометрии.
  //
  // Геометрия объявлена в разметке, а не построена императивно и передана
  // свойством — как в Snowfield.tsx и GroundFog.tsx. R3F убирает за собой
  // только то, что создал сам: императивно созданная сетка осталась бы
  // висеть в видеопамяти после каждого перемонтирования.
  useLayoutEffect(() => {
    const г = геометрия.current
    if (!г) return
    const позиции = г.attributes.position

    for (let i = 0; i < позиции.count; i++) {
      const x = позиции.getX(i)
      // У PlaneGeometry с heightSegments=1 ровно два ряда вершин: верхний
      // на +высота/2, нижний на −высота/2. Верхний несёт силуэт гряды,
      // нижний утоплен под равнину на гряды.заглубление — без запаса между
      // подножием плоскости и краем равнины остаётся щель, сквозь которую
      // видна пустота за сценой.
      const y = позиции.getY(i) > 0 ? профильГряды(x, вершины) : -гряды.заглубление
      позиции.setY(i, y)
    }
    позиции.needsUpdate = true

    // Нормали пересчитываются после смещения — иначе весь план освещается
    // как плоский лист и силуэт гряды не читается вовсе.
    г.computeVertexNormals()
  }, [вершины])

  return (
    // Плоскость без толщины: объёма на таком расстоянии всё равно не
    // разглядеть, он тонет в дымке. Разворот к началу координат не нужен
    // отдельным поворотом — у PlaneGeometry нормаль по умолчанию смотрит
    // вдоль +Z, а отрицательная Z в позиции уводит план за дальний край
    // равнины, то есть нормаль уже смотрит на начало координат.
    <mesh position={[0, 0, -расстояние]}>
      <planeGeometry ref={геометрия} args={[ширина, 1, гряды.сегментов, 1]} />
      {/* Цвет — тот же, что у снега, и это принципиально: гряда не
          красится отдельно, а бледнеет от уже настроенной дымки (fogExp2
          в Sky.tsx). Крашеный вручную план разъехался бы с землёй по тону
          при первой же правке тумана. Карт нет — подробности на такой
          дальности не видны. */}
      <meshStandardMaterial
        color={материалСнега.цвет}
        roughness={материалСнега.шероховатость}
        metalness={материалСнега.металличность}
      />
    </mesh>
  )
}

export default function Ridges() {
  return (
    <>
      {гряды.планы.map((план) => (
        <ПланГряды key={план.расстояние} {...план} />
      ))}
    </>
  )
}
