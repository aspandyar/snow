  /** Коэффициент в формуле round(k · колец · sin θ). Задаёт пропорцию
   *  кирпича: отношение ширины к высоте равно 2/k. Единица даёт кирпич
   *  два к одному, двойка — точный квадрат. Квадрат читается как
   *  мозаика или чешуя, а не как кладка. */
  коэффициент: 1,

  /** Толщина кирпича по нормали, метры. Видна только на отклонённых
   *  кирпичах и в щелях, через которые бьёт внутренний свет. Тоньше —
   *  щели не читаются; толще — сфера выглядит сложенной из брусков. */
  толщина: 0.35,

  /** Шов как доля от размера кирпича. Ноль — кирпичи смыкаются, свет
   *  изнутри наружу не выходит, и весь замысел пропадает. Снизу
   *  ограничен величиной толщина/(2·радиус) = 0.029: ширина считается
   *  на внешней поверхности, а у внутренней грани кирпичи сходятся
   *  теснее и при меньшем шве пересекаются рёбрами. Больше 0.15 —
   *  кладка распадается на россыпь. */
