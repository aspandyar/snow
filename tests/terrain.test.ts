import { describe, expect, it } from 'vitest'

import { вкладДюны, type Дюна } from '@/lib/terrain/height'

// Значения задаются здесь, а не берутся из конфига: иначе тест краснеет
// от безобидной правки числа, которое человек крутит руками.
const дюна: Дюна = { x: 10, z: -4, радиус: 20, высота: 3 }

describe('колокол дюны', () => {
  it('в центре даёт полную высоту', () => {
    expect(вкладДюны(дюна, дюна.x, дюна.z)).toBeCloseTo(дюна.высота, 12)
  })

  it('на границе радиуса даёт ровно ноль', () => {
    expect(вкладДюны(дюна, дюна.x + дюна.радиус, дюна.z)).toBe(0)
  })

  it('за границей даёт РОВНО ноль, а не малую величину', () => {
    // Главный тест задачи. У гауссовой кривой здесь был бы крошечный,
    // но ненулевой хвост: гора в сотне метров приподняла бы землю под
    // сферой сначала на сантиметры, потом на дециметры, и однажды сфера
    // оказалась бы наполовину утопленной в снегу без видимой причины.
    expect(вкладДюны(дюна, дюна.x + дюна.радиус + 0.001, дюна.z)).toBe(0)
    expect(вкладДюны(дюна, дюна.x + 1000, дюна.z)).toBe(0)
    expect(вкладДюны(дюна, дюна.x, дюна.z + 1e6)).toBe(0)
  })

  it('у самой границы вклад пренебрежимо мал — смыкание без излома', () => {
    // Производная колокола на обоих концах равна нулю, поэтому дюна
    // садится на равнину гладко, а не срезанным конусом.
    const почтиГраница = вкладДюны(дюна, дюна.x + дюна.радиус * 0.99, дюна.z)
    expect(почтиГраница).toBeGreaterThan(0)
    expect(почтиГраница).toBeLessThan(дюна.высота * 0.001)
  })

  it('на вершине производная тоже нулевая — пика нет', () => {
    const центр = вкладДюны(дюна, дюна.x, дюна.z)
    const рядом = вкладДюны(дюна, дюна.x + дюна.радиус * 0.01, дюна.z)
    expect(центр - рядом).toBeLessThan(дюна.высота * 0.001)
  })

  it('вклад убывает от центра к краю', () => {
    let предыдущий = Infinity
    for (let доля = 0; доля <= 1; доля += 0.05) {
      const текущий = вкладДюны(дюна, дюна.x + дюна.радиус * доля, дюна.z)
      expect(текущий).toBeLessThanOrEqual(предыдущий)
      предыдущий = текущий
    }
  })
})
