import { describe, expect, it } from 'vitest'
import { Quaternion, Vector3 } from 'three'

import { разложитьКирпичи } from '@/lib/layout/bricks'
import {
  весКирпича,
  доляРаскрытия,
  осьОтъезда,
  осьПроёма,
  отъездОтОси,
  подъёмКирпича,
  поворотОтъезда,
  силаНаведения,
  уголОтОси,
} from '@/lib/opening/aperture'

// Числа здесь свои, а не из конфига: тест обязан ловить ошибку в
// формуле, а не краснеть каждый раз, когда в конфиге подкрутили
// настройку. Значения близки к рабочим, чтобы проверка про
// непересечение кирпичей оставалась осмысленной.
const ЗОНА = 0.95
const ПРОЁМ = 0.55
const ПОДЪЁМ = 3
const РАСКЛАДКА = {
  радиус: 6,
  колец: 28,
  коэффициент: 1,
  толщина: 0.35,
  шов: 0.06,
  смещениеВразбежку: 0.5,
}

describe('осьПроёма', () => {
  it('смотрит из центра сферы наружу, навстречу камере', () => {
    const вход = new Vector3(0.8, -0.1, -0.6).normalize()
    const ось = осьПроёма(вход)
    expect(ось.dot(вход)).toBeCloseTo(-1, 10)
    expect(ось.length()).toBeCloseTo(1, 10)
  })
})

describe('уголОтОси', () => {
  const ось = new Vector3(0, 0, 1)

  it('ноль у самой оси и π напротив', () => {
    expect(уголОтОси(new Vector3(0, 0, 1), ось)).toBeCloseTo(0, 10)
    expect(уголОтОси(new Vector3(0, 0, -1), ось)).toBeCloseTo(Math.PI, 10)
  })

  it('не даёт NaN, когда скалярное произведение чуть вылезает за единицу', () => {
    // Нормализованные векторы дают ровно 1, но накопленная погрешность
    // выдаёт 1.0000000002, и acos от такого — NaN. Кирпич улетел бы в
    // никуда без единой ошибки в консоли.
    const почтиЕдиничный = new Vector3(0, 0, 1.0000000002)
    expect(Number.isNaN(уголОтОси(почтиЕдиничный, ось))).toBe(false)
  })
})

describe('весКирпича', () => {
  it('единица у оси, ноль на краю зоны и дальше', () => {
    expect(весКирпича(0, ЗОНА)).toBe(1)
    expect(весКирпича(ЗОНА, ЗОНА)).toBe(0)
    expect(весКирпича(ЗОНА + 1, ЗОНА)).toBe(0)
  })

  it('убывает линейно — иначе кирпичи у оси сбились бы в пробку', () => {
    expect(весКирпича(ЗОНА / 2, ЗОНА)).toBeCloseTo(0.5, 10)
    expect(весКирпича(ЗОНА / 4, ЗОНА)).toBeCloseTo(0.75, 10)
  })
})

describe('отъездОтОси', () => {
  it('кирпич у оси уезжает на весь радиус проёма', () => {
    expect(отъездОтОси(0, ЗОНА, ПРОЁМ)).toBeCloseTo(ПРОЁМ, 10)
  })

  it('за пределами зоны кладка стоит', () => {
    expect(отъездОтОси(ЗОНА, ЗОНА, ПРОЁМ)).toBe(0)
    expect(отъездОтОси(2, ЗОНА, ПРОЁМ)).toBe(0)
  })

  it('внутри проёма не остаётся ни одного кирпича', () => {
    for (let угол = 0; угол < ЗОНА; угол += 0.01) {
      expect(угол + отъездОтОси(угол, ЗОНА, ПРОЁМ)).toBeGreaterThanOrEqual(ПРОЁМ - 1e-9)
    }
  })

  it('кирпичи не перескакивают друг через друга: углы строго возрастают', () => {
    let прежний = -1
    for (let угол = 0; угол <= ЗОНА; угол += 0.005) {
      const после = угол + отъездОтОси(угол, ЗОНА, ПРОЁМ)
      expect(после).toBeGreaterThan(прежний)
      прежний = после
    }
  })

  it('проём шире зоны выворачивал бы кольца наизнанку', () => {
    // Здесь проверяется САМА ГРАНИЦА применимости, записанная в конфиге:
    // при проёме больше зоны отображение углов перестаёт возрастать.
    const плохойПроём = ЗОНА + 0.2
    const уОси = 0 + отъездОтОси(0, ЗОНА, плохойПроём)
    const уКрая = ЗОНА + отъездОтОси(ЗОНА, ЗОНА, плохойПроём)
    expect(уОси).toBeGreaterThan(уКрая)
  })
})

describe('осьОтъезда', () => {
  const ось = new Vector3(0, 0, 1)

  it('перпендикулярна и оси проёма, и нормали кирпича', () => {
    const нормаль = new Vector3(0.4, 0.3, 0.87).normalize()
    const о = осьОтъезда(new Vector3(), ось, нормаль)
    expect(о.dot(ось)).toBeCloseTo(0, 10)
    expect(о.dot(нормаль)).toBeCloseTo(0, 10)
    expect(о.length()).toBeCloseTo(1, 10)
  })

  it('кирпич ровно на оси всё равно получает направление отъезда', () => {
    // Иначе он остался бы висеть ровно в середине проёма, куда влетает
    // камера.
    const о = осьОтъезда(new Vector3(), ось, ось.clone())
    expect(о.length()).toBeCloseTo(1, 10)
    expect(о.dot(ось)).toBeCloseTo(0, 10)
  })

  it('кирпич ровно напротив оси тоже не ломает вычисление', () => {
    const о = осьОтъезда(new Vector3(), ось, ось.clone().negate())
    expect(о.length()).toBeCloseTo(1, 10)
  })

  it('отъезд УВЕЛИЧИВАЕТ угол от оси, а не уменьшает', () => {
    const нормаль = new Vector3(0.5, 0, 0.866).normalize()
    const о = осьОтъезда(new Vector3(), ось, нормаль)
    const после = нормаль
      .clone()
      .applyQuaternion(поворотОтъезда(new Quaternion(), о, 0.2))
    expect(уголОтОси(после, ось)).toBeGreaterThan(уголОтОси(нормаль, ось))
  })
})

describe('подъёмКирпича', () => {
  it('наибольший у оси, нулевой на краю зоны', () => {
    expect(подъёмКирпича(0, ЗОНА, ПОДЪЁМ)).toBeCloseTo(ПОДЪЁМ, 10)
    expect(подъёмКирпича(ЗОНА, ЗОНА, ПОДЪЁМ)).toBe(0)
  })
})

describe('кирпичи проёма не срастаются', () => {
  // Главная проверка этапа, и она про настоящую раскладку, а не про
  // отдельные формулы. Отъезжая к краю проёма, кирпичи СГУЩАЮТСЯ по
  // меридиану, и без подъёма оказались бы внутри друг друга.
  const кирпичи = разложитьКирпичи(РАСКЛАДКА)
  const ось = осьПроёма(new Vector3(0, 0, -1))

  const развести = (подъём: number) => {
    const о = new Vector3()
    const к = new Quaternion()
    return кирпичи
      .map((кирпич) => {
        const угол = уголОтОси(кирпич.нормаль, ось)
        if (весКирпича(угол, ЗОНА) === 0) return null
        осьОтъезда(о, ось, кирпич.нормаль)
        поворотОтъезда(к, о, отъездОтОси(угол, ЗОНА, ПРОЁМ))
        const точка = кирпич.позиция.clone().applyQuaternion(к)
        const длина = точка.length()
        return точка.multiplyScalar((длина + подъёмКирпича(угол, ЗОНА, подъём)) / длина)
      })
      .filter((т): т is Vector3 => т !== null)
  }

  const наименьшееРасстояние = (точки: Vector3[]) => {
    let наим = Infinity
    for (let i = 0; i < точки.length; i++) {
      for (let j = i + 1; j < точки.length; j++) {
        наим = Math.min(наим, точки[i].distanceTo(точки[j]))
      }
    }
    return наим
  }

  it('в зону попадает пятая часть кладки, а не половина', () => {
    const вЗоне = развести(ПОДЪЁМ).length
    expect(вЗоне / кирпичи.length).toBeGreaterThan(0.1)
    expect(вЗоне / кирпичи.length).toBeLessThan(0.3)
  })

  it('с подъёмом кирпичи стоят дальше своей толщины друг от друга', () => {
    // Толщина, а не высота, и это не поблажка. По меридиану кирпичи
    // после отъезда СТОЯТ ТЕСНЕЕ своей высоты — расходятся они по
    // радиусу, ложась внахлёст как чешуя. Соседние кольца обязаны
    // разойтись хотя бы на толщину, иначе кирпич войдёт в кирпич.
    expect(наименьшееРасстояние(развести(ПОДЪЁМ))).toBeGreaterThan(РАСКЛАДКА.толщина)
  })

  it('без подъёма — срастаются: подъём здесь не украшение', () => {
    expect(наименьшееРасстояние(развести(0))).toBeLessThan(РАСКЛАДКА.толщина)
  })

  it('в самом проёме не остаётся ни одного кирпича', () => {
    const радиусДыры = РАСКЛАДКА.радиус * Math.sin(ПРОЁМ)
    for (const точка of развести(ПОДЪЁМ)) {
      // Расстояние от оси проёма до кирпича, поперёк оси.
      const вдоль = точка.dot(ось)
      const поперёк = точка.clone().addScaledVector(ось, -вдоль).length()
      // Проверяются только кирпичи, оставшиеся на «нашей» стороне сферы:
      // дальняя полусфера к проёму отношения не имеет.
      if (вдоль > 0) expect(поперёк).toBeGreaterThan(радиусДыры * 0.9)
    }
  })
})

describe('доляРаскрытия', () => {
  it('до начала кладка стоит, после конца раскрыта полностью', () => {
    expect(доляРаскрытия(0, 0.58, 0.9)).toBe(0)
    expect(доляРаскрытия(0.57, 0.58, 0.9)).toBe(0)
    expect(доляРаскрытия(0.9, 0.58, 0.9)).toBe(1)
    expect(доляРаскрытия(1, 0.58, 0.9)).toBe(1)
  })

  it('на середине отрезка — ровно половина', () => {
    expect(доляРаскрытия(0.74, 0.58, 0.9)).toBeCloseTo(0.5, 10)
  })

  it('не убывает', () => {
    let прежнее = -1
    for (let i = 0; i <= 100; i++) {
      const текущее = доляРаскрытия(i / 100, 0.58, 0.9)
      expect(текущее).toBeGreaterThanOrEqual(прежнее)
      прежнее = текущее
    }
  })

  it('трогается и останавливается плавно', () => {
    // Скорость сравнивается не с нулём в лоб, а с серединой отрезка: у
    // сглаженного перехода на концах она строго нулевая, но разностная
    // производная с конечным шагом даёт малый остаток.
    const ш = 1e-4
    const скорость = (у: number) =>
      Math.abs(доляРаскрытия(у + ш, 0.58, 0.9) - доляРаскрытия(у, 0.58, 0.9)) / ш
    const вСередине = скорость(0.74)
    expect(скорость(0.58)).toBeLessThan(вСередине / 100)
    expect(скорость(0.9 - ш)).toBeLessThan(вСередине / 100)
  })
})

describe('силаНаведения', () => {
  it('на закрытой сфере курсор работает в полную силу', () => {
    expect(силаНаведения(0)).toBe(1)
  })

  it('на раскрытой не работает вовсе', () => {
    expect(силаНаведения(1)).toBe(0)
  })

  it('гаснет по мере раскрытия', () => {
    expect(силаНаведения(0.25)).toBeGreaterThan(силаНаведения(0.75))
  })
})
