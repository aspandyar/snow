'use client'

import { useLayoutEffect, useRef } from 'react'
import { BackSide } from 'three'
import type { CylinderGeometry } from 'three'

import { горы, материалСнега } from '@/lib/config'
import { профильКольца, type ВершинаКольца } from '@/lib/terrain/height'

type СвойстваКольца = {
  радиус: number
  вершины: ВершинаКольца[]
}

/** Одно кольцо гор: цилиндр без дна и крышки, у которого верхний край
 *  поднят профилем, а нижний утоплен под равнину.
 *
 *  Кольцо, а не плоскость с силуэтом, как было раньше. Плоскости стояли
 *  вдоль одной стороны, и это работало ровно до тех пор, пока камера
 *  смотрела оттуда же. С прокруткой она облетает сферу — и в кадр попадал
 *  открытый край равнины, за которым пусто.
 *
 *  Компонент на кольцо, а не цикл по горы.кольца внутри одного: у
 *  каждого кольца своя геометрия и свой хук её деформации, а хуки нельзя
 *  вызывать в цикле. */
function Кольцо({ радиус, вершины }: СвойстваКольца) {
  const геометрия = useRef<CylinderGeometry>(null)

  useLayoutEffect(() => {
    const г = геометрия.current
    if (!г) return
    const позиции = г.attributes.position

    for (let i = 0; i < позиции.count; i++) {
      const x = позиции.getX(i)
      const z = позиции.getZ(i)
      // Угол берётся из самой вершины, а не из её номера. Номер пришлось
      // бы делить на число сегментов и помнить, что у цилиндра шовная
      // вершина продублирована, — а из координат угол выходит сам, и у
      // обеих половин шва он получается ОДИН И ТОТ ЖЕ. Шва не видно
      // именно поэтому, а не потому, что профиль периодичен (он тоже
      // периодичен, см. профильКольца, но одного этого мало).
      const угол = Math.atan2(x, z)
      // У цилиндра с heightSegments = 1 ровно два ряда вершин: верхний на
      // +высота/2, нижний на −высота/2. Высота задана единицей, так что
      // знак Y и есть признак ряда.
      const y = позиции.getY(i) > 0 ? профильКольца(угол, вершины) : -горы.заглубление
      позиции.setY(i, y)
    }
    позиции.needsUpdate = true

    // Нормали пересчитываются после смещения — иначе кольцо освещается
    // как ровная труба и силуэт гор не читается вовсе.
    г.computeVertexNormals()
  }, [вершины])

  return (
    <mesh>
      {/* Открытый цилиндр: дно и крышка не нужны, мы внутри. Высота
          единица — настоящую высоту вершинам раздаёт профиль выше. */}
      <cylinderGeometry ref={геометрия} args={[радиус, радиус, 1, горы.сегментов, 1, true]} />
      {/* Изнанка: зритель находится ВНУТРИ кольца, и лицевые грани
          цилиндра смотрят от него. Без BackSide кольцо исчезает целиком, и
          это выглядит так, будто компонент не смонтировался.

          Цвет свой, а не снежный, — почему именно, написано у горы.цвет в
          конфиге. Карт нет: подробности на такой дальности не видны. */}
      <meshStandardMaterial
        color={горы.цвет}
        roughness={материалСнега.шероховатость}
        metalness={материалСнега.металличность}
        side={BackSide}
      />
    </mesh>
  )
}

export default function Mountains() {
  return (
    <>
      {горы.кольца.map((кольцо) => (
        <Кольцо key={кольцо.радиус} {...кольцо} />
      ))}
    </>
  )
}
