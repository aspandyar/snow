import { describe, expect, it } from 'vitest'

import { гряды, рельеф } from '@/lib/config'
import {
  создатьВысотуРельефа,
  высотаТумана,
  профильГряды,
  type ПараметрыРельефа,
} from '@/lib/terrain/height'

const параметры: ПараметрыРельефа = {
  зерно: 4242,
  наст: { амплитуда: 0.5, частота: 0.05, октав: 3 },
  дюны: [{ x: 0, z: 0, радиус: 40, высота: 5 }],
}

describe('туман по рельефу', () => {
  const земля = создатьВысотуРельефа(параметры)

  it('отстоит от земли ровно на заданную высоту в любой точке', () => {
    // Плоский лист срезал бы холмы, и дюны торчали бы из тумана,
    // как из воды. Туман обязан повторять рельеф.
    for (const [x, z] of [[0, 0], [15, -22], [-60, 40], [120, 120]]) {
      expect(высотаТумана(земля(x, z), 1.5) - земля(x, z)).toBeCloseTo(1.5, 12)
    }
  })

  it('над дюной поднимается вместе с ней', () => {
    const наДюне = высотаТумана(земля(0, 0), 1.5)
    const вдали = высотаТумана(земля(300, 300), 1.5)
    expect(наДюне).toBeGreaterThan(вдали)
  })
})

describe('профиль гряды', () => {
  const вершины = [
    { x: -40, z: 0, радиус: 60, высота: 18 },
    { x: 50, z: 0, радиус: 45, высота: 12 },
  ]

  it('за пределами всех вершин ровно ноль', () => {
    expect(профильГряды(-300, вершины)).toBe(0)
    expect(профильГряды(400, вершины)).toBe(0)
  })

  it('в вершине даёт её высоту', () => {
    expect(профильГряды(-40, вершины)).toBeCloseTo(18, 6)
  })

  it('перекрывающиеся вершины складываются', () => {
    const рядом = [
      { x: 0, z: 0, радиус: 50, высота: 10 },
      { x: 0, z: 0, радиус: 50, высота: 5 },
    ]
    expect(профильГряды(0, рядом)).toBeCloseTo(15, 6)
  })
})

describe('расстановка гряд', () => {
  it('все гряды стоят за краем равнины', () => {
    // Гряда внутри равнины воткнулась бы в снег и читалась бы не планом,
    // а торчащим из земли куском.
    for (const г of гряды.планы) {
      expect(Math.abs(г.расстояние)).toBeGreaterThan(рельеф.размер / 2)
    }
  })

  it('каждый следующий план дальше предыдущего', () => {
    const расстояния = гряды.планы.map((г) => г.расстояние)
    for (let i = 1; i < расстояния.length; i++) {
      expect(расстояния[i]).toBeGreaterThan(расстояния[i - 1])
    }
  })
})
