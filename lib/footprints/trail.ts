/**
 * Операции над холстом следов. Без React: холст — обычный
 * CanvasRenderingContext2D, эти функции его не создают и не хранят,
 * только рисуют в переданный контекст. Так их можно проверить и
 * переиспользовать отдельно от хука, который владеет холстом.
 */

/** Рисует мягкое пятно под курсором радиальным градиентом.
 *
 *  Градиент, а не заливка круга: резкая граница читалась бы вырезанной
 *  дырой, а не примятым снегом. Пятно рисуется ТЁМНЫМ (чёрным, с
 *  прозрачностью от яркости) — фон холста белый, карта смещения поднимает
 *  вершины по яркости пикселя, и только так тёмное пятно даёт вмятину, а
 *  не бугор. */
export function нарисоватьПятно(
  контекст: CanvasRenderingContext2D,
  x: number,
  y: number,
  радиус: number,
  яркость: number,
): void {
  const градиент = контекст.createRadialGradient(x, y, 0, x, y, радиус)
  градиент.addColorStop(0, `rgba(0, 0, 0, ${яркость})`)
  градиент.addColorStop(1, 'rgba(0, 0, 0, 0)')

  контекст.fillStyle = градиент
  контекст.fillRect(x - радиус, y - радиус, радиус * 2, радиус * 2)
}

/** Гасит полотно: заливает весь холст белым (цвет фона) с малой
 *  прозрачностью. Это и есть весь механизм затухания следа — старые
 *  пятна выцветают сами, кадр за кадром, без таймеров, списка точек и
 *  времени жизни каждого пятна.
 *
 *  Белый цвет заливки не вынесен параметром и не взят из конфига: это не
 *  художественная настройка, а структурная константа — исходный уровень
 *  снега на карте смещения, который по определению равен максимальной
 *  яркости. Настраивать здесь можно только скорость (`затухание`), она и
 *  приходит параметром. */
export function погаситьПолотно(
  контекст: CanvasRenderingContext2D,
  размер: number,
  затухание: number,
): void {
  контекст.fillStyle = `rgba(255, 255, 255, ${затухание})`
  контекст.fillRect(0, 0, размер, размер)
}
