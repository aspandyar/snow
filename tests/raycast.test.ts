import { describe, expect, it } from 'vitest'

import { найтиТочкуНаЗемле } from '@/lib/terrain/raycast'

const п = { шаг: 1.5, дальность: 250, уточнений: 12 }

/** Ровная земля на нуле — простейшая проверяемая поверхность. */
const плоская = () => 0

/** Наклон вдоль X: высота растёт вместе с координатой. */
const наклон = (x: number) => x * 0.1

describe('марш луча по функции высоты', () => {
  it('луч сверху вниз попадает на поверхность', () => {
    const т = найтиТочкуНаЗемле({ x: 0, y: 10, z: 0 }, { x: 0, y: -1, z: 0 }, плоская, п)
    expect(т).not.toBeNull()
    expect(т!.y).toBeCloseTo(0, 3)
  })

  it('найденная точка ЛЕЖИТ на поверхности, а не рядом', () => {
    // Главный тест: если высота найденной точки не совпадает с функцией
    // высоты в ней же, курсор будет мять снег не там, куда показывает.
    const т = найтиТочкуНаЗемле({ x: -20, y: 30, z: 0 }, { x: 0.4, y: -1, z: 0 }, наклон, п)
    expect(т).not.toBeNull()
    expect(т!.y).toBeCloseTo(наклон(т!.x), 2)
  })

  it('луч, направленный от земли, не находит ничего', () => {
    expect(найтиТочкуНаЗемле({ x: 0, y: 5, z: 0 }, { x: 0, y: 1, z: 0 }, плоская, п)).toBeNull()
  })

  it('луч выше поверхности и параллельный ей не находит ничего', () => {
    expect(найтиТочкуНаЗемле({ x: 0, y: 5, z: 0 }, { x: 1, y: 0, z: 0 }, плоская, п)).toBeNull()
  })

  it('луч, начинающийся под землёй, не находит ничего', () => {
    // Иначе камера, случайно оказавшаяся ниже снега, дала бы точку
    // позади себя.
    expect(найтиТочкуНаЗемле({ x: 0, y: -2, z: 0 }, { x: 0, y: -1, z: 0 }, плоская, п)).toBeNull()
  })

  it('число обращений к функции высоты ограничено', () => {
    // Ради этого всё и затевалось: пересечение с геометрией стоило бы
    // триста тысяч проверок треугольников на каждое движение мыши.
    let вызовов = 0
    const считающая = (x: number) => {
      вызовов++
      return наклон(x)
    }
    найтиТочкуНаЗемле({ x: 0, y: 40, z: 0 }, { x: 0, y: -1, z: 0 }, считающая, п)
    expect(вызовов).toBeLessThan(п.дальность / п.шаг + п.уточнений + 5)
  })

  it('не зацикливается при нулевом направлении', () => {
    expect(найтиТочкуНаЗемле({ x: 0, y: 5, z: 0 }, { x: 0, y: 0, z: 0 }, плоская, п)).toBeNull()
  })
})
